def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run the comparative benchmark study using two linear regression models.
    
    One model uses centrality measures from the distance backbone,
    another uses bilateral trade volumes.
    """
    logger.info("Running experiment...")
    
    # Train both models
    logger.info("Training centrality-based model...")
    weights_centralities, bias_centralities, history_centralities = _train_linear_regression(
        data["X_train_centralities"],
        data["y_train_centralities"],
        model["learning_rate"],
        model["max_epochs"],
        model["n_features_centralities"],
        "centralities"
    )
    
    logger.info("Training volume-based model...")
    weights_volumes, bias_volumes, history_volumes = _train_linear_regression(
        data["X_train_volumes"],
        data["y_train_volumes"],
        model["learning_rate"],
        model["max_epochs"],
        model["n_features_volumes"],
        "volumes"
    )
    
    # Make predictions
    y_pred_centralities = [_predict(weights_centralities, bias_centralities, row) for row in data["X_test_centralities"]]
    y_pred_volumes = [_predict(weights_volumes, bias_volumes, row) for row in data["X_test_volumes"]]
    
    # Return results
    return {
        "y_true_centralities": data["y_test_centralities"],
        "y_pred_centralities": y_pred_centralities,
        "y_true_volumes": data["y_test_volumes"],
        "y_pred_volumes": y_pred_volumes,
        "training_history": {
            "centralities": history_centralities,
            "volumes": history_volumes
        }
    }

def _predict(weights: List[float], bias: float, row: List[float]) -> float:
    """Make a prediction using linear regression formula."""
    return bias + sum(w * x for w, x in zip(weights, row))

