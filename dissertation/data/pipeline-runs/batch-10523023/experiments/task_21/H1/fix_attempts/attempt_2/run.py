def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the performance of both models using MAE."""
    logger.info("Evaluating results...")
    
    # Compute MAE for both models
    def compute_mae(y_true: List[float], y_pred: List[float]) -> float:
        if not y_true or not y_pred:
            return float('inf')
        return sum(abs(t - p) for t, p in zip(y_true, y_pred)) / len(y_true)
    
    mae_centralities = compute_mae(experiment_output["y_true_centralities"], experiment_output["y_pred_centralities"])
    mae_volumes = compute_mae(experiment_output["y_true_volumes"], experiment_output["y_pred_volumes"])
    
    # Determine which model performs better
    if mae_centralities < mae_volumes:
        better_model = "centralities"
        worse_model = "volumes"
        improvement = mae_volumes - mae_centralities
        meets = True
        notes = f"Centrality-based model achieved lower MAE ({mae_centralities:.4f}) than volume-based model ({mae_volumes:.4f}). Improvement: {improvement:.4f}"
    elif mae_volumes < mae_centralities:
        better_model = "volumes"
        worse_model = "centralities"
        improvement = mae_centralities - mae_volumes
        meets = False
        notes = f"Volume-based model achieved lower MAE ({mae_volumes:.4f}) than centrality-based model ({mae_centralities:.4f}). Improvement: {improvement:.4f}"
    else:
        better_model = "equal"
        worse_model = "equal"
        improvement = 0.0
        meets = "unknown"
        notes = f"Both models achieved identical MAE ({mae_centralities:.4f})"
    
    # Return evaluation results
    return {
        "mae_centralities": mae_centralities,
        "mae_volumes": mae_volumes,
        "better_model": better_model,
        "worse_model": worse_model,
        "improvement": improvement,
        "meets_success_criteria": meets,
        "success_notes": notes,
        "training_history": experiment_output["training_history"]
    }


