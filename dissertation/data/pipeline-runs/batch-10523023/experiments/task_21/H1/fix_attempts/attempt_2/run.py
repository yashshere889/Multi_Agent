    patience_counter = 0
    history = []
    
    n = len(X)
    
    # Check if we have enough data
    if n == 0:
        logger.warning("No training data available")
        return weights, bias, history
    
    # Training loop
    for epoch in range(max_epochs):
        # Forward pass
        predictions = [_predict(weights, bias, row) for row in X]
        
        # Compute loss (MSE)
        mse = sum((pred - target) ** 2 for pred, target in zip(predictions, y)) / n
        
        # Backward pass (compute gradients)
        grad_w = [0.0] * n_features
        grad_b = 0.0
        for row, target, pred in zip(X, y, predictions):
            error = pred - target
            for i, x in enumerate(row):
                grad_w[i] += error * x
            grad_b += error
            
        # Update weights and bias
        weights = [w - learning_rate * (gw / n) for w, gw in zip(weights, grad_w)]
        bias -= learning_rate * (grad_b / n)
        
        # Log progress
        if (epoch + 1) % CHECKPOINT_EVERY == 0 or epoch + 1 == max_epochs:
            log_progress(epoch=epoch + 1, model=model_name, loss=round(mse, 6))
            history.append(mse)
            
            # Early stopping
            if mse < best_loss:
                best_loss = mse
                patience_counter = 0
            else:
                patience_counter += 1
                
            if patience_counter >= PATIENCE:
                logger.info(f"Early stopping triggered for {model_name} at epoch {epoch + 1}")
                break
                
    logger.info(f"Finished training {model_name} model. Final loss: {mse:.6f}")
    return weights, bias, history


