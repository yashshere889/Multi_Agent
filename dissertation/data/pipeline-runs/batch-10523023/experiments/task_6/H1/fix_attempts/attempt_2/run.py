    results["auc_scores"].append(auc_first)
    results["ece_scores"].append(ece_first)
    results["drifted_features"].append(0)
    
    # Track training history for the first model
    results["training_history"]["slice_0"] = [0.0]  # Placeholder
    
    # Process subsequent time slices
    for i in range(1, model["n_time_slices"]):
        logger.info(f"Processing time slice {i}...")
        
        current_slice = data[i]
        X_current = current_slice.drop('credit_risk', axis=1)
        y_current = current_slice['credit_risk']
        
        # Train new model on current slice
        clf = LogisticRegression(random_state=model["random_seed"], max_iter=1000)
        clf.fit(X_current, y_current)
        
        # Evaluate performance on current slice
        y_prob_current = clf.predict_proba(X_current)[:, 1]
        auc_current = roc_auc_score(y_current, y_prob_current)
        
        # Calculate ECE for current slice
        fraction_of_positives, mean_predicted_value = calibration_curve(y_current, y_prob_current, n_bins=10)
        ece_current = np.mean(np.abs(fraction_of_positives - mean_predicted_value))
        
        # Perform drift detection using Kolmogorov-Smirnov tests
        drifted_count = 0
        if i > 0:
            prev_slice = data[i-1]
            X_prev = prev_slice.drop('credit_risk', axis=1)
            
            # Compare each feature between consecutive slices
            for col in X_current.columns:
                if col in X_prev.columns:
                    ks_stat, p_val = ks_2samp(X_current[col], X_prev[col])
                    if p_val < model["ks_threshold"]:
                        drifted_count += 1
        
        # Store results
        results["time_slice"].append(i)
        results["auc_scores"].append(auc_current)
        results["ece_scores"].append(ece_current)
        results["drifted_features"].append(drifted_count)
        
        # Store training history (placeholder since we're not tracking per-epoch loss)
        results["training_history"][f"slice_{i}"] = [0.0]  # Placeholder
    
    logger.info("Longitudinal experiment completed.")
    return results


