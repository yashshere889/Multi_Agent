def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experiment results against the success criteria."""
    logger.info("Evaluating experiment results...")
    
    # Extract metrics
    time_slices = experiment_output["time_slice"]
    auc_scores = experiment_output["auc_scores"]
    ece_scores = experiment_output["ece_scores"]
    drifted_features = experiment_output["drifted_features"]
    
    # Calculate slopes for trend analysis
    if len(auc_scores) >= 2:
        # Slope of AUC (negative slope means decreasing AUC)
        auc_slope = (auc_scores[-1] - auc_scores[0]) / (time_slices[-1] - time_slices[0])
        
        # Slope of ECE (positive slope means increasing ECE)
        ece_slope = (ece_scores[-1] - ece_scores[0]) / (time_slices[-1] - time_slices[0])
        
        # Determine if calibration degrades faster than ranking discrimination
        # If ECE slope is more positive than AUC slope (more negative), then 
        # calibration degrades faster
        if abs(ece_slope) > abs(auc_slope):
            meets_criteria = True
            reason = "Calibration error (ECE) deteriorates faster than ranking discrimination (AUC) over time."
        elif abs(ece_slope) < abs(auc_slope):
            meets_criteria = False
            reason = "Ranking discrimination (AUC) deteriorates faster than calibration error (ECE) over time."
        else:
            meets_criteria = "unknown"
            reason = "Both metrics show similar rates of change over time."
    else:
        meets_criteria = "unknown"
        reason = "Insufficient data points to compute meaningful slopes."
    
    # Prepare evaluation results
    eval_results = {
        "auc_scores": auc_scores,
        "ece_scores": ece_scores,
        "drifted_features": drifted_features,
        "auc_slope": auc_slope if 'auc_slope' in locals() else None,
        "ece_slope": ece_slope if 'ece_slope' in locals() else None,
        "meets_success_criteria": meets_criteria,
        "success_notes": reason
    }
    
    logger.info("Evaluation completed.")
    return eval_results


