def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run experiments comparing performance with and without augmentation."""
    
    # Define augmentation techniques
    def time_warping(X, y, factor=0.1):
        """Apply time warping to temporal features."""
        # Only apply to numeric features (duration_months, credit_amount, age_years)
        numeric_indices = [i for i, name in enumerate(data["feature_names"]) 
                          if any(col in name for col in ['duration_months', 'credit_amount', 'age_years'])]
        
        X_aug = X.copy().astype(float)
        for idx in numeric_indices:
            noise = np.random.normal(0, factor * np.std(X[:, idx]), size=X.shape[0])
            X_aug[:, idx] = X[:, idx] + noise
            # Ensure non-negative values for duration and amount
            if idx in [0, 2]:  # duration_months and credit_amount
                X_aug[:, idx] = np.maximum(X_aug[:, idx], 0)
        return X_aug, y
    
    def jittering(X, y, factor=0.05):
        """Add jittering to temporal features."""
        numeric_indices = [i for i, name in enumerate(data["feature_names"]) 
                          if any(col in name for col in ['duration_months', 'credit_amount', 'age_years'])]
        
        X_aug = X.copy().astype(float)
        for idx in numeric_indices:
            noise = np.random.normal(0, factor * np.std(X[:, idx]), size=X.shape[0])
            X_aug[:, idx] = X[:, idx] + noise
            # Ensure non-negative values for duration and amount
            if idx in [0, 2]:  # duration_months and credit_amount
                X_aug[:, idx] = np.maximum(X_aug[:, idx], 0)
        return X_aug, y
    
    def smote(X, y, k=5):
        """Simple SMOTE implementation for balancing classes."""
        # Simple oversampling of minority class
        minority_indices = np.where(y == 1)[0]
        majority_indices = np.where(y == 0)[0]
        
        if len(minority_indices) == 0 or len(majority_indices) == 0:
            return X, y
            
        n_minority = len(minority_indices)
        n_majority = len(majority_indices)
        
        # Calculate how many samples to generate
        n_to_generate = n_majority - n_minority
        
        if n_to_generate <= 0:
            return X, y
            
        # Generate synthetic samples by copying minority samples
        synthetic_indices = np.random.choice(minority_indices, size=n_to_generate, replace=True)
        X_synthetic = X[synthetic_indices]
        y_synthetic = y[synthetic_indices]
        
        X_aug = np.vstack([X, X_synthetic])
        y_aug = np.hstack([y, y_synthetic])
        
        return X_aug, y_aug
    
