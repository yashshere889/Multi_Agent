def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experiment results against success criteria."""
    
    # Extract gains
    gains = experiment_output["gains"]
    
    # Calculate average gain differences across all methods
    avg_gain_diff = np.mean([g["gain_difference"] for g in gains.values()])
    
    # Check if the drop in performance gain is at least 20%
    # We consider the drop to be significant if it's at least 0.2 (20%)
    meets_criteria = avg_gain_diff <= -0.2
    
    # Prepare detailed notes
    notes_parts = [
        f"Average performance gain difference across augmentation methods: {avg_gain_diff:.3f}",
        f"Baseline accuracy (random split): {experiment_output['baseline_random']['accuracy']:.3f}",
        f"Baseline accuracy (temporal split): {experiment_output['baseline_temporal']['accuracy']:.3f}"
    ]
    
    for method, gain_info in gains.items():
        notes_parts.append(
            f"{method}: gain_random={gain_info['gain_random']:.3f}, "
            f"gain_temporal={gain_info['gain_temporal']:.3f}, "
            f"difference={gain_info['gain_difference']:.3f}"
        )
    
    success_notes = "; ".join(notes_parts)
    
    return {
        "accuracy": experiment_output["baseline_random"]["accuracy"],
        "f1": experiment_output["baseline_random"]["f1"],
        "average_gain_difference": avg_gain_diff,
        "meets_success_criteria": meets_criteria,
        "success_notes": success_notes
    }


