def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run the experiment comparing static vs regime-aware momentum strategies."""
    features = data["features"]
    returns = data["returns"]
    dates = data["dates"]
    
    # Fit clustering model
    clustering_model = model["clustering_model"]
    cluster_assignments = clustering_model.fit_predict(features)
    
    # Split data into train and test sets (using temporal split)
    split_idx = int(len(returns) * TRAIN_TEST_SPLIT)
    train_features = features[:split_idx]
    test_features = features[split_idx:]
    train_returns = returns[:split_idx]
    test_returns = returns[split_idx:]
    train_dates = dates[:split_idx]
    test_dates = dates[split_idx:]
    train_assignments = cluster_assignments[:split_idx]
    test_assignments = cluster_assignments[split_idx:]
    
    # Backtest static momentum strategy
    static_strategy_returns = _backtest_momentum_strategy(train_returns, test_returns, test_assignments, 
                                                         train_assignments, test_features, train_features, 
                                                         LOOKBACK_PERIOD, REBALANCE_FREQ, False)
    
    # Backtest regime-aware momentum strategy
    regime_aware_strategy_returns = _backtest_momentum_strategy(train_returns, test_returns, test_assignments, 
                                                               train_assignments, test_features, train_features, 
                                                               LOOKBACK_PERIOD, REBALANCE_FREQ, True)
    
    return {
        "static_strategy_returns": static_strategy_returns,
        "regime_aware_strategy_returns": regime_aware_strategy_returns,
        "cluster_assignments": cluster_assignments,
        "test_assignments": test_assignments,
        "test_dates": test_dates,
        "test_returns": test_returns
    }

def _backtest_momentum_strategy(train_returns, test_returns, test_assignments, 
                               train_assignments, test_features, train_features, 
                               lookback_period, rebalance_freq, regime_aware):
    """Backtest a momentum strategy with optional regime awareness."""
    # For simplicity, we'll use a basic momentum approach:
    # - Look back over a period (e.g., 3 months) to compute average returns
    # - Rank assets (here just SP500) by their recent performance
    # - Go long the top performing asset and short the bottom performing asset
    
    # In this case, we'll treat the entire S&P 500 as one asset
    # and compute momentum based on recent returns
    
    strategy_returns = []
    
    # For regime-aware strategy, we adjust weights based on market regime
    regime_weights = {}
    if regime_aware:
        # Assign weights to each regime (e.g., bullish = 1.0, bearish = 0.5, neutral = 0.75)
        unique_clusters = np.unique(train_assignments)
        for i, cluster in enumerate(unique_clusters):
            # Simple heuristic: assign higher weight to more positive regimes
            # This is a placeholder - in practice, you'd want to learn these weights
            if i == 0:  # Assume first cluster is bullish
                regime_weights[cluster] = 1.0
            elif i == 1:  # Second cluster is bearish
                regime_weights[cluster] = 0.5
            else:  # Others are neutral or mixed
                regime_weights[cluster] = 0.75
    
    # Compute momentum signals and returns
    lookback_days = int(lookback_period * 21)  # Approximate trading days per month
    
    for i in range(lookback_days, len(test_returns)):
        # Get recent returns for momentum calculation
        recent_returns = test_returns[i - lookback_days:i]
        
        # Compute momentum score (simple average return)
        momentum_score = np.mean(recent_returns)
        
        # Determine current regime
        current_regime = test_assignments[i]
        
        # Apply regime-specific weight if applicable
        weight = regime_weights.get(current_regime, 1.0) if regime_aware else 1.0
        
        # Simple strategy: go long if momentum is positive, short if negative
        # Adjust position size based on regime weight
        if momentum_score > 0:
            position_return = test_returns[i] * weight
        else:
            position_return = -test_returns[i] * weight
            
        strategy_returns.append(position_return)
    
    return strategy_returns


