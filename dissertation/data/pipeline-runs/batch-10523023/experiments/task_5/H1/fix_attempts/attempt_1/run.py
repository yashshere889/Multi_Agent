def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the performance of both strategies using Sharpe ratio and other metrics."""
    
    static_returns = experiment_output["static_strategy_returns"]
    regime_aware_returns = experiment_output["regime_aware_strategy_returns"]
    
    # Risk-free rate (annualized)
    risk_free_rate = 0.02
    
    # Calculate Sharpe ratios
    def calculate_sharpe_ratio(returns, risk_free_rate):
        if len(returns) == 0:
            return 0.0
        excess_returns = np.array(returns) - risk_free_rate / 252  # Daily risk-free rate
        sharpe = np.mean(excess_returns) / np.std(excess_returns) * np.sqrt(252)
        return sharpe
    
    static_sharpe = calculate_sharpe_ratio(static_returns, risk_free_rate)
    regime_aware_sharpe = calculate_sharpe_ratio(regime_aware_returns, risk_free_rate)
    
    # Calculate annualized returns
    def calculate_annualized_return(returns):
        if len(returns) == 0:
            return 0.0
        total_return = np.prod([1 + r for r in returns])
        annualized_return = (total_return ** (252 / len(returns))) - 1
        return annualized_return
    
    static_return = calculate_annualized_return(static_returns)
    regime_aware_return = calculate_annualized_return(regime_aware_returns)
    
    # Calculate maximum drawdown
    def calculate_max_drawdown(returns):
        if len(returns) == 0:
            return 0.0
        cumulative_returns = np.cumprod([1 + r for r in returns])
        running_max = np.maximum.accumulate(cumulative_returns)
        drawdown = (cumulative_returns - running_max) / running_max
        return np.min(drawdown)
    
    static_drawdown = calculate_max_drawdown(static_returns)
    regime_aware_drawdown = calculate_max_drawdown(regime_aware_returns)
    
    # Compare strategies
    better_strategy = "regime_aware" if regime_aware_sharpe > static_sharpe else "static"
    meets_success_criteria = regime_aware_sharpe > static_sharpe
    
    return {
        "static_sharpe": static_sharpe,
        "regime_aware_sharpe": regime_aware_sharpe,
        "static_return": static_return,
        "regime_aware_return": regime_aware_return,
        "static_drawdown": static_drawdown,
        "regime_aware_drawdown": regime_aware_drawdown,
        "better_strategy": better_strategy,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": f"Static strategy Sharpe: {static_sharpe:.4f}, Regime-aware strategy Sharpe: {regime_aware_sharpe:.4f}. "
                         f"{'Hypothesis supported' if meets_success_criteria else 'Hypothesis refuted'}."
    }


