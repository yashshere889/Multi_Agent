def build_model(data: Any) -> Any:
    """Build the spectral clustering model with optimal number of clusters."""
    features = data["features"]
    
    # Determine optimal number of clusters using silhouette analysis
    best_silhouette = -1
    best_n_clusters = 3
    
    for n_clusters in range(CLUSTER_RANGE[0], CLUSTER_RANGE[1] + 1):
        clustering = SpectralClustering(n_clusters=n_clusters, random_state=RANDOM_SEED, affinity='rbf', gamma=0.1)
        cluster_labels = clustering.fit_predict(features)
        
        # Calculate silhouette score
        silhouette_avg = silhouette_score(features, cluster_labels)
        
        if silhouette_avg > best_silhouette:
            best_silhouette = silhouette_avg
            best_n_clusters = n_clusters
    
    # Create final clustering model with optimal number of clusters
    final_clustering = SpectralClustering(n_clusters=best_n_clusters, random_state=RANDOM_SEED, affinity='rbf', gamma=0.1)
    
    return {
        "clustering_model": final_clustering,
        "n_clusters": best_n_clusters,
        "silhouette_score": best_silhouette
    }


