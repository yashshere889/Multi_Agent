def run_sampling_protocol(X_train_full, y_train_full, X_val, y_val, X_test, y_test, 
                         strategy, model, scaler):
    """Run either random or active learning sampling protocol."""
    
    # Start with a small initial training set
    indices = list(range(len(X_train_full)))
    initial_indices = random.sample(indices, INITIAL_TRAIN_SIZE)
    X_train_current = X_train_full[initial_indices]
    y_train_current = y_train_full[initial_indices]
    
    # Track training history
    training_history = []
    
    # Keep track of selected indices
    selected_indices = set(initial_indices)
    
    # Training loop
    for iteration in range(MAX_ITERATIONS):
        # Fit the model
        gp_model = build_model(None)  # Rebuild model each time
        gp_model.fit(X_train_current, y_train_current)
        
        # Evaluate on validation set
        y_pred_val = gp_model.predict(X_val)
        mse_val = mean_squared_error(y_val, y_pred_val)
        training_history.append(mse_val)
        
        # Check for convergence
        if len(training_history) > PATIENCE:
            recent_losses = training_history[-PATIENCE:]
            if all(loss <= CONVERGENCE_THRESHOLD for loss in recent_losses):
                break
                
        # If we've used all data, break
        if len(selected_indices) >= len(X_train_full):
            break
            
        # Select next sample based on strategy
        if strategy == "random":
            # Random sampling
            available_indices = [i for i in indices if i not in selected_indices]
            if not available_indices:
                break
            next_index = random.choice(available_indices)
        else:
            # Active learning with uncertainty sampling
            # Predict on remaining data
            available_indices = [i for i in indices if i not in selected_indices]
            X_available = X_train_full[available_indices]
            
            # Get predictive variances
            _, variances = gp_model.predict(X_available, return_std=True)
            
            # Select index with highest variance (most uncertain)
            max_variance_idx = np.argmax(variances)
            next_index = available_indices[max_variance_idx]
            
        # Add the selected sample to training set
        selected_indices.add(next_index)
        X_train_current = np.vstack([X_train_current, X_train_full[next_index]])
        y_train_current = np.hstack([y_train_current, y_train_full[next_index]])
        
    # Final evaluation on test set
    final_gp_model = build_model(None)
    final_gp_model.fit(X_train_current, y_train_current)
    y_pred_test = final_gp_model.predict(X_test)
    final_mse = mean_squared_error(y_test, y_pred_test)
    
    return {
        "simulations_needed": len(selected_indices),
        "final_mse": final_mse,
        "training_history": training_history
    }


