def build_model(data: Any) -> Any:
    """Build the Gaussian Process Regression model with appropriate kernel."""
    # Define the kernel: RBF with WhiteKernel for noise modeling
    kernel = RBF(length_scale=1.0) + WhiteKernel(noise_level=1e-5)
    
    # Create the Gaussian Process Regressor
