def run_sampling_protocol(X_train_full, y_train_full, X_val, y_val, 
                         full_indices, strategy, initial_size, max_iterations):
    """Run a single sampling protocol (random or active)."""
    logger = logging.getLogger(__name__)
    
    # Start with initial training set
    train_indices = random.sample(full_indices, initial_size)
    X_train_subset = X_train_full[train_indices]
    y_train_subset = y_train_full[train_indices]
    
    # Track simulations needed
    simulations_needed = initial_size
    
    # Validation MSE tracking
    prev_mse = float('inf')
    
    # Main loop
    for iteration in range(max_iterations):
        # Train model
        gp_model = GaussianProcessRegressor(
            kernel=RBF(length_scale=1.0) + WhiteKernel(noise_level=1.0),
            alpha=1e-6,
            normalize_y=True,
            n_restarts_optimizer=10,
            random_state=RANDOM_SEED
        )
        gp_model.fit(X_train_subset, y_train_subset)
        
        # Check for convergence
        y_val_pred = gp_model.predict(X_val)
        current_mse = mean_squared_error(y_val, y_val_pred)
        
        if abs(prev_mse - current_mse) < CONVERGENCE_THRESHOLD:
            break
            
        prev_mse = current_mse
        
        # Select next sample based on strategy
        if strategy == "random":
            # Random sampling
            available_indices = [i for i in full_indices if i not in train_indices]
            next_idx = random.choice(available_indices)
        else:
            # Active learning with uncertainty sampling
            available_indices = [i for i in full_indices if i not in train_indices]
            
            # Predict on available samples
            X_available = X_train_full[available_indices]
            predictions, stds = gp_model.predict(X_available, return_std=True)
            
            # Select sample with highest uncertainty (highest standard deviation)
            next_idx = available_indices[np.argmax(stds)]
        
        # Add selected sample to training set
        train_indices.append(next_idx)
        X_train_subset = X_train_full[train_indices]
        y_train_subset = y_train_full[train_indices]
        
        simulations_needed += 1
        
        # Safety check to prevent infinite loops
        if len(train_indices) >= len(full_indices):
            break
    
    # Final model training and evaluation
    gp_model.fit(X_train_subset, y_train_subset)
    y_val_pred = gp_model.predict(X_val)
    final_mse = mean_squared_error(y_val, y_val_pred)
    
    # Get final predictions for evaluation
    y_test_pred = gp_model.predict(X_train_full[train_indices])
    
    return {
        "simulations_needed": simulations_needed,
        "final_mse": final_mse,
        "final_predictions": y_test_pred.tolist(),
        "final_targets": y_train_full[train_indices].tolist()
    }


