def load_data() -> Any:
    """Load and preprocess the AG News dataset according to the specified requirements."""
    logger.info("Loading training data...")
    
    # Load training data
    train_path = "/mnt/fastscratch/users/sgyshere/coder-data/ag_news_document_text_category_classification_train.csv"
    test_path = "/mnt/fastscratch/users/sgyshere/coder-data/ag_news_document_text_category_classification_test.csv"
    
    try:
        train_df = pd.read_csv(train_path)
        test_df = pd.read_csv(test_path)
    except Exception as e:
        logger.error(f"Failed to load data files: {e}")
        raise
    
    # Normalize whitespace in text column
    train_df['text'] = train_df['text'].str.replace(r'\s+', ' ', regex=True).str.strip()
    test_df['text'] = test_df['text'].str.replace(r'\s+', ' ', regex=True).str.strip()
    
    # Map integer labels to category names
    label_map = {0: 'World', 1: 'Sports', 2: 'Business', 3: 'Sci/Tech'}
    train_df['label_name'] = train_df['label'].map(label_map)
    test_df['label_name'] = test_df['label'].map(label_map)
    
    # Split training data into 5 folds for cross-validation
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_SEED)
    train_folds = []
    for fold, (train_idx, val_idx) in enumerate(skf.split(train_df['text'], train_df['label'])):
        train_fold = train_df.iloc[train_idx].copy()
        val_fold = train_df.iloc[val_idx].copy()
        train_folds.append((train_fold, val_fold))
    
    return {
        "train_data": train_df,
        "test_data": test_df,
        "train_folds": train_folds,
        "labels": ['World', 'Sports', 'Business', 'Sci/Tech'],
        "label_to_id": {'World': 0, 'Sports': 1, 'Business': 2, 'Sci/Tech': 3}
    }


