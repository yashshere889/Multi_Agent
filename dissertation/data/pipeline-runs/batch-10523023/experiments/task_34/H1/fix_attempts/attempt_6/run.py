def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run fivefold cross-validation and test set evaluation."""
    logger.info("Starting experiment execution...")
    
    # Initialize storage for results
    cv_results = []
    test_results = []
    cv_predictions = {}
    test_predictions = {}
    
    # Prepare data
    train_df = data["train_data"]
    test_df = data["test_data"]
    
    # Fit vectorizer on entire training set for consistency
    all_texts = list(train_df['text']) + list(test_df['text'])
    model["vectorizer"].fit(all_texts)
    
    # Perform 5-fold cross-validation
    logger.info("Performing 5-fold cross-validation...")
    for fold_idx, (train_fold, val_fold) in enumerate(data["train_folds"]):
        logger.info(f"Processing fold {fold_idx + 1}/5")
        
        # Vectorize
        X_train = model["vectorizer"].transform(train_fold['text'])
        X_val = model["vectorizer"].transform(val_fold['text'])
        
        # Train classifier
        y_train = train_fold['label']
        y_val = val_fold['label']
        
        clf = LogisticRegression(random_state=RANDOM_SEED, max_iter=250)
        clf.fit(X_train, y_train)
        
        # Predictions
        y_pred = clf.predict(X_val)
        y_pred_proba = clf.predict_proba(X_val)
        
        # Store predictions for later analysis
        cv_predictions[fold_idx] = {
            'y_true': list(y_val),
            'y_pred': list(y_pred),
            'y_pred_proba': y_pred_proba.tolist()
        }
        
        # Calculate metrics
        accuracy = accuracy_score(y_val, y_pred)
        f1 = f1_score(y_val, y_pred, average='weighted')
        
        cv_results.append({
            'fold': fold_idx,
            'accuracy': accuracy,
            'f1': f1
        })
        
        # Store model for later use
        model["models"].append(clf)
    
    # Evaluate on test set using the last trained model (or average all models)
    logger.info("Evaluating on test set...")
    X_test = model["vectorizer"].transform(test_df['text'])
    y_test = test_df['label']
    
    # Use the last trained model for simplicity
    if model["models"]:
        clf = model["models"][-1]
        y_test_pred = clf.predict(X_test)
        y_test_pred_proba = clf.predict_proba(X_test)
        
        test_accuracy = accuracy_score(y_test, y_test_pred)
        test_f1 = f1_score(y_test, y_test_pred, average='weighted')
        
        test_predictions = {
            'y_true': list(y_test),
            'y_pred': list(y_test_pred),
            'y_pred_proba': y_test_pred_proba.tolist()
        }
        
        test_results.append({
            'accuracy': test_accuracy,
            'f1': test_f1
        })
    
    # Aggregate CV results
    avg_cv_accuracy = np.mean([r['accuracy'] for r in cv_results])
    avg_cv_f1 = np.mean([r['f1'] for r in cv_results])
    
    # Create rankings
    model_rankings = {
        'cv_accuracy': avg_cv_accuracy,
        'cv_f1': avg_cv_f1,
        'test_accuracy': test_results[0]['accuracy'] if test_results else 0,
        'test_f1': test_results[0]['f1'] if test_results else 0
    }
    
    # Return everything needed for evaluation
    return {
        "cv_results": cv_results,
        "test_results": test_results,
        "cv_predictions": cv_predictions,
        "test_predictions": test_predictions,
        "model_rankings": model_rankings
    }


