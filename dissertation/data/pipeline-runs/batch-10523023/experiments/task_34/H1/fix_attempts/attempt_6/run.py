def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experiment results and determine if hypothesis is supported."""
    logger.info("Evaluating experiment results...")
    
    # Extract rankings
    rankings = experiment_output["model_rankings"]
    
    # Create two ranking lists: one for CV and one for test
    # Using accuracy and F1 scores for both CV and test
    cv_ranking = [rankings['cv_accuracy'], rankings['cv_f1']]
    test_ranking = [rankings['test_accuracy'], rankings['test_f1']]
    
    # Check for valid data before computing correlation
    if len(cv_ranking) != len(test_ranking):
        logger.error("Mismatch in ranking lengths for correlation calculation")
        return {
            "spearman_correlation": float('nan'),
            "p_value": float('nan'),
            "meets_success_criteria": False,
            "success_notes": "Invalid ranking data for correlation computation."
        }
    
    # Check for constant values that would cause spearmanr to fail
    if np.allclose(cv_ranking, cv_ranking[0]) or np.allclose(test_ranking, test_ranking[0]):
        logger.warning("Constant values in rankings, cannot compute meaningful correlation")
        return {
            "spearman_correlation": float('nan'),
            "p_value": float('nan'),
            "meets_success_criteria": False,
            "success_notes": "Constant ranking values prevent meaningful correlation computation."
        }
    
    # Calculate Spearman correlation with explicit error handling
    try:
        # Ensure we have numeric data
        cv_array = np.array(cv_ranking, dtype=float)
        test_array = np.array(test_ranking, dtype=float)
        
        # Check for any non-numeric values
        if not np.isfinite(cv_array).all() or not np.isfinite(test_array).all():
            logger.error("Non-finite values found in rankings")
            return {
                "spearman_correlation": float('nan'),
                "p_value": float('nan'),
                "meets_success_criteria": False,
                "success_notes": "Non-finite values in rankings prevent correlation computation."
            }
        
        # Check if arrays have sufficient variation
        if np.std(cv_array) == 0 or np.std(test_array) == 0:
            logger.warning("Zero variance in one or both ranking arrays")
            return {
                "spearman_correlation": float('nan'),
                "p_value": float('nan'),
                "meets_success_criteria": False,
                "success_notes": "Zero variance in rankings prevents meaningful correlation."
            }
        
        # Check if we have enough data points
        if len(cv_array) < 2 or len(test_array) < 2:
            logger.error("Insufficient data points for correlation calculation")
            return {
                "spearman_correlation": float('nan'),
                "p_value": float('nan'),
                "meets_success_criteria": False,
                "success_notes": "Insufficient data points for correlation computation."
            }
        
        # Perform Spearman correlation
        correlation, p_value = spearmanr(cv_array, test_array)
        
        # Explicitly check for NaN results
        if np.isnan(correlation) or np.isnan(p_value):
            logger.error("Spearman correlation computation resulted in NaN values")
            return {
                "spearman_correlation": float('nan'),
                "p_value": float('nan'),
                "meets_success_criteria": False,
                "success_notes": "Computed correlation is NaN due to insufficient variation in rankings."
            }
            
    except Exception as e:
        logger.error(f"Error computing Spearman correlation: {e}")
        return {
            "spearman_correlation": float('nan'),
            "p_value": float('nan'),
            "meets_success_criteria": False,
            "success_notes": f"Correlation computation failed: {str(e)}"
        }
    
    # Determine if hypothesis is supported
    meets_success_criteria = correlation < 0.7
    
    # Prepare return dictionary
    result = {
        "spearman_correlation": float(correlation),
        "p_value": float(p_value),
        "meets_success_criteria": meets_success_criteria,
        "success_notes": (
            f"Spearman rank correlation between CV and test set rankings is {correlation:.3f}. "
            f"This {'supports' if meets_success_criteria else 'does not support'} the hypothesis "
            f"that model performance rankings differ significantly (correlation < 0.7)."
        )
    }
    
    return result


