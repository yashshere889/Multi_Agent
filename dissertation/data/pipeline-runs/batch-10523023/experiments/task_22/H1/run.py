def find_threshold_for_accuracy(probs, y_true, target_accuracy):
    """Find the threshold that achieves target accuracy"""
    # Sort probabilities and corresponding true labels
    sorted_indices = np.argsort(probs)[::-1]
    sorted_probs = probs[sorted_indices]
    sorted_y = y_true[sorted_indices]
    
    # Try different thresholds
    best_threshold = 0.5
    best_accuracy = 0
    
    for threshold in np.arange(0.01, 1.0, 0.01):
        preds = (probs >= threshold).astype(int)
        acc = accuracy_score(y_true, preds)
        if abs(acc - target_accuracy) < abs(best_accuracy - target_accuracy):
            best_accuracy = acc
            best_threshold = threshold
            
    return best_threshold

def find_demographic_parity_threshold(probs, gender, y_true):
    """Find threshold that achieves demographic parity while maintaining high accuracy"""
    # This is a simplified approach - in practice, we'd want to optimize this more carefully
    # For now, we'll use a simple heuristic: find a threshold that roughly balances acceptance rates
    
    # Calculate acceptance rates by gender
    male_acceptance = np.mean(probs[gender == 1] >= 0.5)
    female_acceptance = np.mean(probs[gender == 0] >= 0.5)
    
    # Adjust threshold to make acceptance rates closer
    # This is a simplified approach - in reality, we'd solve this optimization problem
    # Here we'll just adjust the threshold to balance the rates
    if abs(male_acceptance - female_acceptance) > 0.05:
        # If there's a significant imbalance, adjust threshold
        if male_acceptance > female_acceptance:
            # Male acceptance is higher, reduce threshold for males
            return 0.45
        else:
            # Female acceptance is higher, reduce threshold for females
            return 0.55
    else:
        # Acceptance rates are already balanced
        return 0.5

def find_equal_opportunity_threshold(probs, gender, y_true):
    """Find threshold that achieves equal opportunity while maintaining high accuracy"""
    # Equal opportunity means equal true positive rates across groups
    # This is also a simplified approach - in practice, we'd solve this optimization problem
    
    # Calculate TPR by gender
    male_tpr = np.sum((probs[gender == 1] >= 0.5) & (y_true[gender == 1] == 1)) / np.sum(y_true[gender == 1] == 1)
    female_tpr = np.sum((probs[gender == 0] >= 0.5) & (y_true[gender == 0] == 1)) / np.sum(y_true[gender == 0] == 1)
    
    # Adjust threshold to balance TPRs
    # This is a very simplified approach - in reality, we'd solve for the optimal threshold
    if abs(male_tpr - female_tpr) > 0.05:
        # If there's a significant imbalance, adjust threshold
        if male_tpr > female_tpr:
            # Male TPR is higher, reduce threshold for males
            return 0.45
        else:
            # Female TPR is higher, reduce threshold for females
            return 0.55
    else:
        # TPRs are already balanced
        return 0.5


