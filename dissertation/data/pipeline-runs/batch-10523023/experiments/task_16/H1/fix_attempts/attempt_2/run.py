def run_experiment(data: Any, model_config: Any) -> dict[str, Any]:
    """Train both TFT models and generate forecasts."""
    logger = logging.getLogger(__name__)
    
    # Set random seed for reproducibility
    torch.manual_seed(42)
    np.random.seed(42)
    
    # Get models and data loaders
    model_hourly = model_config["model_hourly"]
    model_15min = model_config["model_15min"]
    
    train_loader_hourly = model_config["train_loader_hourly"]
    val_loader_hourly = model_config["val_loader_hourly"]
    test_loader_hourly = model_config["test_loader_hourly"]
    
    train_loader_15min = model_config["train_loader_15min"]
    val_loader_15min = model_config["val_loader_15min"]
    test_loader_15min = model_config["test_loader_15min"]
    
    # Optimizers
    optimizer_hourly = optim.Adam(model_hourly.parameters(), lr=LEARNING_RATE)
    optimizer_15min = optim.Adam(model_15min.parameters(), lr=LEARNING_RATE)
    
    # Loss function
    criterion = nn.L1Loss()  # Using MAE as requested
    
    # Training function
    def train_model(model, train_loader, val_loader, optimizer, epochs, patience):
        best_val_loss = float('inf')
        patience_counter = 0
        train_losses = []
        val_losses = []
        
        for epoch in range(epochs):
            # Training phase
            model.train()
            total_train_loss = 0
            for batch_x, batch_y in train_loader:
                optimizer.zero_grad()
                outputs = model(batch_x)
                loss = criterion(outputs, batch_y)
                loss.backward()
                optimizer.step()
                total_train_loss += loss.item()
            
            avg_train_loss = total_train_loss / len(train_loader)
            train_losses.append(avg_train_loss)
            
            # Validation phase
            model.eval()
            total_val_loss = 0
            with torch.no_grad():
                for batch_x, batch_y in val_loader:
                    outputs = model(batch_x)
                    loss = criterion(outputs, batch_y)
                    total_val_loss += loss.item()
            
            avg_val_loss = total_val_loss / len(val_loader)
            val_losses.append(avg_val_loss)
            
            # Early stopping
            if avg_val_loss < best_val_loss:
                best_val_loss = avg_val_loss
                patience_counter = 0
                # Save best model state
                best_model_state = model.state_dict().copy()
            else:
                patience_counter += 1
                if patience_counter >= patience:
                    logger.info(f"Early stopping at epoch {epoch+1}")
                    break
                    
        # Load best model weights
        model.load_state_dict(best_model_state)
        
        return train_losses, val_losses
    
    # Train both models
    logger.info("Training hourly resolution model...")
    train_losses_hourly, val_losses_hourly = train_model(
        model_hourly, train_loader_hourly, val_loader_hourly, 
        optimizer_hourly, EPOCHS, PATIENCE
    )
    
    logger.info("Training 15-minute resolution model...")
    train_losses_15min, val_losses_15min = train_model(
        model_15min, train_loader_15min, val_loader_15min, 
        optimizer_15min, EPOCHS, PATIENCE
    )
    
    # Generate forecasts for test sets
    def generate_forecasts(model, test_loader):
        model.eval()
        all_predictions = []
        all_targets = []
        
        with torch.no_grad():
            for batch_x, batch_y in test_loader:
                outputs = model(batch_x)
                all_predictions.append(outputs.cpu().numpy())
                all_targets.append(batch_y.cpu().numpy())
        
        return np.vstack(all_predictions), np.vstack(all_targets)
    
    # Generate forecasts for both models
    logger.info("Generating forecasts for hourly model...")
    preds_hourly, targets_hourly = generate_forecasts(model_hourly, test_loader_hourly)
    
    logger.info("Generating forecasts for 15-minute model...")
    preds_15min, targets_15min = generate_forecasts(model_15min, test_loader_15min)
    
    # Calculate MAE for both models
    mae_hourly = np.mean(np.abs(preds_hourly - targets_hourly))
    mae_15min = np.mean(np.abs(preds_15min - targets_15min))
    
    logger.info(f"Hourly MAE: {mae_hourly:.4f}")
    logger.info(f"15-minute MAE: {mae_15min:.4f}")
    
    return {
        "mae_hourly": mae_hourly,
        "mae_15min": mae_15min,
        "preds_hourly": preds_hourly,
        "targets_hourly": targets_hourly,
        "preds_15min": preds_15min,
        "targets_15min": targets_15min
    }


