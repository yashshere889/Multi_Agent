class TemporalFusionTransformer(nn.Module):
    def __init__(self, input_size, hidden_dim, num_heads, num_layers, dropout, forecast_horizon):
        super(TemporalFusionTransformer, self).__init__()
        self.input_size = input_size
        self.hidden_dim = hidden_dim
        self.forecast_horizon = forecast_horizon
        
        # Embedding layer for input features
        self.embedding = nn.Linear(input_size, hidden_dim)
        
        # Transformer encoder layers
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=hidden_dim,
            nhead=num_heads,
            dropout=dropout,
            batch_first=True
        )
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers)
        
        # Output projection layer
        self.output_projection = nn.Linear(hidden_dim, input_size)
        
        # Positional encoding
        self.pos_encoding = self._create_positional_encoding(hidden_dim)
        
    def _create_positional_encoding(self, d_model):
        pe = torch.zeros(1000, d_model)
        position = torch.arange(0, 1000, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        return pe.unsqueeze(0)
        
    def forward(self, x):
        # x shape: (batch_size, sequence_length, input_size)
        batch_size, seq_len, _ = x.shape
        
        # Apply embedding
        x = self.embedding(x)
        
        # Add positional encoding
        x = x + self.pos_encoding[:, :seq_len, :].to(x.device)
        
        # Apply transformer encoder
        x = self.transformer_encoder(x)
        
        # Take the last output for prediction
        x = x[:, -1:, :]  # Shape: (batch_size, 1, hidden_dim)
        
        # Project to output size
        x = self.output_projection(x)
        
        # Expand to forecast horizon
        x = x.expand(batch_size, self.forecast_horizon, self.input_size)
        
        return x


