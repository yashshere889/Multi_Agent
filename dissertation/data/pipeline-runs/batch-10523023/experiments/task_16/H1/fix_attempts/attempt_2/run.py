def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experimental results."""
    logger = logging.getLogger(__name__)
    
    mae_hourly = experiment_output["mae_hourly"]
    mae_15min = experiment_output["mae_15min"]
    
    # Calculate improvement percentage
    if mae_hourly > 0:
        improvement_percentage = ((mae_hourly - mae_15min) / mae_hourly) * 100
    else:
        improvement_percentage = 0.0
    
    # Check if improvement meets success criteria (at least 5% better)
    meets_success_criteria = improvement_percentage >= 5.0
    
    success_notes = (
        f"Hourly Resolution MAE: {mae_hourly:.4f}\n"
        f"15-Minute Resolution MAE: {mae_15min:.4f}\n"
        f"Improvement: {improvement_percentage:.2f}%\n"
        f"Success criteria (≥5% improvement): {'Met' if meets_success_criteria else 'Not met'}"
    )
    
    return {
        "mae_hourly": mae_hourly,
        "mae_15min": mae_15min,
        "improvement_percentage": improvement_percentage,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes
    }


