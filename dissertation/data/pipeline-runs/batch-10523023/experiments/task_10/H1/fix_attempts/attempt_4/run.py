def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """
    Run the comparative benchmark experiment of dimensionality reduction methods
    for tissue-type classification.
    """
    # Initialize results storage
    results = {}
    training_history = {}
    
    X_train = data["X_train"]
    X_test = data["X_test"]
    y_train = data["y_train"]
    y_test = data["y_test"]
    
    # Get reduction ratios
    reduction_ratios = model["reduction_ratios"]
    
    # Define methods to test
    methods = {
        "PCA": lambda X, n_components: PCA(n_components=n_components, random_state=RANDOM_SEED, svd_solver='auto').fit_transform(X),
        "t-SNE": lambda X, n_components: TSNE(n_components=n_components, random_state=RANDOM_SEED, perplexity=min(30, len(X)-1)).fit_transform(X),
        "LLE": lambda X, n_components: LocallyLinearEmbedding(n_components=n_components, random_state=RANDOM_SEED, n_neighbors=min(10, len(X)-1)).fit_transform(X)
    }
    
    # For each method and reduction ratio, perform dimensionality reduction and classification
    for method_name, method_func in methods.items():
        logger.info(f"Running {method_name}...")
        results[method_name] = {}
        
        # For PCA, we also test full dimensionality
        if method_name == "PCA":
            # Test all reduction ratios including 100%
            test_ratios = reduction_ratios
        else:
            # For t-SNE and LLE, we focus on <10% reduction
            test_ratios = [ratio for ratio in reduction_ratios if ratio < 0.1]
        
        for ratio in test_ratios:
            logger.info(f"  Testing {method_name} with {ratio*100:.0f}% reduction...")
            
            # Calculate number of components
            n_components = max(1, int(model["n_features"] * ratio))
            
            # Ensure n_components is valid for PCA
            if method_name == "PCA":
                # Limit components to min(n_samples - 1, n_features - 1) to avoid sklearn errors
                max_components = min(X_train.shape[0] - 1, model["n_features"] - 1)
                n_components = min(n_components, max_components)
            
            # Apply dimensionality reduction
            start_time = time.time()
            X_reduced = method_func(X_train, n_components)
            reduction_time = time.time() - start_time
            
            # Train k-NN classifier
            knn = KNeighborsClassifier(n_neighbors=min(5, len(X_train)-1))
            start_time = time.time()
            knn.fit(X_reduced, y_train)
            fit_time = time.time() - start_time
            
            # Predict on test set
            start_time = time.time()
            y_pred = knn.predict(method_func(X_test, n_components))
            predict_time = time.time() - start_time
            
            # Calculate accuracy
            accuracy = accuracy_score(y_test, y_pred)
            
            # Store results
            key = f"{ratio:.1f}"
            results[method_name][key] = {
                "accuracy": accuracy,
                "reduction_time": reduction_time,
                "fit_time": fit_time,
                "predict_time": predict_time,
                "n_components": n_components
            }
            
            logger.info(f"    Accuracy: {accuracy:.4f} with {n_components} components")
    
    # Also test PCA at full dimensionality for baseline
    logger.info("Testing PCA at full dimensionality...")
    # Use a reasonable number of components for full PCA to avoid the error
    max_components = min(model["n_features"], X_train.shape[0] - 1)
    n_components_full = max_components
    pca_full = PCA(n_components=n_components_full, random_state=RANDOM_SEED, svd_solver='auto')
    X_train_full = pca_full.fit_transform(X_train)
    X_test_full = pca_full.transform(X_test)
    
    knn_full = KNeighborsClassifier(n_neighbors=min(5, len(X_train)-1))
    knn_full.fit(X_train_full, y_train)
    y_pred_full = knn_full.predict(X_test_full)
    accuracy_full = accuracy_score(y_test, y_pred_full)
    
    results["PCA"]["1.0"] = {
        "accuracy": accuracy_full,
        "reduction_time": 0.0,
        "fit_time": 0.0,
        "predict_time": 0.0,
        "n_components": n_components_full
    }
    
    return {
        "results": results,
        "training_history": training_history
    }


