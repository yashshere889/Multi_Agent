def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """
    Evaluate the experiment results against the success criteria.
    
    Success criteria: If t-SNE or LLE achieves classification accuracy within 5% 
    of PCA at <10% reduction ratio, the hypothesis is supported.
    """
    results = experiment_output["results"]
    
    # Get PCA accuracy at full dimensionality (baseline)
    baseline_accuracy = results["PCA"]["1.0"]["accuracy"]
    
    # Get accuracy for t-SNE and LLE at <10% reduction
    t_sne_accuracy = None
    lle_accuracy = None
    
    # Look for the lowest <10% reduction ratio
