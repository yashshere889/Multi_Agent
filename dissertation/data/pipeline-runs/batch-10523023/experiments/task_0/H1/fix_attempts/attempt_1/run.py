def build_model(data):
    import torch
    import torch.nn as nn
    from torch.utils.data import DataLoader, TensorDataset
    
    class PatchTST_Lite(nn.Module):
        def __init__(self, seq_len, n_features, d_model=32, n_heads=4, d_ff=64, dropout=0.1):
            super().__init__()
            self.seq_len = seq_len
            self.n_features = n_features
            
            # Embedding layer
            self.embedding = nn.Linear(n_features, d_model)
            
            # Transformer encoder layers
            encoder_layer = nn.TransformerEncoderLayer(
                d_model=d_model,
                nhead=n_heads,
                dim_feedforward=d_ff,
                dropout=dropout,
                batch_first=True
            )
            self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=2)
            
            # Output layer
            self.output_layer = nn.Linear(d_model, 1)
            
        def forward(self, x):
            # x shape: (batch_size, seq_len, n_features)
            x = self.embedding(x)
            x = self.transformer_encoder(x)
            # Take the last token's output
            x = x[:, -1, :]
            x = self.output_layer(x)
            return x
    
    class Informer(nn.Module):
        def __init__(self, seq_len, n_features, d_model=32, n_heads=4, d_ff=64, dropout=0.1):
            super().__init__()
            self.seq_len = seq_len
            self.n_features = n_features
            
            # Embedding layer
            self.embedding = nn.Linear(n_features, d_model)
            
            # Transformer encoder layers
            encoder_layer = nn.TransformerEncoderLayer(
                d_model=d_model,
                nhead=n_heads,
                dim_feedforward=d_ff,
                dropout=dropout,
                batch_first=True
            )
            self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=2)
            
            # Output layer
            self.output_layer = nn.Linear(d_model, 1)
            
        def forward(self, x):
            # x shape: (batch_size, seq_len, n_features)
            x = self.embedding(x)
            x = self.transformer_encoder(x)
            # Take the last token's output
            x = x[:, -1, :]
            x = self.output_layer(x)
            return x
    
    # Create models
    patchtst_model = PatchTST_Lite(
        seq_len=data['seq_len'],
        n_features=data['n_features']
    )
    
    informer_model = Informer(
        seq_len=data['seq_len'],
        n_features=data['n_features']
    )
    
    # Create data loaders
    train_dataset = TensorDataset(
        torch.FloatTensor(data['X_train_seq']),
        torch.FloatTensor(data['y_train_seq'])
    )
    val_dataset = TensorDataset(
        torch.FloatTensor(data['X_val_seq']),
        torch.FloatTensor(data['y_val_seq'])
    )
    
    train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True)
    val_loader = DataLoader(val_dataset, batch_size=BATCH_SIZE, shuffle=False)
    
    return {
        'patchtst': patchtst_model,
        'informer': informer_model,
        'train_loader': train_loader,
        'val_loader': val_loader,
        'device': torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    }


