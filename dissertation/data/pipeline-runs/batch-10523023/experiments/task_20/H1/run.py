    success_notes = (
        f"K-means with PCA ARI: {kmeans_pca_ari:.4f}\n"
        f"K-means with PCA NMI: {kmeans_pca_nmi:.4f}\n"
        f"Best ARI method: {best_ari_method}\n"
        f"Best NMI method: {best_nmi_method}\n"
        f"K-means with PCA outperforms others in ARI: {ari_better_than_others}\n"
        f"K-means with PCA outperforms others in NMI: {nmi_better_than_others}\n"
        f"Overall success criteria met: {meets_success_criteria}"
    )
    
    return {
        "ari_scores": ari_scores,
        "nmi_scores": nmi_scores,
        "sil_scores": sil_scores,
        "consistency_scores": consistency_scores,
        "best_ari_method": best_ari_method,
        "best_nmi_method": best_nmi_method,
        "kmeans_pca_ari": kmeans_pca_ari,
        "kmeans_pca_nmi": kmeans_pca_nmi,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes
    }


