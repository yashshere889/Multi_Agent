    best_nmi_method = max(nmi_scores, key=nmi_scores.get)
    
    # Success criteria: K-means with PCA should perform better than others
    # in terms of ARI and NMI compared to predefined income thresholds
    kmeans_pca_ari = ari_scores["kmeans_pca"]
    kmeans_pca_nmi = nmi_scores["kmeans_pca"]
    
    # Check if K-means with PCA outperforms other methods
    ari_better_than_others = all(
        kmeans_pca_ari > ari_scores[method] for method in ari_scores.keys() if method != "kmeans_pca"
    )
    
    nmi_better_than_others = all(
        kmeans_pca_nmi > nmi_scores[method] for method in nmi_scores.keys() if method != "kmeans_pca"
    )
    
    # Overall success criteria
