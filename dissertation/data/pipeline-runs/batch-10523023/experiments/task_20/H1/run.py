def load_data() -> Any:
    """Load and preprocess the UCI Adult Census Income dataset."""
    logger = logging.getLogger(__name__)
    
    # Load the dataset
    try:
        df = pd.read_csv("/mnt/fastscratch/users/sgyshere/coder-data/uci_adult_census_income.csv")
        logger.info(f"Loaded dataset with {len(df)} samples")
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise
    
    # Drop the 'fnlwgt' column as it is a sampling weight, not a feature
    df = df.drop(columns=['fnlwgt'])
    
    # Handle missing values represented by '?'
    df = df[df['workclass'] != '?']
    df = df[df['occupation'] != '?']
    df = df[df['native_country'] != '?']
    
    # Identify categorical and numerical columns
    categorical_features = df.select_dtypes(include=['object']).columns.tolist()
    numerical_features = df.select_dtypes(include=[np.number]).columns.tolist()
    
    # Remove target variable from features if present
    if 'income' in numerical_features:
        numerical_features.remove('income')
    if 'income' in categorical_features:
        categorical_features.remove('income')
    
    # Create binary target variable from 'income' column
    y = df['income'].apply(lambda x: 1 if x == '>50K' else 0)
    
    # Prepare features
    X = df.drop(columns=['income'])
    
    # Impute missing values in numerical features
    numerical_imputer = SimpleImputer(strategy='median')
    X[numerical_features] = numerical_imputer.fit_transform(X[numerical_features])
    
    # Encode categorical variables using one-hot encoding
    X_encoded = pd.get_dummies(X, columns=categorical_features, drop_first=True)
    
    # Normalize numerical features
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_encoded)
    
    # Convert back to DataFrame for consistency
    X_scaled_df = pd.DataFrame(X_scaled, columns=X_encoded.columns)
    
    logger.info(f"Processed features: {X_scaled_df.shape}")
    logger.info(f"Target distribution: {y.value_counts()}")
    
    return {
        "X": X_scaled_df,
        "y": y,
        "feature_names": X_scaled_df.columns.tolist(),
        "categorical_features": categorical_features,
        "numerical_features": numerical_features
    }


