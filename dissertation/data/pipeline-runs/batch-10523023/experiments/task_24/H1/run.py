def _truncate_text(text: str, word_count: int) -> str:
    """Helper to truncate text to specified word count"""
    words = text.split()
    return ' '.join(words[:word_count])

def _calculate_correlation(x_vals, y_vals):
    """Calculate Pearson correlation coefficient"""
    if len(x_vals) < 2 or len(y_vals) < 2:
        return None
    try:
        return np.corrcoef(x_vals, y_vals)[0, 1]
    except:
        return None


