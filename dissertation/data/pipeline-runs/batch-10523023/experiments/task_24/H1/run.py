def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """
    Execute the experimental design:
    1. For each article, generate truncated versions at different compression rates
    2. Calculate readability scores for each truncated version
    3. Evaluate factual accuracy using zero-shot faithfulness
    4. Return structured results for evaluation
    """
    results = []
    
    # Get the faithfulness pipeline
    faithfulness_pipe = model.get("faithfulness_pipeline")
    
    # Process each article
    for i, article in enumerate(data['articles']):
        article_id = i
        original_text = article['text']
        word_count = article['word_count']
        
        # Tokenize original text to get words
        original_words = original_text.split()
        
        # Generate truncated versions for each compression rate
        for rate in COMPRESSION_RATES:
            # Calculate target word count
            target_words = max(MIN_WORD_COUNT, int(word_count * rate))
            
            # Truncate text
            truncated_words = original_words[:target_words]
            truncated_text = ' '.join(truncated_words)
            
            # Calculate readability score (Flesch-Kincaid Grade Level)
            try:
                readability_score = textstat.flesch_kincaid_grade(truncated_text)
            except Exception as e:
                logger.warning(f"Could not calculate readability for article {article_id}, rate {rate}: {str(e)}")
                readability_score = None
            
            # Calculate faithfulness score
            faithfulness_score = None
            try:
                if faithfulness_pipe is not None:
                    # Use the faithfulness pipeline to evaluate the truncated text against original
                    # Summarize the original text and compare with truncated version
                    summary = faithfulness_pipe(original_text, max_length=130, min_length=30, do_sample=False)[0]['summary_text']
                    
                    # Simple faithfulness measure: check if key words from original appear in summary
                    original_words_set = set(original_words)
                    summary_words = summary.split()
                    summary_words_set = set(summary_words)
                    
                    # Calculate overlap ratio
                    if len(original_words_set) > 0:
                        overlap = len(original_words_set.intersection(summary_words_set))
                        faithfulness_score = overlap / len(original_words_set)
                    else:
                        faithfulness_score = 0.0
                else:
                    # Fallback: simple keyword overlap between original and truncated text
                    truncated_words_set = set(truncated_words)
                    original_words_set = set(original_words)
                    
                    if len(original_words_set) > 0:
                        overlap = len(original_words_set.intersection(truncated_words_set))
                        faithfulness_score = overlap / len(original_words_set)
                    else:
                        faithfulness_score = 0.0
                    
            except Exception as e:
                logger.warning(f"Could not calculate faithfulness for article {article_id}, rate {rate}: {str(e)}")
                faithfulness_score = None
            
            # Store results
            results.append({
                'article_id': article_id,
                'compression_rate': rate,
                'readability_score': readability_score,
                'factual_accuracy_score': faithfulness_score,
                'original_word_count': word_count,
                'truncated_word_count': target_words
            })
            
            # Log progress
            if (i * len(COMPRESSION_RATES) + COMPRESSION_RATES.index(rate)) % 10 == 0:
                log_progress(article_id=i, compression_rate=rate, processed=True)
    
    return {
        'results': results
    }


