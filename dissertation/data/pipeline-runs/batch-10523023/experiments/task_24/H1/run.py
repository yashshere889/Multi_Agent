def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """
    Evaluate the experiment results against success criteria.
    Check for trends in readability and factual accuracy with increasing compression.
    """
    results = experiment_output['results']
    
    # Group results by compression rate
    grouped_results = defaultdict(list)
    for r in results:
        grouped_results[r['compression_rate']].append(r)
    
    # Calculate averages for each compression rate
    avg_readability = {}
    avg_accuracy = {}
    
    for rate in COMPRESSION_RATES:
        rate_results = grouped_results[rate]
        readability_scores = [r['readability_score'] for r in rate_results if r['readability_score'] is not None]
        accuracy_scores = [r['factual_accuracy_score'] for r in rate_results if r['factual_accuracy_score'] is not None]
        
        if readability_scores:
            avg_readability[rate] = np.mean(readability_scores)
        else:
            avg_readability[rate] = None
            
        if accuracy_scores:
            avg_accuracy[rate] = np.mean(accuracy_scores)
        else:
            avg_accuracy[rate] = None
    
    # Check for trends
    readability_trend = None
    accuracy_trend = None
    
    # For readability, we expect higher values (lower grade level) with lower compression
    readability_values = [avg_readability[r] for r in COMPRESSION_RATES if avg_readability[r] is not None]
    accuracy_values = [avg_accuracy[r] for r in COMPRESSION_RATES if avg_accuracy[r] is not None]
    
    if len(readability_values) >= 2:
        # Check if readability increases (grade level decreases) with compression
        # This means higher compression rates lead to more readable text
        readability_trend = "positive" if len(readability_values) > 1 and readability_values[-1] > readability_values[0] else "negative"
    
    if len(accuracy_values) >= 2:
        # Check if accuracy decreases with compression
        accuracy_trend = "negative" if len(accuracy_values) > 1 and accuracy_values[-1] < accuracy_values[0] else "positive"
    
    # Determine if success criteria are met
    meets_success_criteria = False
    success_notes = ""
    
    # Success criteria: 
    # 1. Significant negative trend in readability (higher compression = more readable)
    # 2. Moderate negative correlation with factual accuracy
    
    if readability_trend == "negative":
        success_notes += "Found negative trend in readability scores with increasing compression. "
        meets_success_criteria = True
    else:
        success_notes += "No clear trend found in readability scores. "
        
    if accuracy_trend == "negative":
        success_notes += "Found negative trend in factual accuracy scores with increasing compression. "
        meets_success_criteria = True
    else:
        success_notes += "No clear trend found in factual accuracy scores. "
    
    if not meets_success_criteria:
        success_notes += "Overall, no strong evidence supporting the hypothesis."
    
    return {
        "readability_by_compression": avg_readability,
        "accuracy_by_compression": avg_accuracy,
        "readability_trend": readability_trend,
        "accuracy_trend": accuracy_trend,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes
    }


