def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """
    Run the experiment comparing BERT sentiment scores vs Fama-French factors
    for predicting next-day S&P 500 return direction using Granger causality tests.
    """
    
    merged_df = data['merged_df']
    
    # Prepare data for Granger causality tests
    # We'll test two models:
    # 1. BERT sentiment scores predicting next-day direction
    # 2. Fama-French factors predicting next-day direction
    
    # For Granger causality, we need to work with time series data
    # Let's create lagged versions of our variables
    
    # Create lagged variables for Granger causality
    df_for_granger = merged_df.copy()
    
    # Lag the variables by 1 day
    df_for_granger['sentiment_lag1'] = df_for_granger['sentiment_score'].shift(1)
    df_for_granger['market_lag1'] = df_for_granger['market_excess_return'].shift(1)
