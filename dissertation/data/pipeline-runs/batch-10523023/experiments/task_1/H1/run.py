    df_for_granger['hml_lag1'] = df_for_granger['hml'].shift(1)
    
    # Drop NaN values created by shifting
    df_for_granger = df_for_granger.dropna()
    
    # Prepare variables for Granger causality
    # For BERT model: sentiment_lag1 -> next_day_direction
    # For FF model: market_lag1, smb_lag1, hml_lag1 -> next_day_direction
    
    # Convert to numpy arrays for Granger causality
    y = df_for_granger['next_day_direction'].values
    
    # BERT model variables
    x_bert = df_for_granger[['sentiment_lag1']].values
    
    # Fama-French model variables  
    x_ff = df_for_granger[['market_lag1', 'smb_lag1', 'hml_lag1']].values
    
    # For Granger causality, we need to ensure we have enough data points
    if len(y) < MIN_SAMPLES_FOR_GRANGER:
        raise ValueError(f"Not enough data points for Granger causality test. Need at least {MIN_SAMPLES_FOR_GRANGER}, got {len(y)}")
    
    # Perform Granger causality tests
    logger.info("Performing Granger causality tests...")
    
    # Test for BERT sentiment model
