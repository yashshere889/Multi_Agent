def run_experiment(data: Any, model_configs: Any) -> dict[str, Any]:
    """Run experiments with increasing training set sizes."""
    results = defaultdict(list)
    training_histories = defaultdict(list)
    
    # Get full dataset
    X_full = data["X_train"]
    y_full = data["y_train"]
    
    # Generate training sets of various sizes by sampling with replacement
    for size in TRAINING_SET_SIZES:
        logger.info(f"Training on dataset size: {size}")
        
        # Sample with replacement to create larger datasets
        indices = np.random.choice(len(X_full), size=size, replace=True)
        X_sample = X_full[indices]
        y_sample = y_full.iloc[indices]
        
        # Train and evaluate each model
        for model_name, model in model_configs.items():
            logger.info(f"Training {model_name} on sample of size {size}")
            
            # Fit model
            if model_name == "NeuralNetwork":
                # For neural network, we'll use early stopping based on validation loss
                # Split sample into train/validation
                X_train_split, X_val_split, y_train_split, y_val_split = train_test_split(
                    X_sample, y_sample, test_size=0.2, random_state=RANDOM_SEED, stratify=y_sample
                )
                
                # Train with early stopping
                model.fit(X_train_split, y_train_split)
                
                # Predictions
                y_pred = model.predict(X_val_split)
                accuracy = accuracy_score(y_val_split, y_pred)
                
                # Store training history (we'll approximate it with validation loss)
                # Since MLPClassifier doesn't expose per-epoch loss easily, we'll 
                # just record the final accuracy for now
                training_histories[model_name].append(accuracy)
                
            else:
                # For tree-based models, we can train directly
                model.fit(X_sample, y_sample)
                
                # Predictions on test set
                y_pred = model.predict(data["X_test"])
                accuracy = accuracy_score(data["y_test"], y_pred)
                
                # Store training history (approximate with final accuracy)
                training_histories[model_name].append(accuracy)
            
            results[model_name].append(accuracy)
    
    # Return predictions and training histories
    return {
        "results": dict(results),
        "training_histories": dict(training_histories),
        "training_set_sizes": TRAINING_SET_SIZES
    }


