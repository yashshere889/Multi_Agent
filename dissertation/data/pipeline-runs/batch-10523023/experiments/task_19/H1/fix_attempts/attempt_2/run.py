def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run the comparative econometric analysis between EPU index and lagged unemployment.
    
    This implements the design steps:
    1. Construct two regression models: one with lagged unemployment as predictor, 
       and another with EPU index as predictor, both controlling for GDP growth and inflation.
    2. Compare the adjusted R-squared, coefficient magnitudes, and statistical significance.
    """
    
    # Extract data
    gdp_growth = data["gdp_growth"]
    inflation = data["inflation"]
    unemployment_proxy = data["unemployment_proxy"]
    epu_index = data["epu_index"]
    lagged_unemployment = data["lagged_unemployment"]
    
    # Prepare data for regression
    n_samples = len(gdp_growth)
    
    # Model 1: EPU index as predictor
    X1 = np.column_stack([gdp_growth, inflation, epu_index])
    y1 = unemployment_proxy
    
    # Model 2: Lagged unemployment as predictor  
    X2 = np.column_stack([gdp_growth, inflation, lagged_unemployment])
    y2 = unemployment_proxy
    
    # Perform OLS regression manually
    def ols_regression(X, y):
        # Add intercept column
        X_with_intercept = np.column_stack([np.ones(X.shape[0]), X])
        
        # Calculate coefficients using normal equation: (X'X)^(-1)X'y
        XtX = np.dot(X_with_intercept.T, X_with_intercept)
        XtX_inv = np.linalg.inv(XtX)
        XtX_inv_Xt = np.dot(XtX_inv, X_with_intercept.T)
        coefficients = np.dot(XtX_inv_Xt, y)
        
        # Calculate predictions
        predictions = np.dot(X_with_intercept, coefficients)
        
        # Calculate residuals
        residuals = y - predictions
        
        # Calculate R-squared
        ss_res = np.sum(residuals**2)
        ss_tot = np.sum((y - np.mean(y))**2)
        r_squared = 1 - (ss_res / ss_tot)
        
        # Adjusted R-squared
        n = len(y)
        k = X.shape[1]  # number of predictors (excluding intercept)
        adj_r_squared = 1 - ((1 - r_squared) * (n - 1) / (n - k - 1))
        
        # Standard errors and t-stats
        mse = ss_res / (n - k - 1)
        var_coef = mse * np.diag(XtX_inv)
        std_errors = np.sqrt(var_coef)
        t_stats = coefficients / std_errors
        
        # P-values (two-tailed)
        from scipy.stats import t
        p_values = 2 * (1 - t.cdf(np.abs(t_stats), df=n-k-1))
        
        return {
            "coefficients": coefficients,
            "r_squared": r_squared,
            "adj_r_squared": adj_r_squared,
            "std_errors": std_errors,
            "t_stats": t_stats,
            "p_values": p_values,
            "predictions": predictions
        }
    
    # Run regressions
    result1 = ols_regression(X1, y1)  # EPU model
    result2 = ols_regression(X2, y2)  # Lagged unemployment model
    
    # Extract coefficients for comparison
    # Coefficient for the main predictor (index)
    epu_coefficient = result1["coefficients"][2]  # Third coefficient (index)
    lagged_unemp_coefficient = result2["coefficients"][2]  # Third coefficient (index)
    
    # Extract p-values for significance testing
    epu_p_value = result1["p_values"][2]
    lagged_unemp_p_value = result2["p_values"][2]
    
    # Extract R-squared values
    epu_adj_r2 = result1["adj_r_squared"]
    lagged_unemp_adj_r2 = result2["adj_r_squared"]
    
    # Store results
    results = {
        "epu_model": result1,
        "lagged_unemp_model": result2,
        "epu_coefficient": epu_coefficient,
        "lagged_unemp_coefficient": lagged_unemp_coefficient,
        "epu_p_value": epu_p_value,
        "lagged_unemp_p_value": lagged_unemp_p_value,
        "epu_adj_r2": epu_adj_r2,
        "lagged_unemp_adj_r2": lagged_unemp_adj_r2,
        "n_samples": n_samples
    }
    
    return results


