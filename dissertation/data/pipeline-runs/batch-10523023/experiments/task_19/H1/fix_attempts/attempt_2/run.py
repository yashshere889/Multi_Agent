def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experimental results against the success criteria.
    
    Success criteria: If the coefficient for the EPU index is significantly larger 
    than that for lagged unemployment, and the adjusted R-squared improves, 
    the hypothesis is supported. Otherwise, it is refuted.
    """
    
    # Extract key metrics
    epu_coeff = experiment_output["epu_coefficient"]
    lagged_unemp_coeff = experiment_output["lagged_unemp_coefficient"]
    epu_p_val = experiment_output["epu_p_value"]
    lagged_unemp_p_val = experiment_output["lagged_unemp_p_value"]
    epu_adj_r2 = experiment_output["epu_adj_r2"]
    lagged_unemp_adj_r2 = experiment_output["lagged_unemp_adj_r2"]
    
    # Determine if coefficients are statistically significant (p < 0.05)
    epu_significant = epu_p_val < 0.05
    lagged_unemp_significant = lagged_unemp_p_val < 0.05
    
    # Check if EPU coefficient is larger in absolute value and significant
    # Also check if EPU model has better adjusted R-squared
    epu_better = (abs(epu_coeff) > abs(lagged_unemp_coeff)) and epu_significant
    r2_improvement = epu_adj_r2 > lagged_unemp_adj_r2
    
    # Determine success based on criteria
    if epu_better and r2_improvement:
        meets = True
        notes = ("The EPU index shows a stronger and more significant relationship "
                 "with unemployment changes compared to lagged unemployment, and "
                 "also explains more variance (higher adjusted R-squared).")
    elif not epu_significant and not lagged_unemp_significant:
        meets = False
        notes = ("Neither the EPU index nor lagged unemployment shows statistical "
                 "significance in explaining unemployment changes.")
    elif not epu_better and not r2_improvement:
        meets = False
        notes = ("The lagged unemployment variable performs better than the EPU index "
                 "in terms of coefficient magnitude and explanatory power.")
    else:
        meets = "unknown"
        notes = ("Mixed results: EPU index may be significant but not stronger than "
                 "lagged unemployment, or vice versa.")
    
    return {
        "epu_coefficient": epu_coeff,
        "lagged_unemp_coefficient": lagged_unemp_coeff,
        "epu_p_value": epu_p_val,
        "lagged_unemp_p_value": lagged_unemp_p_val,
        "epu_adj_r2": epu_adj_r2,
        "lagged_unemp_adj_r2": lagged_unemp_adj_r2,
        "meets_success_criteria": meets,
        "success_notes": notes
    }


