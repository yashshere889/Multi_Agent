def run_experiment(data: Any, model_config: Any) -> dict[str, Any]:
    """Train both models and evaluate their performance."""
    logger = logging.getLogger(__name__)
    
    # Helper function to convert SMILES to molecular graphs
    def smiles_to_graph(smiles):
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise ValueError(f"Invalid SMILES: {smiles}")
        
        # Generate atom features (atomic number)
        atom_features = []
        for atom in mol.GetAtoms():
            atom_features.append(atom.GetAtomicNum())
        
        # Generate adjacency matrix
        adj_matrix = np.zeros((mol.GetNumAtoms(), mol.GetNumAtoms()))
        for bond in mol.GetBonds():
            begin_atom = bond.GetBeginAtomIdx()
            end_atom = bond.GetEndAtomIdx()
            adj_matrix[begin_atom][end_atom] = 1
            adj_matrix[end_atom][begin_atom] = 1
        
        # Convert to PyTorch tensors with explicit dtypes to avoid casting issues
        x = torch.tensor(atom_features, dtype=torch.long)
        # Ensure edge_index is long type for indexing
        edge_indices = np.argwhere(adj_matrix)
        edge_index = torch.tensor(edge_indices, dtype=torch.long).t().contiguous()
        
        return Data(x=x, edge_index=edge_index)
    
    # Helper function to generate Morgan fingerprints
    def smiles_to_fingerprint(smiles):
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise ValueError(f"Invalid SMILES: {smiles}")
        fp = AllChem.GetMorganFingerprintAsBitVect(mol, 2, nBits=2048)
        return np.array(fp)
    
    # Custom collate function for PyG Data objects
    def custom_collate_fn(batch):
        # batch is a list of tuples (smiles, target)
        smiles_list, targets = zip(*batch)
        # Convert to graphs
        graphs = [smiles_to_graph(smiles) for smiles in smiles_list]
        # Create a Batch object
        return Batch.from_data_list(graphs)
    
    # Train GNN model
    logger.info("Training GNN model...")
    gnn_model = model_config["gnn_model"]
    optimizer = torch.optim.Adam(gnn_model.parameters(), lr=LEARNING_RATE)
    
    # Prepare training data
    train_data = list(zip(data["train_smiles"], data["train_targets"]))
    train_loader = DataLoader(train_data, batch_size=BATCH_SIZE, shuffle=True, collate_fn=custom_collate_fn)
    
    # Prepare validation data
    val_data = list(zip(data["val_smiles"], data["val_targets"]))
    val_loader = DataLoader(val_data, batch_size=BATCH_SIZE, shuffle=False, collate_fn=custom_collate_fn)
    
    # Training loop
    best_val_rmse = float('inf')
    patience_counter = 0
    
    for epoch in range(NUM_EPOCHS):
        gnn_model.train()
        total_loss = 0
        
        for batch in train_loader:
            optimizer.zero_grad()
            out = gnn_model(batch)
            loss = F.mse_loss(out, batch.y.float())
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
        
        # Validation
        gnn_model.eval()
        val_predictions = []
        val_targets = []
        
        with torch.no_grad():
            for batch in val_loader:
                out = gnn_model(batch)
                val_predictions.extend(out.cpu().numpy())
                val_targets.extend(batch.y.cpu().numpy())
        
        val_rmse = np.sqrt(mean_squared_error(val_targets, val_predictions))
        
        if val_rmse < best_val_rmse:
            best_val_rmse = val_rmse
            patience_counter = 0
            # Save best model state
            best_gnn_state = gnn_model.state_dict()
        else:
            patience_counter += 1
        
        if patience_counter >= PATIENCE:
            logger.info(f"Early stopping at epoch {epoch}")
            break
    
    # Restore best model state
    gnn_model.load_state_dict(best_gnn_state)
    
    # Evaluate GNN model on test set
    logger.info("Evaluating GNN model...")
    gnn_model.eval()
    test_data = list(zip(data["test_smiles"], data["test_targets"]))
    test_loader = DataLoader(test_data, batch_size=BATCH_SIZE, shuffle=False, collate_fn=custom_collate_fn)
    
    gnn_predictions = []
    gnn_targets = []
    
    with torch.no_grad():
        for batch in test_loader:
            out = gnn_model(batch)
            gnn_predictions.extend(out.cpu().numpy())
            gnn_targets.extend(batch.y.cpu().numpy())
    
    gnn_rmse = np.sqrt(mean_squared_error(gnn_targets, gnn_predictions))
    
    # Train fingerprint model
    logger.info("Training fingerprint model...")
    rf_model = model_config["rf_model"]
    
    # Prepare fingerprint data
    train_fps = np.array([smiles_to_fingerprint(smiles) for smiles in data["train_smiles"]])
    val_fps = np.array([smiles_to_fingerprint(smiles) for smiles in data["val_smiles"]])
    test_fps = np.array([smiles_to_fingerprint(smiles) for smiles in data["test_smiles"]])
    
    # Train RF model
    rf_model.fit(train_fps, data["train_targets"])
    
    # Evaluate RF model on test set
    logger.info("Evaluating fingerprint model...")
    rf_predictions = rf_model.predict(test_fps)
    rf_rmse = np.sqrt(mean_squared_error(data["test_targets"], rf_predictions))
    
    return {
        "gnn_rmse": gnn_rmse,
        "rf_rmse": rf_rmse
    }


