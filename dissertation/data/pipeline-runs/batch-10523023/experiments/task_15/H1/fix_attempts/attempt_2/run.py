def add_spatial_lag(X: np.ndarray, weights: np.ndarray, y_values: np.ndarray) -> np.ndarray:
    """Add spatial lag term to features using proper spatial autoregressive calculation."""
    n_samples, n_features = X.shape
    
    # For each sample, compute spatially lagged values of the target variable
    # This implements a simplified spatial lag model where we compute
    # a weighted average of neighboring target values
    spatial_lag = np.zeros(n_samples)
    
    # Use the target values (y_values) to compute spatial lag
    # This is a basic implementation of spatial lag - in a full implementation
    # we would use the spatial weights matrix to compute a proper SAR model
    for i in range(n_samples):
        # Get weights for sample i
        weights_i = weights[i]
        # Normalize weights to sum to 1
        weights_sum = np.sum(weights_i)
        if weights_sum > 0:
            normalized_weights = weights_i / weights_sum
        else:
            normalized_weights = weights_i
            
        # Compute weighted average of target values
        spatial_lag[i] = np.sum(normalized_weights * y_values)
    
    # Add spatial lag as a new feature
    X_extended = np.column_stack([X, spatial_lag])
    
    return X_extended


