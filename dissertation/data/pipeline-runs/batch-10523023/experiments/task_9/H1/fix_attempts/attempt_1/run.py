def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate both models using accuracy and AUC-ROC metrics"""
    
    # Extract results
    clinical_results = experiment_output["clinical"]
    all_results = experiment_output["all"]
    
    # Calculate metrics for clinical model
    clinical_acc = accuracy_score(clinical_results["test_true"], clinical_results["test_pred"])
    clinical_auc = roc_auc_score(clinical_results["test_true"], clinical_results["test_prob"])
    
    # Calculate metrics for all model
    all_acc = accuracy_score(all_results["test_true"], all_results["test_pred"])
    all_auc = roc_auc_score(all_results["test_true"], all_results["test_prob"])
    
    # Determine if the hypothesis is supported or refuted
    # If the model with demographic features shows significantly better performance,
    # the hypothesis is refuted. If there is no significant difference, the hypothesis is supported.
    
    # For simplicity, we'll consider a difference of 0.05 as significant
    acc_diff = all_acc - clinical_acc
    auc_diff = all_auc - clinical_auc
    
    # Check if the difference is statistically meaningful
    # We'll use a simple threshold approach for this experiment
    is_significant = abs(acc_diff) > 0.05 or abs(auc_diff) > 0.05
    
    # The hypothesis is supported if there's no significant improvement
    # The hypothesis is refuted if there's significant improvement with demographics
    meets_success_criteria = not is_significant
    
    success_notes = (
        f"Clinical model accuracy: {clinical_acc:.4f}, AUC: {clinical_auc:.4f}. "
        f"All features model accuracy: {all_acc:.4f}, AUC: {all_auc:.4f}. "
        f"Difference in accuracy: {acc_diff:.4f}, AUC: {auc_diff:.4f}. "
    )
    
    if is_significant:
        success_notes += "Significant improvement observed with demographic features."
    else:
        success_notes += "No significant improvement observed with demographic features."
    
    return {
        "clinical_accuracy": clinical_acc,
        "clinical_auc": clinical_auc,
        "all_accuracy": all_acc,
        "all_auc": all_auc,
        "accuracy_difference": acc_diff,
        "auc_difference": auc_diff,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes
    }


