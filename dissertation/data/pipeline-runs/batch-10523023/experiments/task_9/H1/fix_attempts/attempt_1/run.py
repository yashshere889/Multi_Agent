def load_data() -> Any:
    """Load and preprocess the UCI Adult Census Income dataset according to 
    the specified preprocessing steps."""
    logger.info("Loading data from uci_adult_census_income.csv")
    
    # Load the dataset
    df = pd.read_csv("/mnt/fastscratch/users/sgyshere/coder-data/uci_adult_census_income.csv")
    
    # Remove fnlwgt column (sampling weight, not a feature)
    df = df.drop(columns=["fnlwgt"])
    
    # Handle missing values ('?' in the dataset) by removing rows with missing values
    df = df[df != '?'].dropna()
    
    # Define features
    numerical_features = ["age", "education_num", "hours_per_week"]
    categorical_features = ["sex", "race"]
    
    # Separate features and target
    X = df[numerical_features + categorical_features]
    y = (df["income"] == ">50K").astype(int)
    
    # Split into train/test sets (80/20)
    from sklearn.model_selection import train_test_split
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_FRACTION, random_state=RANDOM_SEED, stratify=y
    )
    
    return {
        "X_train": X_train,
        "y_train": y_train,
        "X_test": X_test,
        "y_test": y_test,
        "numerical_features": numerical_features,
        "categorical_features": categorical_features,
        "target_column": "income"
    }


