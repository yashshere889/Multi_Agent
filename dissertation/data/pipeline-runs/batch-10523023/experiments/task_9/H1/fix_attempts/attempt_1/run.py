# evaluate() returns a plain dict: real metric keys, plus these two reserved
# keys that this orchestration promotes into the result envelope rather than
# treating as a metric.
_RESERVED_EVAL_KEYS = ("meets_success_criteria", "success_notes")


def _normalize_verdict(value: Any) -> Any:
    """Coerce evaluate()'s verdict to a real bool, or to the "unknown" sentinel.

    Generated code routinely computes this from a comparison over numpy values
    (`improvement >= 10.0`), which yields numpy.bool_ rather than bool.
    numpy.bool_ is not JSON-serialisable, so the json.dump(default=str) below
    records the *string* "True" instead. Downstream,
    writer_agent.compute_hypothesis_verdict tests `meets is True`, which a
    string fails, so a correct verdict is silently downgraded to inconclusive
    and a real result is thrown away. Observed in coder benchmark run 10431840,
    cases 05 and 12, which reported 'True'/'False' and were counted as carrying
    no verdict at all.

    The fix belongs here, at the origin, where the type is still known — NOT in
    the downstream `is True` comparisons, whose strictness is the safety
    property that stops a truthy non-verdict being read as success.

    bool() alone will not do: bool("False") is True, so a verdict that has
    already lost its type must be parsed rather than cast. Anything
    unrecognised becomes "unknown", which is the safe direction — withholding a
    verdict is always permitted; asserting a wrong one is not.
    """
    if value is True or value is False:
        return value
    # numpy.bool_ and other scalar wrappers expose .item(), which unwraps to a
    # genuine Python bool. Duck-typed because this template imports no numpy.
    item = getattr(value, "item", None)
    if callable(item):
        try:
            inner = item()
        except Exception:
            return "unknown"
        if inner is True or inner is False:
            return inner
        return "unknown"
    if isinstance(value, str):
        lowered = value.strip().lower()
        if lowered == "true":
            return True
        if lowered == "false":
            return False
    # Numbers are not verdicts, and neither is anything else.
    return "unknown"


def _build_result_envelope(status: str, eval_output: dict | None, error: str | None, elapsed: float) -> dict[str, Any]:
    eval_output = eval_output or {}
    meets_success_criteria = _normalize_verdict(
        eval_output.get("meets_success_criteria", "unknown")
    )
    notes = eval_output.get("success_notes", "")
    metrics = {k: v for k, v in eval_output.items() if k not in _RESERVED_EVAL_KEYS}
    if status == "failure":
        meets_success_criteria = "unknown"
        notes = notes or "Experiment raised an exception before evaluation completed — see 'error'."
    return {
        "experiment_id": EXPERIMENT_ID,
        "experiment_name": EXPERIMENT_NAME,
        "hypothesis": HYPOTHESIS,
        "author": AUTHOR,
        "baseline": BASELINE,
        "success_criteria": SUCCESS_CRITERIA,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "status": status,  # "success" | "failure"
        "elapsed_seconds": round(elapsed, 4),
        "resumed": RESUME,
        "metrics": metrics,
        "meets_success_criteria": meets_success_criteria,
        "notes": notes,
        "error": error,
    }


def _save_results(results: dict[str, Any]) -> Path:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = OUTPUT_DIR / "results.json"
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, default=str)
    return out_path


def _print_summary(results: dict[str, Any], out_path: Path) -> None:
    sep = "=" * 72
    print(f"\n{sep}")
    print(f"  EXPERIMENT : {results['experiment_name']}")
    print(f"  ID         : {results['experiment_id']}")
    print(f"  STATUS     : {results['status'].upper()}")
    print(f"  ELAPSED    : {results['elapsed_seconds']} s")
    print(f"  SAVED TO   : {out_path}")
    if PROGRESS_PATH.exists():
        print(f"  PROGRESS   : {PROGRESS_PATH}")
    print(sep)
    if results["metrics"]:
        print("  METRICS")
        for k, v in results["metrics"].items():
            print(f"    {k:<30} {v}")
    print(f"  MEETS SUCCESS CRITERIA: {results['meets_success_criteria']}")
    if results["notes"]:
        print(f"  NOTES: {results['notes']}")
    if results["error"]:
        print("  ERROR")
        for line in results["error"].splitlines():
            print(f"    {line}")
    print(f"{sep}\n")


def run() -> dict[str, Any]:
    logger.info("Starting experiment '%s' (%s)", EXPERIMENT_NAME, EXPERIMENT_ID)
    t0 = time.perf_counter()

    try:
        logger.info("Phase 1/4 — Loading data...")
        data = load_data()

        logger.info("Phase 2/4 — Building model...")
        model = build_model(data)

        logger.info("Phase 3/4 — Running experiment...")
        experiment_output = run_experiment(data, model)

        logger.info("Phase 4/4 — Evaluating...")
        eval_output = evaluate(experiment_output)

        elapsed = time.perf_counter() - t0
        results = _build_result_envelope(status="success", eval_output=eval_output, error=None, elapsed=elapsed)
        logger.info("Experiment completed in %.2f s.", elapsed)

    except Exception:  # noqa: BLE001
        elapsed = time.perf_counter() - t0
        tb = traceback.format_exc()
        logger.error("Experiment FAILED:\n%s", tb)
        results = _build_result_envelope(status="failure", eval_output=None, error=tb, elapsed=elapsed)

    out_path = _save_results(results)
    _print_summary(results, out_path)
    return results


if __name__ == "__main__":
    outcome = run()
    sys.exit(0 if outcome["status"] == "success" else 1)
