def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Train both models using cross-validation and evaluate on test set"""
    
    # Initialize results storage
    results = {}
    
    # Cross-validation for clinical model
    skf = StratifiedKFold(n_splits=N_FOLDS, shuffle=True, random_state=RANDOM_SEED)
    
    clinical_cv_scores = []
    clinical_cv_probs = []
    clinical_cv_preds = []
    
    for fold, (train_idx, val_idx) in enumerate(skf.split(data["X_train"], data["y_train"])):
        X_fold_train = data["X_train"].iloc[train_idx]
        y_fold_train = data["y_train"].iloc[train_idx]
        X_fold_val = data["X_train"].iloc[val_idx]
        y_fold_val = data["y_train"].iloc[val_idx]
        
        # Fit clinical model
        model["clinical_model"].fit(X_fold_train, y_fold_train)
        
        # Predict on validation set
        y_fold_pred = model["clinical_model"].predict(X_fold_val)
        y_fold_prob = model["clinical_model"].predict_proba(X_fold_val)[:, 1]
        
        # Store scores
        acc = accuracy_score(y_fold_val, y_fold_pred)
        clinical_cv_scores.append(acc)
        clinical_cv_probs.extend(y_fold_prob)
        clinical_cv_preds.extend(y_fold_pred)
    
    # Cross-validation for all model
    all_cv_scores = []
    all_cv_probs = []
    all_cv_preds = []
    
    for fold, (train_idx, val_idx) in enumerate(skf.split(data["X_train"], data["y_train"])):
        X_fold_train = data["X_train"].iloc[train_idx]
        y_fold_train = data["y_train"].iloc[train_idx]
        X_fold_val = data["X_train"].iloc[val_idx]
        y_fold_val = data["y_train"].iloc[val_idx]
        
        # Fit all model
        model["all_model"].fit(X_fold_train, y_fold_train)
        
        # Predict on validation set
        y_fold_pred = model["all_model"].predict(X_fold_val)
        y_fold_prob = model["all_model"].predict_proba(X_fold_val)[:, 1]
        
        # Store scores
        acc = accuracy_score(y_fold_val, y_fold_pred)
        all_cv_scores.append(acc)
        all_cv_probs.extend(y_fold_prob)
        all_cv_preds.extend(y_fold_pred)
    
    # Final test set evaluation
    # Clinical model
    clinical_model_pred = model["clinical_model"].predict(data["X_test"])
    clinical_model_prob = model["clinical_model"].predict_proba(data["X_test"])[:, 1]
    
    # All model
    all_model_pred = model["all_model"].predict(data["X_test"])
    all_model_prob = model["all_model"].predict_proba(data["X_test"])[:, 1]
    
    # Store final results
    results = {
        "clinical": {
            "cv_scores": clinical_cv_scores,
            "test_pred": clinical_model_pred,
            "test_prob": clinical_model_prob,
            "test_true": data["y_test"]
        },
        "all": {
            "cv_scores": all_cv_scores,
            "test_pred": all_model_pred,
            "test_prob": all_model_prob,
            "test_true": data["y_test"]
        }
    }
    
    # Training history for convergence analysis
    results["training_history"] = {
        "clinical": [np.mean(clinical_cv_scores)] * N_FOLDS,
        "all": [np.mean(all_cv_scores)] * N_FOLDS
    }
    
    return results


