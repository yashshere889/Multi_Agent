def build_model(data: Any) -> Any:
    """Build two logistic regression models:
    1. Clinical features only (age, education_num, hours_per_week)
    2. All features including demographic variables (sex, race)
    """
    # Create preprocessing pipelines for both feature sets
    clinical_features = data["numerical_features"]
    all_features = data["numerical_features"] + data["categorical_features"]
    
    # Preprocessing pipeline for clinical features only
    clinical_preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), clinical_features),
        ],
        remainder="passthrough"
    )
    
    # Preprocessing pipeline for all features
    all_preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), data["numerical_features"]),
            ("cat", OneHotEncoder(drop='first', sparse_output=False), data["categorical_features"]),
        ],
        remainder="passthrough"
    )
    
    # Models
    clinical_model = Pipeline([
        ("preprocessor", clinical_preprocessor),
        ("classifier", LogisticRegression(random_state=RANDOM_SEED, max_iter=MAX_ITER))
    ])
    
    all_model = Pipeline([
        ("preprocessor", all_preprocessor),
        ("classifier", LogisticRegression(random_state=RANDOM_SEED, max_iter=MAX_ITER))
    ])
    
    return {
        "clinical_model": clinical_model,
        "all_model": all_model,
        "clinical_features": clinical_features,
        "all_features": all_features
    }


