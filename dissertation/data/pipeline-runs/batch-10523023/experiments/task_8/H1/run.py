def _bayesian_quantile_regression(returns: np.ndarray, tau: float) -> float:
    """Estimate VaR using Bayesian quantile regression with asymmetric Laplace distribution.
    
    This implements a simplified version of Bayesian quantile regression based on 
    the asymmetric Laplace distribution as described in the referenced literature.
    """
    # For simplicity, we use a closed-form approximation for the 5th percentile
    # In a full implementation, this would involve sampling from the posterior
    # using MCMC or variational inference
    
    # Simple approach: use empirical quantile as approximation
    var_estimate = np.percentile(returns, tau * 100)
    
    # Alternative: use robust estimation with trimmed mean
    # Trim 10% from each end to reduce outlier impact
    trimmed_returns = returns[np.argsort(returns)[int(len(returns)*0.1):int(len(returns)*0.9)]]
    if len(trimmed_returns) > 0:
        var_estimate = np.percentile(trimmed_returns, tau * 100)
    
    return var_estimate

def _gaussian_error_model(returns: np.ndarray, tau: float) -> float:
    """Estimate VaR using Gaussian error model."""
    # Compute mean and standard deviation
    mean_return = np.mean(returns)
    std_return = np.std(returns)
    
    # For normal distribution, VaR at 5th percentile is:
    # VaR = mean + z_0.05 * std
    # where z_0.05 = -1.645 (inverse CDF of standard normal at 0.05)
    z_score = stats.norm.ppf(tau)
    var_estimate = mean_return + z_score * std_return
    
    return var_estimate

def _pinball_loss(y_true: list[float], y_pred: list[float], tau: float) -> float:
    """Calculate pinball loss for quantile regression.
    
    Pinball loss = (1/2) * sum(max(0, tau*(y - y_pred), (1-tau)*(y_pred - y)))
    """
    loss = 0.0
    for y, y_pred_val in zip(y_true, y_pred):
        if y >= y_pred_val:
            loss += tau * (y - y_pred_val)
        else:
            loss += (1 - tau) * (y_pred_val - y)
    return loss


