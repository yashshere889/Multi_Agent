def load_data() -> Any:
    """Load and preprocess the UCI Credit Approval dataset."""
    logger = logging.getLogger(__name__)
    
    # Load the dataset
    data_path = "/mnt/fastscratch/users/sgyshere/coder-data/uci_credit_approval.csv"
    try:
        df = pd.read_csv(data_path)
        logger.info(f"Loaded dataset with {len(df)} samples from {data_path}")
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise
    
    # Remove rows with missing values ('?')
    df_clean = df[df['A1'] != '?']
    
    # Drop columns A14 and A15 which contain placeholders
    df_clean = df_clean.drop(columns=['A14', 'A15'], errors='ignore')
    
    # Separate features and target
    X = df_clean.drop(columns=['approved'])
    y = df_clean['approved']
    
    # Encode categorical features using one-hot encoding
    encoder = OneHotEncoder(drop='first', sparse_output=False)
    X_encoded = encoder.fit_transform(X)
    
    # Convert target to binary (encode '-' as 1, '+' as 0)
    y_binary = (y == '-').astype(int)
    
    # Split into train and test sets (80/20 split)
    X_train, X_test, y_train, y_test = train_test_split(
        X_encoded, y_binary, test_size=TEST_FRACTION, 
        random_state=RANDOM_SEED, stratify=y_binary
    )
    
    # Ensure test set maintains original class imbalance
    train_class_dist = np.bincount(y_train)
    test_class_dist = np.bincount(y_test)
    logger.info(f"Training set class distribution: {train_class_dist}")
    logger.info(f"Test set class distribution: {test_class_dist}")
    
    return {
        "X_train": X_train.tolist(),
        "y_train": y_train.tolist(),
        "X_test": X_test.tolist(),
        "y_test": y_test.tolist(),
        "feature_names": encoder.get_feature_names_out(X.columns),
        "target_names": ['approved', 'rejected'],
        "encoder": encoder
    }


