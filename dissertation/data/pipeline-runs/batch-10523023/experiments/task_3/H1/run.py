def run_experiment(data: Any, model_config: Any) -> dict[str, Any]:
    """Run the experiment with three methods: SMOTE, Class-weighted RF, Threshold Tuning."""
    logger = logging.getLogger(__name__)
    
    # Prepare data
    X_train = np.array(data["X_train"])
    y_train = np.array(data["y_train"])
    X_test = np.array(data["X_test"])
    y_test = np.array(data["y_test"])
    
    # Method 1: SMOTE oversampling
    logger.info("Running SMOTE method...")
    from imblearn.over_sampling import SMOTE
    smote = SMOTE(random_state=RANDOM_SEED)
    X_train_smote, y_train_smote = smote.fit_resample(X_train, y_train)
    
    # Instead of using .clone(), create a fresh model instance
    model_smote = RandomForestClassifier(
        n_estimators=100,
        random_state=RANDOM_SEED,
        max_depth=10,
        min_samples_split=5,
        min_samples_leaf=2
    )
    model_smote.fit(X_train_smote, y_train_smote)
    y_pred_proba_smote = model_smote.predict_proba(X_test)[:, 1]
    
    # Method 2: Class-weighted Random Forest
    logger.info("Running Class-weighted Random Forest method...")
    class_weights = compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)
    class_weight_dict = dict(zip(np.unique(y_train), class_weights))
    
    # Create a fresh model instance with class weights
    model_cw = RandomForestClassifier(
        n_estimators=100,
        random_state=RANDOM_SEED,
        max_depth=10,
        min_samples_split=5,
        min_samples_leaf=2,
        class_weight=class_weight_dict
    )
    model_cw.fit(X_train, y_train)
    y_pred_proba_cw = model_cw.predict_proba(X_test)[:, 1]
    
    # Method 3: Decision threshold tuning
    logger.info("Running Threshold Tuning method...")
    # Create a fresh base model instance
    model_base = RandomForestClassifier(
        n_estimators=100,
        random_state=RANDOM_SEED,
        max_depth=10,
        min_samples_split=5,
        min_samples_leaf=2
    )
    model_base.fit(X_train, y_train)
    y_pred_proba_base = model_base.predict_proba(X_test)[:, 1]
    
    # Find threshold that achieves TARGET_FPR
    fpr, tpr, thresholds = roc_curve(y_test, y_pred_proba_base)
    # Find the closest threshold to achieve TARGET_FPR
    closest_idx = np.argmin(np.abs(fpr - TARGET_FPR))
    optimal_threshold = thresholds[closest_idx]
    
    # Apply threshold to get predictions
    y_pred_threshold = (y_pred_proba_base >= optimal_threshold).astype(int)
    
    # Calculate recall at fixed FPR for all methods
    # For SMOTE and class-weighted RF, we use 0.5 threshold for consistency
    recall_smote = recall_score(y_test, (y_pred_proba_smote >= 0.5).astype(int))
    recall_cw = recall_score(y_test, (y_pred_proba_cw >= 0.5).astype(int))
    recall_threshold = recall_score(y_test, y_pred_threshold)
    
    return {
        "recall_at_fixed_fpr": {
            "smote": recall_smote,
            "class_weighted_rf": recall_cw,
            "threshold_tuning": recall_threshold
        },
        "y_true": y_test.tolist(),
        "y_pred_proba_smote": y_pred_proba_smote.tolist(),
        "y_pred_proba_cw": y_pred_proba_cw.tolist(),
        "y_pred_proba_threshold": y_pred_proba_base.tolist(),
        "y_pred_threshold": y_pred_threshold.tolist()
    }


