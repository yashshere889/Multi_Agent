def calculate_recall_at_fpr(model, X_test, y_test, target_fpr):
    """Calculate recall at a fixed false positive rate"""
    # Get prediction probabilities
    y_prob = model.predict_proba(X_test)[:, 1]  # Probability of positive class
    
    # Calculate ROC curve
    fpr, tpr, thresholds = roc_curve(y_test, y_prob)
    
    # Find the threshold that gives us the closest FPR to our target
    # We want the highest TPR (recall) for FPR <= target_fpr
    valid_thresholds = [(fpr_idx, tpr_val, thresh_val) 
                        for fpr_idx, (fpr_val, tpr_val, thresh_val) 
                        in enumerate(zip(fpr, tpr, thresholds)) 
                        if fpr_val <= target_fpr]
    
    if not valid_thresholds:
        # If no threshold achieves target FPR, use the one with lowest FPR
        min_fpr_idx = np.argmin(fpr)
        return tpr[min_fpr_idx]
    
    # Choose the threshold that maximizes TPR (recall) among valid ones
    best_idx = max(valid_thresholds, key=lambda x: x[1])[0]
    return tpr[best_idx]


