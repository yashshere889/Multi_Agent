def train_rf_with_smote(X_train, y_train, n_features):
    """Train Random Forest with SMOTE oversampling"""
    # Apply SMOTE to the training data
    smote = SMOTE(random_state=RANDOM_SEED)
    X_train_resampled, y_train_resampled = smote.fit_resample(X_train, y_train)
    
    # Train Random Forest
    rf = RandomForestClassifier(n_estimators=100, random_state=RANDOM_SEED)
    rf.fit(X_train_resampled, y_train_resampled)
    
    # Return model and dummy history (since we don't have epochs)
    return rf, []

def train_class_weighted_rf(X_train, y_train, n_features):
    """Train Random Forest with class weights"""
    # Calculate class weights
    unique, counts = np.unique(y_train, return_counts=True)
    class_weights = dict(zip(unique, 1.0 / counts))
    
    # Train Random Forest with class weights
    rf = RandomForestClassifier(
        n_estimators=100,
        class_weight=class_weights,
        random_state=RANDOM_SEED
    )
    rf.fit(X_train, y_train)
    
    # Return model and dummy history
    return rf, []

