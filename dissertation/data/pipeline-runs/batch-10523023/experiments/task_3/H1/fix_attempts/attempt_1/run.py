    smote_worse_than_dt = smote_recall < dt_recall
    
    # Success criteria: SMOTE should yield lower recall than at least one of the other methods
    # to support the hypothesis
    supports_hypothesis = smote_worse_than_cwrf or smote_worse_than_dt
    
    # If SMOTE is worse than both, it strongly supports the hypothesis
    strong_support = smote_worse_than_cwrf and smote_worse_than_dt
    
    # If SMOTE is better or equal to both, it refutes the hypothesis
