def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """
    Run the comparative benchmark experiment.
    
    Args:
        data: The loaded data (DataFrame)
        model: The built model structure
        
    Returns:
        Dictionary containing experiment results
    """
    logger.info("Running experiment...")
    
    # Get data components
    X = model['X']
    y = model['y']
    feature_cols = model['feature_cols']
    label_encoders = model['label_encoders']
    scaler = model['scaler']
    
    # Initialize results storage
    results = {
        'xgboost': [],
        'degree_day': [],
        'training_history': {}
    }
    
    # Perform cross-validation
    kf = KFold(n_splits=N_FOLDS, shuffle=True, random_state=RANDOM_SEED)
    
    for fold, (train_idx, val_idx) in enumerate(kf.split(X)):
        logger.info(f"Processing fold {fold + 1}/{N_FOLDS}")
        
        # Split data
        X_train, X_val = X[train_idx], X[val_idx]
        y_train, y_val = y[train_idx], y[val_idx]
        
        # Train XGBoost model
        xgb_model = model['models']['xgboost']
        xgb_model.fit(X_train, y_train)
        
        # Predictions
        xgb_pred = xgb_model.predict(X_val)
        
        # Evaluate XGBoost
        xgb_mae = mean_absolute_error(y_val, xgb_pred)
        xgb_rmse = mean_squared_error(y_val, xgb_pred, squared=False)
        xgb_r2 = r2_score(y_val, xgb_pred)
        
        results['xgboost'].append({
            'mae': xgb_mae,
            'rmse': xgb_rmse,
            'r2': xgb_r2
        })
        
        # Train degree-day model
        degree_day_pred = _train_degree_day_model(X_train, y_train, X_val, 
                                                 feature_cols, label_encoders)
        
        # Evaluate degree-day model
        dd_mae = mean_absolute_error(y_val, degree_day_pred)
        dd_rmse = mean_squared_error(y_val, degree_day_pred, squared=False)
        dd_r2 = r2_score(y_val, degree_day_pred)
        
        results['degree_day'].append({
            'mae': dd_mae,
            'rmse': dd_rmse,
            'r2': dd_r2
        })
        
        # Log progress
        log_progress(fold=fold+1, 
                    xgb_mae=xgb_mae, xgb_rmse=xgb_rmse, xgb_r2=xgb_r2,
                    dd_mae=dd_mae, dd_rmse=dd_rmse, dd_r2=dd_r2)
    
    return results


def _train_degree_day_model(X_train: np.ndarray, y_train: np.ndarray, 
                           X_val: np.ndarray, feature_cols: List[str],
                           label_encoders: Dict[str, LabelEncoder]) -> np.ndarray:
    """
    Train and apply the degree-day model.
    
    Args:
        X_train: Training features
        y_train: Training targets
        X_val: Validation features
        feature_cols: Feature column names
        label_encoders: Label encoders for categorical variables
        
    Returns:
        Predictions from the degree-day model
    """
    # Extract relevant features
    temp_idx = feature_cols.index('temperature')
    precip_idx = feature_cols.index('precipitation')
    crop_idx = feature_cols.index('crop_type_encoded')
    
    # For simplicity, we'll use a basic degree-day approach
    # In a real implementation, this would be more sophisticated
    predictions = []
    
    for i in range(len(X_val)):
        # Get temperature for this sample
        temp = X_val[i][temp_idx]
        
        # Calculate degree-days above base threshold
        degree_days = max(0, temp - BASE_TEMPERATURE)
        
        # Simple model: yield = base_yield + degree_days * effect
        # We'll estimate base yield from training data
        avg_yield = np.mean(y_train)
        effect = 0.02  # Simplified effect of degree-days
        
        predicted_yield = avg_yield + degree_days * effect
        predictions.append(max(0.1, predicted_yield))  # Ensure positive yield
    
    return np.array(predictions)


