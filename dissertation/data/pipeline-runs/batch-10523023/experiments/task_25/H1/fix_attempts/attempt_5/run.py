    logger.info("Applying sparse fine-tuning...")
    
    # Get all parameter names and their shapes
    param_names = [name for name, _ in model["model"].named_parameters()]
    num_params = len(param_names)
    
    # Select a fraction of parameters to update
    num_sparse_params = int(num_params * SPARSE_FRACTION)
    selected_param_indices = np.random.choice(num_params, num_sparse_params, replace=False)
    selected_param_names = [param_names[i] for i in selected_param_indices]
    
    # Freeze all parameters except selected ones
    for name, param in model["model"].named_parameters():
        if name in selected_param_names:
            param.requires_grad = True
        else:
            param.requires_grad = False
    
    # Train sparse model
    sparse_losses = train_model(
        data["train_texts_10"], 
        data["train_labels_10"], 
        model["model"], 
        tokenizer, 
        "sparse fine-tuning"
    )
    
    # Evaluate both models
    def evaluate_model(model_obj, texts, labels, name):
        model_obj.eval()
        predictions = []
        true_labels = []
        
        dataset = TextDataset(texts, labels, tokenizer, MAX_LENGTH)
        dataloader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=False)
        
        with torch.no_grad():
            for batch in dataloader:
                input_ids = batch['input_ids'].to(device)
                attention_mask = batch['attention_mask'].to(device)
                labels = batch['labels'].to(device)
                
                outputs = model_obj(
                    input_ids=input_ids,
                    attention_mask=attention_mask
                )
                
                logits = outputs.logits
                preds = torch.argmax(logits, dim=-1)
                
                predictions.extend(preds.cpu().numpy())
                true_labels.extend(labels.cpu().numpy())
        
        accuracy = accuracy_score(true_labels, predictions)
        f1 = f1_score(true_labels, predictions, average='weighted')
        
        logger.info(f"{name} - Accuracy: {accuracy:.4f}, F1: {f1:.4f}")
        
        return {
            "accuracy": accuracy,
            "f1": f1,
            "predictions": predictions,
            "true_labels": true_labels
        }
    
    # Evaluate both models on test set
    full_results = evaluate_model(model["model"], data["test_texts"], data["test_labels"], "Full Fine-tuning")
    
    # Reset model for sparse training
    # Reload original model state
    # Instead, we'll recreate the model for the sparse training
    # But since we're doing everything in one run, we'll just retrain the sparse model
    # with the same setup as before
    
    # Reapply sparse training setup
    for name, param in model["model"].named_parameters():
        if name in selected_param_names:
            param.requires_grad = True
        else:
            param.requires_grad = False
    
    # Train sparse model again (this is the same as before, but we're being careful)
    sparse_losses = train_model(
        data["train_texts_10"], 
        data["train_labels_10"], 
        model["model"], 
        tokenizer, 
        "sparse fine-tuning"
    )
    
    sparse_results = evaluate_model(model["model"], data["test_texts"], data["test_labels"], "Sparse Fine-tuning")
    
    # Store training history
    training_history = {
        "full_fine_tuning": full_losses,
        "sparse_fine_tuning": sparse_losses
    }
    
    # Return results
    return {
        "full_results": full_results,
        "sparse_results": sparse_results,
        "training_history": training_history
    }


