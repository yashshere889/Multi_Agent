def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    logger.info("Running experiment...")
    
    # Set device
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    logger.info(f"Using device: {device}")
    
    model["model"].to(device)
    
    # Prepare data
    tokenizer = model["tokenizer"]
    
    # Define a custom dataset class
    class TextDataset(Dataset):
        def __init__(self, texts, labels, tokenizer, max_length):
            self.texts = texts
            self.labels = labels
            self.tokenizer = tokenizer
            self.max_length = max_length
            
        def __len__(self):
            return len(self.texts)
            
        def __getitem__(self, idx):
            text = str(self.texts[idx])
            label = self.labels[idx]
            
            encoding = self.tokenizer(
                text,
                truncation=True,
                padding='max_length',
                max_length=self.max_length,
                return_tensors='pt'
            )
            
            return {
                'input_ids': encoding['input_ids'].flatten(),
                'attention_mask': encoding['attention_mask'].flatten(),
                'labels': torch.tensor(label, dtype=torch.long)
            }
    
    # Training history storage
    training_history = {}
    
    # Function to train a model
    def train_model(train_texts, train_labels, model_obj, tokenizer, name):
        logger.info(f"Training {name} model...")
        
        # Create dataset and dataloader
        dataset = TextDataset(train_texts, train_labels, tokenizer, MAX_LENGTH)
        dataloader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)
        
        # Optimizer
        optimizer = torch.optim.AdamW(model_obj.parameters(), lr=LEARNING_RATE)
        
        # Training loop with early stopping
        model_obj.train()
        best_val_loss = float('inf')
        patience_counter = 0
        epoch_losses = []
        
        for epoch in range(NUM_EPOCHS):
            total_loss = 0
            num_batches = 0
            
            for batch in dataloader:
                optimizer.zero_grad()
                
                input_ids = batch['input_ids'].to(device)
                attention_mask = batch['attention_mask'].to(device)
                labels = batch['labels'].to(device)
                
                outputs = model_obj(
                    input_ids=input_ids,
                    attention_mask=attention_mask,
                    labels=labels
                )
                
                loss = outputs.loss
                loss.backward()
                
                optimizer.step()
                
                total_loss += loss.item()
                num_batches += 1
                
                # Log progress
                if num_batches % 5 == 0:
                    logger.debug(f"Epoch {epoch+1}, Batch {num_batches}, Loss: {loss.item():.4f}")
            
            avg_loss = total_loss / num_batches
            epoch_losses.append(avg_loss)
            logger.info(f"Epoch {epoch+1}/{NUM_EPOCHS}, Loss: {avg_loss:.4f}")
            
            # Early stopping check (we'll just monitor loss)
            if avg_loss < best_val_loss:
                best_val_loss = avg_loss
                patience_counter = 0
                # Save best model state
                best_model_state = model_obj.state_dict().copy()
            else:
                patience_counter += 1
                if patience_counter >= PATIENCE:
                    logger.info(f"Early stopping triggered at epoch {epoch+1}")
                    break
        
        # Restore best model state
        model_obj.load_state_dict(best_model_state)
        
        return epoch_losses
    
    # Train full fine-tuning model
    full_losses = train_model(
        data["train_texts_full"], 
        data["train_labels_full"], 
        model["model"], 
        tokenizer, 
        "full fine-tuning"
    )
    
