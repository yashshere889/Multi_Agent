def run_experiment(data, model):
    # Set device
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    
    # Move models to device
    model['standard'] = model['standard'].to(device)
    model['pinn'] = model['pinn'].to(device)
    
    # Prepare data loaders
    X_train_tensor = torch.FloatTensor(data['X_train']).to(device)
    y_train_tensor = torch.FloatTensor(data['y_train']).unsqueeze(1).to(device)
    X_val_tensor = torch.FloatTensor(data['X_val']).to(device)
    y_val_tensor = torch.FloatTensor(data['y_val']).unsqueeze(1).to(device)
    
    # Optimizers
    opt_standard = optim.Adam(model['standard'].parameters(), lr=LEARNING_RATE)
    opt_pinn = optim.Adam(model['pinn'].parameters(), lr=LEARNING_RATE)
    
    # Training history
    training_history = {
        'standard': [],
        'pinn': []
    }
    
    best_val_loss = float('inf')
    patience_counter = 0
    
    # Checkpoint resume
    ckpt_path = resume_checkpoint()
    if ckpt_path is not None:
        checkpoint = torch.load(ckpt_path)
        model['standard'].load_state_dict(checkpoint['standard_state'])
        model['pinn'].load_state_dict(checkpoint['pinn_state'])
        training_history = checkpoint['history']
        logger.info("Resumed from checkpoint")
    
    # Training loop
    for epoch in range(MAX_EPOCHS):
        # Standard NN training
        model['standard'].train()
        opt_standard.zero_grad()
        y_pred_standard = model['standard'](X_train_tensor)
        loss_standard = nn.MSELoss()(y_pred_standard, y_train_tensor)
        loss_standard.backward()
        opt_standard.step()
        
        # PINN training
        model['pinn'].train()
        opt_pinn.zero_grad()
        y_pred_pinn = model['pinn'](X_train_tensor)
        loss_pinn = model['pinn'].pinn_loss(X_train_tensor, y_train_tensor)
        loss_pinn.backward()
        opt_pinn.step()
        
        # Validation
        model['standard'].eval()
        model['pinn'].eval()
        with torch.no_grad():
            val_pred_standard = model['standard'](X_val_tensor)
            val_loss_standard = nn.MSELoss()(val_pred_standard, y_val_tensor)
            
            val_pred_pinn = model['pinn'](X_val_tensor)
            val_loss_pinn = nn.MSELoss()(val_pred_pinn, y_val_tensor)
        
        # Log progress
        log_progress(
            epoch=epoch,
            standard_train_loss=loss_standard.item(),
            pinn_train_loss=loss_pinn.item(),
            standard_val_loss=val_loss_standard.item(),
            pinn_val_loss=val_loss_pinn.item()
        )
        
        # Store training history
        training_history['standard'].append(loss_standard.item())
        training_history['pinn'].append(loss_pinn.item())
        
        # Early stopping
        current_val_loss = min(val_loss_standard.item(), val_loss_pinn.item())
        if current_val_loss < best_val_loss:
            best_val_loss = current_val_loss
            patience_counter = 0
        else:
            patience_counter += 1
            
        if patience_counter >= PATIENCE:
            logger.info(f"Early stopping at epoch {epoch}")
            break
            
        # Checkpoint
        tmp = begin_checkpoint()
        torch.save({
            'standard_state': model['standard'].state_dict(),
            'pinn_state': model['pinn'].state_dict(),
            'history': training_history
        }, tmp)
        finish_checkpoint(tmp)
    
    # Evaluate on OOD data
    model['standard'].eval()
    model['pinn'].eval()
    with torch.no_grad():
        ood_X_tensor = torch.FloatTensor(data['X_ood']).to(device)
        ood_y_tensor = torch.FloatTensor(data['y_ood']).unsqueeze(1).to(device)
        
        pred_standard = model['standard'](ood_X_tensor)
        pred_pinn = model['pinn'](ood_X_tensor)
        
        mse_standard = nn.MSELoss()(pred_standard, ood_y_tensor).item()
        mse_pinn = nn.MSELoss()(pred_pinn, ood_y_tensor).item()
    
    return {
        'mse_standard': mse_standard,
        'mse_pinn': mse_pinn,
        'training_history': training_history
    }


