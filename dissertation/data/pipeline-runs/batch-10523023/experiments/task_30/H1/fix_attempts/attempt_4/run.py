def build_model(data):
    class StandardNN(nn.Module):
        def __init__(self, input_dim):
            super().__init__()
            self.network = nn.Sequential(
                nn.Linear(input_dim, 64),
                nn.ReLU(),
                nn.Linear(64, 32),
                nn.ReLU(),
                nn.Linear(32, 1)
            )
        
        def forward(self, x):
            return self.network(x)
    
    class PINN(nn.Module):
        def __init__(self, input_dim):
            super().__init__()
            self.network = nn.Sequential(
                nn.Linear(input_dim, 64),
                nn.ReLU(),
                nn.Linear(64, 32),
                nn.ReLU(),
                nn.Linear(32, 1)
            )
            
        def forward(self, x):
            return self.network(x)
            
        def pinn_loss(self, x, y_true):
            # Simple PINN loss with physical constraint
            # Here we add a regularization term to encourage smoothness
            # This is a simplified version of physical constraints
            y_pred = self.forward(x)
            mse_loss = nn.MSELoss()(y_pred, y_true)
            
            # Add gradient-based regularization to enforce smoothness
            # This is a basic form of physical constraint
            if x.requires_grad:
                grad_outputs = torch.ones_like(y_pred)
                gradients = torch.autograd.grad(
                    outputs=y_pred, inputs=x,
                    grad_outputs=grad_outputs,
                    create_graph=True, retain_graph=True
                )[0]
                
                # Regularize gradient magnitude to encourage smooth solutions
                smoothness_penalty = torch.mean(gradients**2)
                return mse_loss + 0.01 * smoothness_penalty
            else:
                return mse_loss
    
    # Create models
    standard_model = StandardNN(data['feature_count'])
    pinn_model = PINN(data['feature_count'])
    
    return {
        'standard': standard_model,
        'pinn': pinn_model,
        'feature_count': data['feature_count']
    }


