def log_progress(**fields: Any) -> None:
    """Append one line to progress.jsonl, and log it.

    Written and flushed immediately, one self-contained JSON object per line,
    so a run that is killed part-way still leaves a readable record of how far
    it got. That is the only trace a preempted job leaves behind — results.json
    is deliberately never written for an incomplete run, because a partial
    result that looks like a finished one is worse than no result at all.

    Call it once per epoch (or per fold, per trial, per condition) with
    whatever describes progress: log_progress(epoch=3, train_loss=0.21).
    """
    record = {"timestamp_utc": datetime.now(timezone.utc).isoformat(), **fields}
    with open(PROGRESS_PATH, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, default=str) + "\n")
        fh.flush()
    logger.info("progress %s", record)


