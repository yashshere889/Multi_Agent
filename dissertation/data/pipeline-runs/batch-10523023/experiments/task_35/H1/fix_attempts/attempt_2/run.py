def train_gam(data, model):
    """Train GAM with Bayesian optimization."""
    X_train = data["X_train"]
    y_train = data["y_train"]
    X_test = data["X_test"]
    y_test = data["y_test"]
    
    @use_named_args(model["gam_search_space"])
    def objective(**params):
        try:
            # Create GAM with specified parameters
            gam = GAM(
                s(0, lam=params['lam']) if X_train.shape[1] > 0 else 0,
                max_iter=params['max_iter'],
                verbose=False
            )
            
            # Fit the model
            gam.fit(X_train, y_train)
            
            # Predict and calculate accuracy
            y_pred = gam.predict(X_test)
            accuracy = accuracy_score(y_test, y_pred)
            
            # Return negative accuracy (since we minimize)
            return -accuracy
        except Exception as e:
            logger.warning(f"GAM training failed with params {params}: {e}")
            return 1.0  # Return high loss if training fails
    
    # Run Bayesian optimization
    res = gp_minimize(objective, model["gam_search_space"], 
                      n_calls=model["budget"], random_state=RANDOM_SEED)
    
    # Train final model with best parameters
    best_params = dict(zip(['lam', 'max_iter'], res.x))
    final_gam = GAM(
        s(0, lam=best_params['lam']) if X_train.shape[1] > 0 else 0,
        max_iter=best_params['max_iter'],
        verbose=False
    )
    
    # Fit final model
    final_gam.fit(X_train, y_train)
    
    # Get predictions and accuracy
    y_pred = final_gam.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    
    # Get training history (approximate)
    history = [abs(x) for x in res.func_vals]  # Convert back to positive accuracy
    
    return {
        "accuracy": accuracy,
        "history": history
    }

