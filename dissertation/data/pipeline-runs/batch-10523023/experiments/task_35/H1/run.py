def load_data() -> Any:
    """Load and preprocess the UCI Adult Census Income dataset."""
    logger = logging.getLogger(__name__)
    
    # Load the dataset
    try:
        df = pd.read_csv("/mnt/fastscratch/users/sgyshere/coder-data/uci_adult_census_income.csv")
        logger.info(f"Loaded dataset with {len(df)} samples")
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise
    
    # Drop the 'fnlwgt' column as it is a sampling weight, not a feature
    df = df.drop(columns=['fnlwgt'])
    
    # Handle missing values represented by '?'
    df = df[df['workclass'] != '?']
    df = df[df['occupation'] != '?']
    df = df[df['native_country'] != '?']
    
    # Encode categorical variables using one-hot encoding
    categorical_features = df.select_dtypes(include=['object']).columns.tolist()
    numerical_features = df.select_dtypes(include=[np.number]).columns.tolist()
    
    # Remove target variable from features
    numerical_features.remove('income')
    categorical_features.remove('income')
    
    # Preprocess the data
    preprocessor = ColumnTransformer(
        transformers=[
            ('num', SimpleImputer(strategy='median'), numerical_features),
            ('cat', OneHotEncoder(drop='first', sparse_output=False), categorical_features)
        ]
    )
    
    # Prepare features and target
    X = df.drop(columns=['income'])
    y = df['income'].apply(lambda x: 1 if x == '>50K' else 0)
    
    # Split the dataset into train/test sets (80/20 split)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, 
        test_size=TEST_SIZE, 
        random_state=RANDOM_SEED, 
        stratify=y
    )
    
    logger.info(f"Train set: {len(X_train)} samples")
    logger.info(f"Test set: {len(X_test)} samples")
    
    return {
        "X_train": X_train,
        "y_train": y_train,
        "X_test": X_test,
        "y_test": y_test,
        "preprocessor": preprocessor
    }


