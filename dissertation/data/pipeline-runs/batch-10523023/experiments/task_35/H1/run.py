def run_experiment(data: Any, model_config: Any) -> dict[str, Any]:
    """Run hyperparameter optimization and evaluate models."""
    logger = logging.getLogger(__name__)
    
    # Initialize random seed for reproducibility
    np.random.seed(RANDOM_SEED)
    # Use the preprocessor to transform data
    X_train_processed = model_config["preprocessor"].fit_transform(data["X_train"])
    X_test_processed = model_config["preprocessor"].transform(data["X_test"])
    
    # Define objective functions for optimization
    @use_named_args(model_config["gam_search_space"])
    def gam_objective(**params):
        # Fit GAM with specified parameters
        gam = GAM(l(0) + s(1) + s(2) + s(3) + s(4) + s(5) + s(6) + s(7) + s(8) + s(9), 
                  lam=params['lam'], alpha=params['alpha'], fit_intercept=params['fit_intercept'])
        gam.fit(X_train_processed, data["y_train"])
        score = gam.score(X_test_processed, data["y_test"])
        return 1 - score  # Minimize error (return 1 - accuracy)
    
    @use_named_args(model_config["rf_search_space"])
    def rf_objective(**params):
        # Fit Random Forest with specified parameters
        rf = RandomForestClassifier(n_estimators=params['n_estimators'],
                                   max_depth=params['max_depth'],
                                   learning_rate=params['learning_rate'],
                                   random_state=RANDOM_SEED)
        rf.fit(X_train_processed, data["y_train"])
        score = rf.score(X_test_processed, data["y_test"])
        return 1 - score  # Minimize error (return 1 - accuracy)
    
    @use_named_args(model_config["gb_search_space"])
    def gb_objective(**params):
        # Fit Gradient Boosting with specified parameters
        gb = GradientBoostingClassifier(n_estimators=params['n_estimators'],
                                       max_depth=params['max_depth'],
                                       learning_rate=params['learning_rate'],
                                       random_state=RANDOM_SEED)
        gb.fit(X_train_processed, data["y_train"])
        score = gb.score(X_test_processed, data["y_test"])
        return 1 - score  # Minimize error (return 1 - accuracy)
    
    # Optimize GAM
    logger.info("Optimizing GAM...")
    gam_result = gp_minimize(gam_objective, model_config["gam_search_space"], 
                           n_calls=model_config["budget"], random_state=RANDOM_SEED)
    
    # Optimize Random Forest
    logger.info("Optimizing Random Forest...")
    rf_result = gp_minimize(rf_objective, model_config["rf_search_space"], 
                          n_calls=model_config["budget"], random_state=RANDOM_SEED)
    
    # Optimize Gradient Boosting
    logger.info("Optimizing Gradient Boosting...")
    gb_result = gp_minimize(gb_objective, model_config["gb_search_space"], 
                          n_calls=model_config["budget"], random_state=RANDOM_SEED)
    
    # Train final models with best parameters
    best_gam = GAM(l(0) + s(1) + s(2) + s(3) + s(4) + s(5) + s(6) + s(7) + s(8) + s(9),
                   lam=gam_result.x[0], alpha=gam_result.x[1], fit_intercept=gam_result.x[2])
    best_gam.fit(X_train_processed, data["y_train"])
    gam_accuracy = best_gam.score(X_test_processed, data["y_test"])
    
    best_rf = RandomForestClassifier(n_estimators=rf_result.x[0],
                                    max_depth=rf_result.x[1],
                                    learning_rate=rf_result.x[2],
                                    random_state=RANDOM_SEED)
    best_rf.fit(X_train_processed, data["y_train"])
    rf_accuracy = best_rf.score(X_test_processed, data["y_test"])
    
    best_gb = GradientBoostingClassifier(n_estimators=gb_result.x[0],
                                        max_depth=gb_result.x[1],
                                        learning_rate=gb_result.x[2],
                                        random_state=RANDOM_SEED)
    best_gb.fit(X_train_processed, data["y_train"])
    gb_accuracy = best_gb.score(X_test_processed, data["y_test"])
    
    return {
        "gam_accuracy": gam_accuracy,
        "rf_accuracy": rf_accuracy,
        "gb_accuracy": gb_accuracy
    }


