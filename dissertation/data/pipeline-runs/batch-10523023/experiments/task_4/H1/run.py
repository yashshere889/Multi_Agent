def build_model(data):
    class MultiTaskModel(nn.Module):
        def __init__(self, input_dim, hidden_dims, n_classes):
            super(MultiTaskModel, self).__init__()
            
            # Shared layers
            layers = []
            prev_dim = input_dim
            for dim in hidden_dims:
                layers.append(nn.Linear(prev_dim, dim))
                layers.append(nn.ReLU())
                layers.append(nn.Dropout(0.2))
                prev_dim = dim
            
            self.shared_layers = nn.Sequential(*layers)
            
            # Task-specific heads
            self.credit_head = nn.Linear(hidden_dims[-1], n_classes)
            self.factor_heads = nn.ModuleList([
                nn.Linear(hidden_dims[-1], 1) for _ in range(3)  # Mkt-RF, SMB, HML
            ])
            
        def forward(self, x):
            shared = self.shared_layers(x)
            credit_pred = self.credit_head(shared)
            factor_preds = [head(shared) for head in self.factor_heads]
            return credit_pred, factor_preds
    
    model = MultiTaskModel(data['input_dim'], HIDDEN_DIMS, data['n_classes'])
    return model


