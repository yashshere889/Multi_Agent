def run_experiment(data, model):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model.to(device)
    
    # Loss functions
    criterion = nn.CrossEntropyLoss()
    factor_criterion = nn.MSELoss()
    
    # Optimizer
    optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)
    
    # Data loaders
    train_loader = DataLoader(data['train'], batch_size=BATCH_SIZE, shuffle=True)
    val_loader = DataLoader(data['val'], batch_size=BATCH_SIZE, shuffle=False)
    
    # Training history tracking
    training_history = {'multi_task': [], 'single_task': []}
    
    # Multi-task training
    best_val_loss = float('inf')
    patience_counter = 0
    epoch = 0
    
    # Checkpointing
    checkpoint_path = resume_checkpoint()
    if checkpoint_path:
        checkpoint = torch.load(checkpoint_path)
        model.load_state_dict(checkpoint['model_state_dict'])
        optimizer.load_state_dict(checkpoint['optimizer_state_dict'])
        epoch = checkpoint['epoch']
        best_val_loss = checkpoint['best_val_loss']
        patience_counter = checkpoint['patience_counter']
        logger.info(f"Resumed training from epoch {epoch}")
    
    while epoch < MAX_EPOCHS:
        model.train()
        total_loss = 0
        
        for batch_x, batch_y in train_loader:
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)
            
            optimizer.zero_grad()
            
            # Forward pass
            credit_pred, factor_preds = model(batch_x)
            
            # Compute losses
            credit_loss = criterion(credit_pred, batch_y.long())
            factor_losses = [factor_criterion(pred.squeeze(), batch_y.float()) for pred in factor_preds]
            total_loss_batch = credit_loss + sum(factor_losses)
            
            # Backward pass
            total_loss_batch.backward()
            optimizer.step()
            
            total_loss += total_loss_batch.item()
        
        avg_loss = total_loss / len(train_loader)
        training_history['multi_task'].append(avg_loss)
        
        # Validation
        model.eval()
        val_loss = 0
        with torch.no_grad():
            for batch_x, batch_y in val_loader:
                batch_x, batch_y = batch_x.to(device), batch_y.to(device)
                credit_pred, factor_preds = model(batch_x)
                credit_loss = criterion(credit_pred, batch_y.long())
                factor_losses = [factor_criterion(pred.squeeze(), batch_y.float()) for pred in factor_preds]
                val_loss += (credit_loss + sum(factor_losses)).item()
        
        val_loss /= len(val_loader)
        
        log_progress(epoch=epoch, train_loss=avg_loss, val_loss=val_loss)
        
        # Early stopping
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            # Save best model
            tmp = begin_checkpoint()
            torch.save({
                'model_state_dict': model.state_dict(),
                'optimizer_state_dict': optimizer.state_dict(),
                'epoch': epoch,
                'best_val_loss': best_val_loss,
                'patience_counter': patience_counter
            }, tmp)
            finish_checkpoint(tmp)
        else:
            patience_counter += 1
            if patience_counter >= PATIENCE:
                logger.info("Early stopping triggered")
                break
                
        epoch += 1
    
    # Final evaluation on test set
    model.eval()
    test_predictions = []
    test_labels = []
    
    with torch.no_grad():
        for batch_x, batch_y in DataLoader(data['test'], batch_size=BATCH_SIZE, shuffle=False):
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)
            credit_pred, _ = model(batch_x)
            probs = torch.softmax(credit_pred, dim=1)[:, 1]  # Probability of positive class
            test_predictions.extend(probs.cpu().numpy())
            test_labels.extend(batch_y.cpu().numpy())
    
    return {
        'predictions': test_predictions,
        'labels': test_labels,
        'training_history': training_history
    }


