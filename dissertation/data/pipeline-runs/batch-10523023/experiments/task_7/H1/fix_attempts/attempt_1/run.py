def run_experiment(data, model):
    """Run the experiment comparing ensemble methods."""
    logger.info("Running experiment...")
    
    # Initialize results storage
    results = {
        'bootstrap_predictions': [],
        'deep_ensemble_predictions': [],
        'actual_returns': [],
        'input_variance': [],
        'test_indices': []
    }
    
    # Get data
    X_train = data['X_train']
    X_val = data['X_val']
    X_test = data['X_test']
    y_train = data['y_train']
    y_val = data['y_val']
    y_test = data['y_test']
    input_variance = model['input_variance']
    test_indices = model['test_indices']
    
    # Store actual returns for test set
    results['actual_returns'] = y_test.tolist()
    results['input_variance'] = input_variance.tolist()
    results['test_indices'] = test_indices.tolist()
    
    # Bootstrap Resampling
    logger.info(f"Performing bootstrap resampling with {BOOTSTRAP_SAMPLES} samples...")
    bootstrap_predictions = []
    
    for i in range(BOOTSTRAP_SAMPLES):
        # Generate bootstrap sample indices
        n_samples = len(X_train)
        bootstrap_indices = np.random.choice(n_samples, size=n_samples, replace=True)
        
        # Create bootstrap samples
        X_bootstrap = X_train[bootstrap_indices]
        y_bootstrap = y_train[bootstrap_indices]
        
        # Fit linear regression model
        lr_model = LinearRegression()
        lr_model.fit(X_bootstrap, y_bootstrap)
        
        # Predict on test set
        pred = lr_model.predict(X_test)
        bootstrap_predictions.append(pred)
        
        # Log progress
        if i % 10 == 0:
            logger.info(f"Bootstrap sample {i+1}/{BOOTSTRAP_SAMPLES}")
    
    # Store bootstrap predictions
    results['bootstrap_predictions'] = np.array(bootstrap_predictions).T.tolist()
    
    # Deep Ensemble
    logger.info(f"Training deep ensemble with {DEEP_ENSEMBLE_COUNT} networks...")
    
    # Training history for deep ensemble
    training_histories = {}
    
    # For each neural network in the ensemble
    for i, nn_model in enumerate(model['neural_networks']):
        logger.info(f"Training neural network {i+1}/{DEEP_ENSEMBLE_COUNT}")
        
        # Create PyTorch datasets
        train_dataset = TensorDataset(torch.FloatTensor(X_train), torch.FloatTensor(y_train).unsqueeze(1))
        val_dataset = TensorDataset(torch.FloatTensor(X_val), torch.FloatTensor(y_val).unsqueeze(1))
        
        train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=BATCH_SIZE, shuffle=False)
        
        # Define optimizer and loss function
        optimizer = optim.Adam(nn_model.parameters(), lr=LEARNING_RATE)
        criterion = nn.MSELoss()
        
        # Training history
        train_losses = []
        val_losses = []
        
        # Early stopping
        best_val_loss = float('inf')
        patience_counter = 0
        
        # Checkpointing
        checkpoint_path = resume_checkpoint()
        if checkpoint_path is not None:
            nn_model.load_state_dict(torch.load(checkpoint_path))
            logger.info(f"Resumed training from checkpoint")
        
        # Training loop
        for epoch in range(MAX_EPOCHS):
            # Training phase
            nn_model.train()
            total_train_loss = 0
            for x_batch, y_batch in train_loader:
                optimizer.zero_grad()
                outputs = nn_model(x_batch)
                loss = criterion(outputs, y_batch)
                loss.backward()
                optimizer.step()
                total_train_loss += loss.item()
            
            avg_train_loss = total_train_loss / len(train_loader)
            train_losses.append(avg_train_loss)
            
            # Validation phase
            nn_model.eval()
            total_val_loss = 0
            with torch.no_grad():
                for x_batch, y_batch in val_loader:
                    outputs = nn_model(x_batch)
                    loss = criterion(outputs, y_batch)
                    total_val_loss += loss.item()
            
            avg_val_loss = total_val_loss / len(val_loader)
            val_losses.append(avg_val_loss)
            
            # Early stopping
            if avg_val_loss < best_val_loss:
                best_val_loss = avg_val_loss
                patience_counter = 0
                # Save checkpoint
                tmp = begin_checkpoint()
                torch.save(nn_model.state_dict(), tmp)
                finish_checkpoint(tmp)
            else:
                patience_counter += 1
                if patience_counter >= PATIENCE:
                    logger.info(f"Early stopping at epoch {epoch+1}")
                    break
            
            # Log progress
            if epoch % 10 == 0:
                log_progress(epoch=epoch, train_loss=avg_train_loss, val_loss=avg_val_loss)
        
        # Store training history
        training_histories[f'nn_{i}'] = train_losses
        
        # Make predictions with this model
        nn_model.eval()
        with torch.no_grad():
            test_tensor = torch.FloatTensor(X_test)
            pred = nn_model(test_tensor).numpy().flatten()
            results['deep_ensemble_predictions'].append(pred)
    
    # Convert deep ensemble predictions to proper format
    results['deep_ensemble_predictions'] = np.array(results['deep_ensemble_predictions']).T.tolist()
    
    # Add training histories to results
    results['training_history'] = training_histories
    
    return results


