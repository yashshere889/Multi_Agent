def evaluate(experiment_output):
    """Evaluate the experiment results."""
    logger.info("Evaluating experiment results...")
    
    # Extract data
    bootstrap_preds = np.array(experiment_output['bootstrap_predictions'])
    deep_ensemble_preds = np.array(experiment_output['deep_ensemble_predictions'])
    actual_returns = np.array(experiment_output['actual_returns'])
    input_variance = np.array(experiment_output['input_variance'])
    
    # Calculate forecast errors
    bootstrap_errors = np.abs(actual_returns - bootstrap_preds.mean(axis=1))
    deep_ensemble_errors = np.abs(actual_returns - np.array(deep_ensemble_preds).mean(axis=1))
    
    # Calculate ensemble spreads
    bootstrap_spread = np.std(bootstrap_preds, axis=1)
    deep_ensemble_spread = np.std(deep_ensemble_preds, axis=1)
    
    # Calculate correlations
    bootstrap_correlation = np.corrcoef(bootstrap_spread, bootstrap_errors)[0, 1]
    deep_ensemble_correlation = np.corrcoef(deep_ensemble_spread, deep_ensemble_errors)[0, 1]
    input_variance_correlation = np.corrcoef(input_variance, bootstrap_errors)[0, 1]
    
    # Determine which method shows stronger correlation
    if bootstrap_correlation > input_variance_correlation:
        stronger_method = "bootstrap"
    elif deep_ensemble_correlation > input_variance_correlation:
        stronger_method = "deep_ensemble"
    else:
        stronger_method = "none"
    
    # Evaluate success criteria
    meets_success_criteria = False
    success_notes = ""
    
    if bootstrap_correlation > input_variance_correlation and deep_ensemble_correlation > input_variance_correlation:
        if bootstrap_correlation > deep_ensemble_correlation:
            meets_success_criteria = True
            success_notes = f"Bootstrap resampling shows stronger correlation ({bootstrap_correlation:.4f}) with forecast error than input variance ({input_variance_correlation:.4f}), and deep ensemble also shows stronger correlation ({deep_ensemble_correlation:.4f}). Bootstrap method is strongest."
        else:
            meets_success_criteria = True
            success_notes = f"Deep ensemble shows stronger correlation ({deep_ensemble_correlation:.4f}) with forecast error than input variance ({input_variance_correlation:.4f}), and bootstrap also shows stronger correlation ({bootstrap_correlation:.4f}). Deep ensemble method is strongest."
    elif bootstrap_correlation > input_variance_correlation or deep_ensemble_correlation > input_variance_correlation:
        stronger = "bootstrap" if bootstrap_correlation > input_variance_correlation else "deep_ensemble"
        meets_success_criteria = True
        success_notes = f"{stronger.capitalize()} resampling shows stronger correlation with forecast error than input variance."
    else:
        meets_success_criteria = False
        success_notes = "Neither ensemble method shows stronger correlation with forecast error than input variance."
    
    # Return results
    return {
        "bootstrap_correlation": float(bootstrap_correlation),
        "deep_ensemble_correlation": float(deep_ensemble_correlation),
        "input_variance_correlation": float(input_variance_correlation),
        "stronger_method": stronger_method,
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes,
        "training_history": experiment_output.get("training_history", {})
    }


