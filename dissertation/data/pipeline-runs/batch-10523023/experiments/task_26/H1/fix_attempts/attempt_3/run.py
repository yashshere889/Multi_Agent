def run_experiment(data: Any, model_config: Any) -> dict[str, Any]:
    """Train and evaluate BERT models on each document group."""
    logger = logging.getLogger(__name__)
    
    # Define a custom dataset class
    class TextDataset(Dataset):
        def __init__(self, texts, labels, tokenizer, max_length):
            self.texts = texts
            self.labels = labels
            self.tokenizer = tokenizer
            self.max_length = max_length
            
        def __len__(self):
            return len(self.texts)
            
        def __getitem__(self, idx):
            text = str(self.texts[idx])
            label = self.labels[idx]
            
            encoding = self.tokenizer(
                text,
                truncation=True,
                padding='max_length',
                max_length=self.max_length,
                return_tensors='pt'
            )
            
            return {
                'input_ids': encoding['input_ids'].flatten(),
                'attention_mask': encoding['attention_mask'].flatten(),
                'labels': torch.tensor(label, dtype=torch.long)
            }
    
    # Function to train a model
    def train_model(train_df, model, tokenizer, device, categories):
        # Map category names to indices
        category_to_idx = {cat: idx for idx, cat in enumerate(categories)}
        labels = [category_to_idx[cat] for cat in train_df['category']]
        
        # Create dataset and dataloader
        dataset = TextDataset(train_df['text'].tolist(), labels, tokenizer, MAX_LENGTH)
        dataloader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)
        
        # Move model to device
        model.to(device)
        
        # Optimizer and scheduler
        optimizer = AdamW(model.parameters(), lr=LEARNING_RATE)
        total_steps = len(dataloader) * EPOCHS
        scheduler = get_linear_schedule_with_warmup(
            optimizer,
            num_warmup_steps=0,
            num_training_steps=total_steps
        )
        
        # Training loop
        model.train()
        for epoch in range(EPOCHS):
            total_loss = 0
            progress_bar = tqdm(dataloader, desc=f"Epoch {epoch+1}/{EPOCHS}")
            for batch in progress_bar:
                optimizer.zero_grad()
                
                input_ids = batch['input_ids'].to(device)
                attention_mask = batch['attention_mask'].to(device)
                labels = batch['labels'].to(device)
                
                outputs = model(input_ids=input_ids, attention_mask=attention_mask, labels=labels)
                loss = outputs.loss
                loss.backward()
                
                optimizer.step()
                scheduler.step()
                
                total_loss += loss.item()
                progress_bar.set_postfix({'loss': f'{loss.item():.4f}'})
        
        return model
    
    # Function to evaluate a model
    def evaluate_model(test_df, model, tokenizer, device, categories):
        # Map category names to indices
        category_to_idx = {cat: idx for idx, cat in enumerate(categories)}
        labels = [category_to_idx[cat] for cat in test_df['category']]
        
        # Create dataset and dataloader
        dataset = TextDataset(test_df['text'].tolist(), labels, tokenizer, MAX_LENGTH)
        dataloader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=False)
        
        # Evaluation
        model.eval()
        predictions = []
        true_labels = []
        
        with torch.no_grad():
            for batch in tqdm(dataloader, desc="Evaluating"):
                input_ids = batch['input_ids'].to(device)
                attention_mask = batch['attention_mask'].to(device)
                labels = batch['labels'].to(device)
                
                outputs = model(input_ids=input_ids, attention_mask=attention_mask)
                logits = outputs.logits
                preds = torch.argmax(logits, dim=-1)
                
                predictions.extend(preds.cpu().numpy())
                true_labels.extend(labels.cpu().numpy())
        
        accuracy = accuracy_score(true_labels, predictions)
        return accuracy
    
    # Get device
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    logger.info(f"Using device: {device}")
    
    # Train and evaluate models for each group
    results = {}
    
    # Short vocabulary-rich group
    logger.info("Training model for short vocabulary-rich group...")
    short_model = train_model(
        data['short_voc_rich'], 
        model_config['model'].copy(), 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    short_accuracy = evaluate_model(
        data['short_voc_rich'], 
        short_model, 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    results['short_voc_rich_accuracy'] = short_accuracy
    
    # Long low-vocabulary group
    logger.info("Training model for long low-vocabulary group...")
    long_model = train_model(
        data['long_low_voc'], 
        model_config['model'].copy(), 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    long_accuracy = evaluate_model(
        data['long_low_voc'], 
        long_model, 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    results['long_low_voc_accuracy'] = long_accuracy
    
    # Original vocabulary-rich group
    logger.info("Training model for original vocabulary-rich group...")
    orig_model = train_model(
        data['orig_voc_rich'], 
        model_config['model'].copy(), 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    orig_accuracy = evaluate_model(
        data['orig_voc_rich'], 
        orig_model, 
        model_config['tokenizer'], 
        device, 
        model_config['categories']
    )
    results['orig_voc_rich_accuracy'] = orig_accuracy
    
    return results


