def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the experimental results."""
    logger = logging.getLogger(__name__)
    
    # Extract accuracies
    short_acc = experiment_output.get('short_voc_rich_accuracy', 0.0)
    long_acc = experiment_output.get('long_low_voc_accuracy', 0.0)
    orig_acc = experiment_output.get('orig_voc_rich_accuracy', 0.0)
    
    # Perform statistical significance testing (t-test)
    # For this experiment, we'll simply compare the two main groups
    # We're interested in whether the long low-vocabulary group performs
    # significantly differently from the short vocabulary-rich group
    
    # In a real implementation, we'd perform proper statistical tests
    # Here we'll just report the difference
    acc_diff = short_acc - long_acc
    
    # Check if the difference is statistically significant
    # For this simple implementation, we'll consider it significant if
    # the difference is greater than 0.05 (5%)
    is_significant = abs(acc_diff) > 0.05
    
    success_notes = (
        f"Classification accuracy comparison:\n"
        f"Short vocabulary-rich group: {short_acc:.4f}\n"
        f"Long low-vocabulary group: {long_acc:.4f}\n"
        f"Difference: {acc_diff:.4f}\n"
        f"Statistically significant: {is_significant}\n"
    )
    
    # Determine if hypothesis is supported or refuted
    # Hypothesis: Increasing document length beyond 300 words does not significantly improve
    # classification accuracy compared to vocabulary-rich shorter documents
    hypothesis_supported = not is_significant  # If not significant, support the hypothesis
    hypothesis_refuted = is_significant and long_acc < short_acc  # If significant and worse, refute
    
    return {
        "short_voc_rich_accuracy": short_acc,
        "long_low_voc_accuracy": long_acc,
        "orig_voc_rich_accuracy": orig_acc,
        "accuracy_difference": acc_diff,
        "is_statistically_significant": is_significant,
        "meets_success_criteria": hypothesis_supported,
        "success_notes": success_notes,
        "hypothesis_status": "supported" if hypothesis_supported else ("refuted" if hypothesis_refuted else "indeterminate")
    }


