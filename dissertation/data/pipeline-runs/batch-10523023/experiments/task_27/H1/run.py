class NTM(nn.Module):
    """Neural Topic Model with variance-invariance-covariance regularization."""
    
    def __init__(self, vocab_size, hidden_dim, latent_dim, variance_weight, invariance_weight, covariance_weight):
        super(NTM, self).__init__()
        self.vocab_size = vocab_size
        self.hidden_dim = hidden_dim
        self.latent_dim = latent_dim
        self.variance_weight = variance_weight
        self.invariance_weight = invariance_weight
        self.covariance_weight = covariance_weight
        
        # Encoder
        self.encoder = nn.Sequential(
            nn.Linear(vocab_size, hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU()
        )
        
        # Latent space parameters
        self.mu_layer = nn.Linear(hidden_dim, latent_dim)
        self.log_var_layer = nn.Linear(hidden_dim, latent_dim)
        
        # Decoder
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(hidden_dim, vocab_size),
            nn.Softmax(dim=1)
        )
        
    def encode(self, x):
        h = self.encoder(x)
        mu = self.mu_layer(h)
        log_var = self.log_var_layer(h)
        return mu, log_var
    
    def reparameterize(self, mu, log_var):
        std = torch.exp(0.5 * log_var)
        eps = torch.randn_like(std)
        return mu + eps * std
    
    def decode(self, z):
        return self.decoder(z)
    
    def forward(self, x):
        mu, log_var = self.encode(x)
        z = self.reparameterize(mu, log_var)
        x_recon = self.decode(z)
        
        # Reconstruction loss
        recon_loss = -torch.sum(x * torch.log(x_recon + 1e-8), dim=1).mean()
        
        # Variance regularization
        variance_loss = self.variance_weight * torch.mean(torch.var(mu, dim=0))
        
        # Invariance regularization (encourage similar representations for similar documents)
        # This is a simplified version - in practice, you might want to use pairwise similarities
        invariance_loss = self.invariance_weight * torch.mean(torch.norm(mu[:-1] - mu[1:], dim=1))
        
        # Covariance regularization (encourage independence of latent dimensions)
        # This is a simplified version - in practice, you might want to use more sophisticated methods
        covariance_loss = self.covariance_weight * torch.mean(torch.abs(torch.cov(mu.T)))
        
        return recon_loss, variance_loss, invariance_loss, covariance_loss

def simulate_citation_peaks(topic_distributions):
    """Simulate citation peaks based on topic prevalence changes over time."""
    # For this simulation, we'll identify periods of rapid increase in topic weights
    # as citation peaks. We'll use a sliding window approach.
    
    # Convert to numpy array for easier manipulation
    topic_array = np.array(topic_distributions)
    
    # Calculate topic prevalence over time (sum of topic weights for each topic)
    topic_prevalence = np.sum(topic_array, axis=0)
    
    # Identify peaks by looking for rapid increases in topic weights
    # We'll use a simple approach: find local maxima in topic prevalence
    peaks = []
    for i in range(len(topic_prevalence)):
        if i == 0:
            # First element - check if it's a peak
            if topic_prevalence[i] > topic_prevalence[i+1]:
                peaks.append(i)
        elif i == len(topic_prevalence) - 1:
            # Last element - check if it's a peak
            if topic_prevalence[i] > topic_prevalence[i-1]:
                peaks.append(i)
        else:
            # Middle elements - check if it's a peak
            if topic_prevalence[i] > topic_prevalence[i-1] and topic_prevalence[i] > topic_prevalence[i+1]:
                peaks.append(i)
    
    # For our purposes, we'll define citation peaks as the top 3 topics with highest prevalence
    # and also include some additional peaks based on rapid changes
    top_topics = np.argsort(topic_prevalence)[-3:]
    peaks.extend(top_topics.tolist())
    
    # Remove duplicates and sort
    peaks = sorted(list(set(peaks)))
    
    return peaks

def calculate_mae(citation_peaks, topic_distributions):
    """Calculate Mean Absolute Error between actual topic shift times and citation peak times."""
    # For this experiment, we'll simplify the calculation
    # Since we don't have actual timestamps, we'll use a proxy:
    # the average distance between topic distributions and citation peaks
    
    if not citation_peaks:
        return float('inf')
    
    # Calculate mean absolute deviation from citation peaks
    # This is a simplified approach - in reality, you'd need actual time series data
    # For now, we'll just return a normalized value based on topic distribution spread
    topic_array = np.array(topic_distributions)
    mean_topic_dist = np.mean(topic_array, axis=0)
    
    # Calculate the average distance from the mean topic distribution
    distances = []
    for dist in topic_distributions:
        dist_array = np.array(dist)
        distance = np.mean(np.abs(dist_array - mean_topic_dist))
        distances.append(distance)
    
    return np.mean(distances)

def calculate_precision_at_k(citation_peaks, topic_distributions):
    """Calculate Precision at k for detecting topic shifts within a window of citation peaks."""
    # Simplified precision calculation
    # We'll consider a topic shift detected if the topic weight is among the top topics
    # that are identified as citation peaks
    
    if not citation_peaks:
        return 0.0
    
    # For each document, check if its dominant topic is among citation peaks
    correct_predictions = 0
    total_predictions = len(topic_distributions)
    
    for dist in topic_distributions:
        # Find the dominant topic (highest probability)
        dominant_topic = np.argmax(dist)
        if dominant_topic in citation_peaks:
            correct_predictions += 1
    
    return correct_predictions / total_predictions if total_predictions > 0 else 0.0

def calculate_recall_at_k(citation_peaks, topic_distributions):
    """Calculate Recall at k for detecting topic shifts within a window of citation peaks."""
    # Simplified recall calculation
    # We'll consider recall as the proportion of citation peaks that are correctly identified
    
    if not citation_peaks:
        return 0.0
    
    # For each citation peak, check if it's among the dominant topics of documents
    found_peaks = 0
    total_peaks = len(citation_peaks)
    
    # Find the dominant topics for each document
    dominant_topics = [np.argmax(dist) for dist in topic_distributions]
    
    # Count how many citation peaks are among dominant topics
    for peak in citation_peaks:
        if peak in dominant_topics:
            found_peaks += 1
    
    return found_peaks / total_peaks if total_peaks > 0 else 0.0


