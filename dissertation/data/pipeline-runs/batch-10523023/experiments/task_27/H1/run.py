    lda_model = model_config["lda_model"]
    
    # Get topic distributions for each document
    lda_topic_distributions = []
    for i, doc in enumerate(data["corpus"]):
        topic_dist = lda_model.get_document_topics(doc)
        # Convert to dense vector
        dense_dist = [0.0] * N_TOPICS
        for topic_id, prob in topic_dist:
            dense_dist[topic_id] = prob
        lda_topic_distributions.append(dense_dist)
    
    # Train NTM model
    logger.info("Training NTM model...")
    ntm_model = model_config["ntm_model"]
    ntm_optimizer = optim.Adam(ntm_model.parameters(), lr=NTM_LEARNING_RATE)
    
