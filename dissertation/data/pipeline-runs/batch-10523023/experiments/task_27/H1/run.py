def load_data() -> Any:
    """Load and preprocess the 20 Newsgroups dataset for topic modeling."""
    logger = logging.getLogger(__name__)
    
    # Load the dataset
    data_path = "/mnt/fastscratch/users/sgyshere/coder-data/twenty_newsgroups_document_text_category_classification_train.csv"
    try:
        df = pd.read_csv(data_path)
        logger.info(f"Loaded dataset with {len(df)} samples from {data_path}")
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise
    
    # Filter documents to science-related categories
    science_categories = ['sci.med', 'sci.space', 'comp.graphics']
    filtered_df = df[df['category'].isin(science_categories)]
    
    # Preprocess text: lowercase, remove punctuation, tokenize, remove stopwords
    def preprocess_text(text):
        # Convert to lowercase
        text = text.lower()
        # Remove punctuation
        text = re.sub(r'[^\w\s]', '', text)
        # Tokenize
        tokens = text.split()
        # Remove stopwords (simple list for demonstration)
        stopwords = set(['the', 'a', 'an', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for', 'of', 'with', 'by', 'is', 'are', 'was', 'were', 'be', 'been', 'have', 'has', 'had', 'do', 'does', 'did', 'will', 'would', 'could', 'should', 'may', 'might', 'must', 'can'])
        tokens = [token for token in tokens if token not in stopwords]
        return ' '.join(tokens)
    
    filtered_df['processed_text'] = filtered_df['text'].apply(preprocess_text)
    
    # Convert documents to bag-of-words format
    vectorizer = CountVectorizer(max_features=10000, min_df=2, max_df=0.5)
    bow_matrix = vectorizer.fit_transform(filtered_df['processed_text'])
    
    # Create dictionary for Gensim
    texts = [doc.split() for doc in filtered_df['processed_text']]
    dictionary = Dictionary(texts)
    corpus = [dictionary.doc2bow(text) for text in texts]
    
    logger.info(f"Filtered dataset to {len(filtered_df)} science-related documents")
    logger.info(f"Vocabulary size: {len(vectorizer.vocabulary_)}")
    
    return {
        "documents": filtered_df['processed_text'].tolist(),
        "bow_matrix": bow_matrix,
        "corpus": corpus,
        "dictionary": dictionary,
        "original_df": filtered_df
    }


