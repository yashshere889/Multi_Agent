def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run the full experiment pipeline."""
    logger.info("Starting experiment...")
    
    # Set random seed for reproducibility
    random.seed(RANDOM_SEED)
    np.random.seed(RANDOM_SEED)
    
    # Prepare data
    train_texts = data["train_texts"]
    train_labels = data["train_labels"]
    test_texts = data["test_texts"]
    test_labels = data["test_labels"]
    
    # Create bootstrap samples
    logger.info(f"Creating {N_BOOTSTRAPS} bootstrap samples...")
    bootstrap_samples = []
    n_samples = len(train_texts)
    
    for i in range(N_BOOTSTRAPS):
        indices = np.random.choice(n_samples, size=n_samples, replace=True)
        sampled_texts = [train_texts[j] for j in indices]
        sampled_labels = [train_labels[j] for j in indices]
        bootstrap_samples.append((sampled_texts, sampled_labels))
    
    # Apply TF-IDF vectorization to all bootstrap samples
    logger.info("Applying TF-IDF vectorization...")
    vectorizer = TfidfVectorizer(max_features=5000, stop_words='english')
    
    # Fit vectorizer on full training set for consistent feature space
    full_train_tfidf = vectorizer.fit_transform(train_texts)
    
    # Transform all bootstrap samples
    bootstrap_vectors = []
    for texts, _ in bootstrap_samples:
        vecs = vectorizer.transform(texts)
        bootstrap_vectors.append(vecs)
    
    # Apply feature selection to each bootstrap sample
    logger.info("Applying feature selection to bootstrap samples...")
    feature_indices_list = []
    feature_names_list = []
    
    for i, (texts, labels) in enumerate(bootstrap_samples):
        # Use the fitted vectorizer to transform
        X = bootstrap_vectors[i]
        y = np.array(labels)
        
        # Apply feature selection
        selector = SelectKBest(score_func=chi2, k=FEATURE_SELECTION_K)
        X_selected = selector.fit_transform(X, y)
        
        # Get selected feature indices and names
        selected_features = selector.get_support(indices=True)
        feature_indices_list.append(selected_features)
        
        # Get feature names for debugging
        feature_names = [vectorizer.get_feature_names_out()[idx] for idx in selected_features]
        feature_names_list.append(feature_names)
    
    # Calculate Consistency Index for each feature
    logger.info("Calculating Consistency Index...")
    # For each feature, count how many times it appears across bootstrap samples
    feature_counts = defaultdict(int)
    for indices in feature_indices_list:
        for idx in indices:
            feature_counts[idx] += 1
    
    # Normalize counts to get consistency scores (0-1)
    consistency_scores = {}
    for idx, count in feature_counts.items():
        consistency_scores[idx] = count / N_BOOTSTRAPS
    
    # Sort features by consistency score
    sorted_features = sorted(consistency_scores.items(), key=lambda x: x[1], reverse=True)
    
    # Split into high and low consistency groups
    num_high_consistent = len(sorted_features) // 2
    high_consistent_indices = [idx for idx, _ in sorted_features[:num_high_consistent]]
    low_consistent_indices = [idx for idx, _ in sorted_features[num_high_consistent:]]
    
    # Train classifiers on different feature sets
    logger.info("Training classifiers...")
    
    # Full feature set
    X_full = full_train_tfidf
    y_full = np.array(train_labels)
    
    # High consistency features
    high_consistent_mask = np.zeros(full_train_tfidf.shape[1], dtype=bool)
    high_consistent_mask[high_consistent_indices] = True
    X_high = full_train_tfidf[:, high_consistent_mask]
    
    # Low consistency features
    low_consistent_mask = np.zeros(full_train_tfidf.shape[1], dtype=bool)
    low_consistent_mask[low_consistent_indices] = True
    X_low = full_train_tfidf[:, low_consistent_mask]
    
    # Test set transformation
    test_tfidf = vectorizer.transform(test_texts)
    X_test_full = test_tfidf
    X_test_high = test_tfidf[:, high_consistent_mask]
    X_test_low = test_tfidf[:, low_consistent_mask]
    
    # Train classifiers
    clf_full = LogisticRegression(random_state=RANDOM_SEED, max_iter=1000)
    clf_full.fit(X_full, y_full)
    pred_full = clf_full.predict(X_test_full)
    acc_full = accuracy_score(test_labels, pred_full)
    
    clf_high = LogisticRegression(random_state=RANDOM_SEED, max_iter=1000)
    clf_high.fit(X_high, y_full)
    pred_high = clf_high.predict(X_test_high)
    acc_high = accuracy_score(test_labels, pred_high)
    
    clf_low = LogisticRegression(random_state=RANDOM_SEED, max_iter=1000)
    clf_low.fit(X_low, y_full)
    pred_low = clf_low.predict(X_test_low)
    acc_low = accuracy_score(test_labels, pred_low)
    
    # Calculate correlation between consistency scores and accuracies
    # We'll use the mean consistency score of features in each set
    mean_consistency_high = np.mean([consistency_scores[idx] for idx in high_consistent_indices])
    mean_consistency_low = np.mean([consistency_scores[idx] for idx in low_consistent_indices])
    
    consistency_scores_for_corr = [mean_consistency_low, mean_consistency_high]
    accuracies_for_corr = [acc_low, acc_full]  # Using full model as baseline
    
    # Return results
    return {
        "accuracies": {
            "low_consistency": acc_low,
            "high_consistency": acc_high,
            "full_features": acc_full
        },
        "consistency_scores": {
            "low_consistency": mean_consistency_low,
            "high_consistency": mean_consistency_high,
            "full_features": 1.0  # Full features have perfect consistency (all selected)
        },
        "correlation_data": {
            "consistency_scores": consistency_scores_for_corr,
            "accuracies": accuracies_for_corr
        }
    }


