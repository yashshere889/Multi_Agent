def expected_calibration_error(y_true: np.ndarray, y_prob: np.ndarray, n_bins: int) -> float:
    """
    Compute Expected Calibration Error (ECE) using binning approach.
    This is a standard implementation based on the definition in the literature.
    """
    # Create bins
    bin_boundaries = np.linspace(0, 1, n_bins + 1)
    bin_lowers = bin_boundaries[:-1]
    bin_uppers = bin_boundaries[1:]
    
    # Find which bin each prediction belongs to
    pred_bin_indices = np.digitize(y_prob, bin_uppers, right=True)
    
    # Adjust indices to be within valid range
    pred_bin_indices = np.minimum(pred_bin_indices, n_bins - 1)
    
    # Initialize ECE components
    ece = 0.0
    total_count = len(y_true)
    
    # For each bin, compute accuracy and confidence
    for bin_lower, bin_upper in zip(bin_lowers, bin_uppers):
        # Find samples in this bin
        in_bin = np.logical_and(pred_bin_indices >= bin_lower, pred_bin_indices < bin_upper)
        bin_count = np.sum(in_bin)
        
        if bin_count > 0:
            # Compute accuracy and average confidence for this bin
            bin_accuracy = np.mean(y_true[in_bin])
            bin_confidence = np.mean(y_prob[in_bin])
            
            # Accumulate weighted difference
            ece += (bin_count / total_count) * abs(bin_accuracy - bin_confidence)
    
    return ece


