def train_and_evaluate_models(dataset_data: Dict, models: Dict, market_name: str, device: torch.device) -> Dict:
    """
    Train and evaluate both models on a given dataset.
    
    Args:
        dataset_data: Dictionary containing train/val/test data for a market
        models: Dictionary containing both model instances
        market_name: Name of the market ('US' or 'Europe')
        device: Device to run training on
        
    Returns:
        Dictionary containing training and evaluation results
    """
    # Prepare data
    train_data = torch.tensor(dataset_data['train'], dtype=torch.float32)
    val_data = torch.tensor(dataset_data['val'], dtype=torch.float32)
    test_data = torch.tensor(dataset_data['test'], dtype=torch.float32)
    
    # Create data loaders
    train_loader = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(train_data, train_data),
        batch_size=BATCH_SIZE,
        shuffle=True
    )
    
    val_loader = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(val_data, val_data),
        batch_size=BATCH_SIZE,
        shuffle=False
    )
    
    test_loader = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(test_data, test_data),
        batch_size=BATCH_SIZE,
        shuffle=False
    )
    
    # Move models to device
    ftaxlstm_model = models['ftaxlstm'].to(device)
    lstm_model = models['lstm'].to(device)
    
    # Define loss function and optimizer
    criterion = nn.MSELoss()
    ftaxlstm_optimizer = torch.optim.Adam(ftaxlstm_model.parameters(), lr=LEARNING_RATE)
    lstm_optimizer = torch.optim.Adam(lstm_model.parameters(), lr=LEARNING_RATE)
    
    # Training loop for FTA-XLSTM
    logger.info(f"Training FTA-XLSTM on {market_name} dataset")
    ftaxlstm_model.train()
    for epoch in range(EPOCHS):
        for batch_idx, (data, target) in enumerate(train_loader):
            data, target = data.to(device), target.to(device)
            ftaxlstm_optimizer.zero_grad()
            output = ftaxlstm_model(data)
            loss = criterion(output, target.unsqueeze(1))
            loss.backward()
            ftaxlstm_optimizer.step()
    
    # Training loop for LSTM
    logger.info(f"Training LSTM on {market_name} dataset")
    lstm_model.train()
    for epoch in range(EPOCHS):
        for batch_idx, (data, target) in enumerate(train_loader):
            data, target = data.to(device), target.to(device)
            lstm_optimizer.zero_grad()
            output = lstm_model(data)
            loss = criterion(output, target.unsqueeze(1))
            loss.backward()
            lstm_optimizer.step()
    
    # Evaluation
    ftaxlstm_model.eval()
    lstm_model.eval()
    
    # Evaluate FTA-XLSTM
    ftaxlstm_predictions = []
    ftaxlstm_targets = []
    with torch.no_grad():
        for data, target in test_loader:
            data, target = data.to(device), target.to(device)
            output = ftaxlstm_model(data)
            ftaxlstm_predictions.extend(output.cpu().numpy())
            ftaxlstm_targets.extend(target.cpu().numpy())
    
    # Evaluate LSTM
    lstm_predictions = []
    lstm_targets = []
    with torch.no_grad():
        for data, target in test_loader:
            data, target = data.to(device), target.to(device)
            output = lstm_model(data)
            lstm_predictions.extend(output.cpu().numpy())
            lstm_targets.extend(target.cpu().numpy())
    
    # Calculate metrics
    ftaxlstm_mae = np.mean(np.abs(np.array(ftaxlstm_predictions) - np.array(ftaxlstm_targets)))
    ftaxlstm_rmse = np.sqrt(np.mean((np.array(ftaxlstm_predictions) - np.array(ftaxlstm_targets)) ** 2))
    
    lstm_mae = np.mean(np.abs(np.array(lstm_predictions) - np.array(lstm_targets)))
    lstm_rmse = np.sqrt(np.mean((np.array(lstm_predictions) - np.array(lstm_targets)) ** 2))
    
    return {
        'ftaxlstm': {
            'mae': float(ftaxlstm_mae),
            'rmse': float(ftaxlstm_rmse),
            'predictions': ftaxlstm_predictions,
            'targets': ftaxlstm_targets
        },
        'lstm': {
            'mae': float(lstm_mae),
            'rmse': float(lstm_rmse),
            'predictions': lstm_predictions,
            'targets': lstm_targets
        }
    }


