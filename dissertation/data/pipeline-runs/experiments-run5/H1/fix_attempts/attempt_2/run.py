def synthesize_stock_data(num_stocks: int, num_days: int, market_name: str) -> np.ndarray:
    """
    Generate synthetic stock price data with realistic characteristics.
    
    This function creates synthetic stock market data that mimics real-world 
    behavior including trends, volatility, and correlations between different 
    stocks. The data includes realistic price movements with varying degrees 
    of correlation between stocks.
    
    Args:
        num_stocks: Number of stocks to generate
        num_days: Number of trading days to simulate
        market_name: Name of the market ('US' or 'Europe')
        
    Returns:
        Array of shape (num_stocks, num_days) containing synthetic stock prices
    """
    # Set random seed for reproducibility
    random.seed(RANDOM_SEED)
    np.random.seed(RANDOM_SEED)
    
    # Base trend for the market
    base_trend = np.linspace(100, 150, num_days)
    
    # Market-specific volatility
    if market_name == 'US':
        market_volatility = MARKET_VOLATILITY * 1.2
    else:  # Europe
        market_volatility = MARKET_VOLATILITY * 0.8
    
    # Generate correlated stock returns
    stock_returns = []
    
    for i in range(num_stocks):
        # Generate random walk with drift
        returns = np.random.normal(0, market_volatility, num_days)
        
        # Add some correlation between stocks
        if i > 0:
            # Correlate with previous stock
            prev_returns = stock_returns[-1]
            correlated_returns = MARKET_CORRELATION * prev_returns + \
                                (1 - MARKET_CORRELATION**2)**0.5 * returns
            returns = correlated_returns
        
        # Add trend component
        trend_component = np.sin(np.linspace(0, 4*np.pi, num_days)) * 0.02
        returns += trend_component
        
        stock_returns.append(returns)
    
    # Convert returns to prices
    prices = []
    for stock_return in stock_returns:
        # Start with base price
        price_series = [base_trend[0]]
        for i in range(1, len(stock_return)):
            # Geometric Brownian motion
            new_price = price_series[-1] * np.exp(stock_return[i])
            price_series.append(new_price)
        prices.append(np.array(price_series))
    
    return np.array(prices)


