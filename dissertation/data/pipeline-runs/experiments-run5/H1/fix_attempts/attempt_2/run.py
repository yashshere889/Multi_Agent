class FTA_XLSTM(nn.Module):
    """
    Frequency-Domain Temporal Attention-XLSTM model.
    
    This model incorporates Discrete Cosine Transform (DCT) to extract 
    frequency-domain features and uses temporal attention mechanisms 
    to improve stock price forecasting performance.
    """
    def __init__(self, input_size: int, hidden_size: int, num_layers: int, dropout: float):
        super(FTA_XLSTM, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.dropout = dropout
        
        # DCT Layer (simulated as a linear transformation for simplicity)
        self.dct_layer = nn.Linear(input_size, input_size)
        
        # LSTM layers
        self.lstm = nn.LSTM(
            input_size=input_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0
        )
        
        # Attention mechanism
        self.attention = nn.Linear(hidden_size, 1)
        
        # Output layer
        self.fc = nn.Linear(hidden_size, 1)
        
    def forward(self, x):
        # Apply DCT-like transformation (using linear layer as approximation)
        x = self.dct_layer(x)
        
        # Reshape for LSTM (batch_size, sequence_length, input_size)
        batch_size = x.size(0)
        x = x.view(batch_size, -1, self.input_size)
        
        # LSTM forward pass
        lstm_out, _ = self.lstm(x)
        
        # Apply attention mechanism
        attention_weights = torch.softmax(self.attention(lstm_out), dim=1)
        context_vector = torch.sum(attention_weights * lstm_out, dim=1)
        
        # Final prediction
        output = self.fc(context_vector)
        
        return output

class LSTM(nn.Module):
    """
    Standard LSTM model for comparison.
    
    This is a standard recurrent neural network architecture designed to 
    capture sequential patterns in time-series data.
    """
    def __init__(self, input_size: int, hidden_size: int, num_layers: int, dropout: float):
        super(LSTM, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.dropout = dropout
        
        # LSTM layers
        self.lstm = nn.LSTM(
            input_size=input_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0
        )
        
        # Output layer
        self.fc = nn.Linear(hidden_size, 1)
        
    def forward(self, x):
        # Reshape for LSTM (batch_size, sequence_length, input_size)
        batch_size = x.size(0)
        x = x.view(batch_size, -1, self.input_size)
        
        # LSTM forward pass
        lstm_out, _ = self.lstm(x)
        
        # Use the last time step's output
        output = self.fc(lstm_out[:, -1, :])
        
        return output


