def run_experiment(data, models):
    """
    Run the comparative benchmark experiment between time-domain and FFT models.
    
    Args:
        data: Preprocessed data from load_data()
        models: Tuple of (baseline_model, fft_model)
        
    Returns:
        dict containing predictions and model information
    """
    baseline_model, fft_model = models
    
    # Train baseline model
    baseline_history = baseline_model.fit(
        data['X_train'], data['y_train'],
        validation_data=(data['X_val'], data['y_val']),
        epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        verbose=0
    )
    
    # Train FFT model
    fft_history = fft_model.fit(
        data['X_train'], data['y_train'],
        validation_data=(data['X_val'], data['y_val']),
        epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        verbose=0
    )
    
    # Make predictions
    baseline_pred = baseline_model.predict(data['X_test'])
    fft_pred = fft_model.predict(data['X_test'])
    
    # Get actual values
    y_test = data['y_test']
    
    return {
        'baseline_predictions': baseline_pred.flatten().tolist(),
        'fft_predictions': fft_pred.flatten().tolist(),
        'actual_values': y_test.tolist(),
        'baseline_history': baseline_history.history,
        'fft_history': fft_history.history
    }


