def build_model():
    """
    Build two LSTM models:
    1. Baseline model using only time-domain features
    2. Model with FFT-based frequency-domain features
    
    Returns:
        tuple: (baseline_model, fft_model)
    """
    # Define baseline model (time-domain only)
    baseline_model = Sequential([
        LSTM(50, return_sequences=True, input_shape=(LOOKBACK_WINDOW, 5)),
        LSTM(50),
        Dense(1)
    ])
    
    baseline_model.compile(
        optimizer=Adam(learning_rate=LEARNING_RATE),
        loss='mse',
        metrics=['mae']
    )
    
    # Define FFT model (time-domain + frequency-domain features)
    # Note: For simplicity, we'll use the same architecture but with modified input shape
    # In practice, this would involve more complex feature engineering
    fft_model = Sequential([
        LSTM(50, return_sequences=True, input_shape=(LOOKBACK_WINDOW, 5)),
        LSTM(50),
        Dense(1)
    ])
    
    fft_model.compile(
        optimizer=Adam(learning_rate=LEARNING_RATE),
        loss='mse',
        metrics=['mae']
    )
    
    return (baseline_model, fft_model)


