def evaluate(experiment_output):
    """
    Evaluate model performance using MAE, RMSE, and Directional Accuracy.
    
    Args:
        experiment_output: Dictionary from run_experiment
        
    Returns:
        dict with metrics and success criteria evaluation
    """
    baseline_pred = np.array(experiment_output['baseline_predictions'])
    fft_pred = np.array(experiment_output['fft_predictions'])
    actual_values = np.array(experiment_output['actual_values'])
    
    # Calculate MAE
    baseline_mae = np.mean(np.abs(baseline_pred - actual_values))
    fft_mae = np.mean(np.abs(fft_pred - actual_values))
    
    # Calculate RMSE
    baseline_rmse = np.sqrt(np.mean((baseline_pred - actual_values) ** 2))
    fft_rmse = np.sqrt(np.mean((fft_pred - actual_values) ** 2))
    
    # Calculate Directional Accuracy
    def directional_accuracy(pred, actual):
        pred_direction = np.diff(pred) > 0
        actual_direction = np.diff(actual) > 0
        return np.mean(pred_direction == actual_direction)
    
    baseline_da = directional_accuracy(baseline_pred, actual_values)
    fft_da = directional_accuracy(fft_pred, actual_values)
    
    # Compare to baseline
    mae_improvement = baseline_mae - fft_mae
    rmse_improvement = baseline_rmse - fft_rmse
    da_improvement = fft_da - baseline_da
    
    # Simple statistical test (t-test approximation)
    # We'll consider significant improvement if improvement is > 10% of baseline
    mae_significant = abs(mae_improvement) > 0.1 * baseline_mae
    rmse_significant = abs(rmse_improvement) > 0.1 * baseline_rmse
    da_significant = abs(da_improvement) > 0.1 * baseline_da
    
    # Determine success
    meets_success_criteria = (
        mae_significant and 
        rmse_significant and 
        da_significant
    )
    
    # Prepare results
    results = {
        'baseline_mae': float(baseline_mae),
        'fft_mae': float(fft_mae),
        'baseline_rmse': float(baseline_rmse),
        'fft_rmse': float(fft_rmse),
        'baseline_da': float(baseline_da),
        'fft_da': float(fft_da),
        'meets_success_criteria': meets_success_criteria,
        'success_notes': f"Baseline MAE: {baseline_mae:.4f}, FFT MAE: {fft_mae:.4f}. "
                         f"Baseline RMSE: {baseline_rmse:.4f}, FFT RMSE: {fft_rmse:.4f}. "
                         f"Baseline DA: {baseline_da:.4f}, FFT DA: {fft_da:.4f}. "
                         f"Improvements: MAE={mae_improvement:.4f}, RMSE={rmse_improvement:.4f}, DA={da_improvement:.4f}."
    }
    
    return results


