def load_data():
    """
    Generate synthetic S&P 500-like historical stock data.
    
    This function creates realistic-looking synthetic stock price data 
    with trends, seasonality, and noise that mimics real financial markets.
    It generates log returns and applies rolling window features to simulate
    real-world preprocessing steps.
    """
    np.random.seed(RANDOM_SEED)
    
    # Generate synthetic time series data resembling S&P 500
    dates = pd.date_range(start='2000-01-01', periods=DATA_LENGTH, freq='D')
    
    # Create trend component
    trend = np.linspace(1000, 1500, DATA_LENGTH)
    
    # Create seasonal component (annual cycle)
    seasonal = 50 * np.sin(2 * np.pi * np.arange(DATA_LENGTH) / 252)
    
    # Create noise component
    noise = np.random.normal(0, 20, DATA_LENGTH)
    
    # Combine components to create base price
    base_price = trend + seasonal + noise
    
    # Ensure positive prices
    base_price = np.maximum(base_price, 100)
    
    # Generate log returns
    log_returns = np.diff(np.log(base_price), prepend=np.log(base_price[0]))
    
    # Create DataFrame
    df = pd.DataFrame({
        'date': dates,
        'price': base_price,
        'log_return': log_returns
    })
    
    # Apply rolling window features
    df['ma_30'] = df['price'].rolling(window=30).mean()
    df['ma_60'] = df['price'].rolling(window=60).mean()
    df['volatility'] = df['log_return'].rolling(window=30).std()
    
    # Forward-fill NaN values
    df = df.fillna(method='bfill')
    
    # Normalize features
    scaler = MinMaxScaler(feature_range=(0, 1))
    features = ['price', 'log_return', 'ma_30', 'ma_60', 'volatility']
    df_scaled = df.copy()
    df_scaled[features] = scaler.fit_transform(df[features])
    
    # Prepare data for LSTM
    data = df_scaled[features].values
    
    # Split data
    train_size = int(len(data) * TRAIN_SPLIT)
    val_size = int(len(data) * VALIDATION_SPLIT)
    
    train_data = data[:train_size]
    val_data = data[train_size:train_size + val_size]
    test_data = data[train_size + val_size:]
    
    # Create sequences for LSTM
    def create_sequences(data, lookback_window):
        X, y = [], []
        for i in range(lookback_window, len(data)):
            X.append(data[i-lookback_window:i])
            y.append(data[i, 0])  # Predict price
        return np.array(X), np.array(y)
    
    X_train, y_train = create_sequences(train_data, LOOKBACK_WINDOW)
    X_val, y_val = create_sequences(val_data, LOOKBACK_WINDOW)
    X_test, y_test = create_sequences(test_data, LOOKBACK_WINDOW)
    
    # Reshape for LSTM input (samples, time steps, features)
    X_train = X_train.reshape((X_train.shape[0], X_train.shape[1], len(features)))
    X_val = X_val.reshape((X_val.shape[0], X_val.shape[1], len(features)))
    X_test = X_test.reshape((X_test.shape[0], X_test.shape[1], len(features)))
    
    return {
        'X_train': X_train,
        'y_train': y_train,
        'X_val': X_val,
        'y_val': y_val,
        'X_test': X_test,
        'y_test': y_test,
        'scaler': scaler,
        'features': features
    }


