class LSTMModel(nn.Module):
    def __init__(self, input_size, hidden_dim, num_layers):
        super(LSTMModel, self).__init__()
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers
        
        self.lstm = nn.LSTM(input_size, hidden_dim, num_layers, batch_first=True)
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        h0 = torch.zeros(self.num_layers, x.size(0), self.hidden_dim).to(x.device)
        c0 = torch.zeros(self.num_layers, x.size(0), self.hidden_dim).to(x.device)
        
        out, _ = self.lstm(x, (h0, c0))
        out = self.fc(out[:, -1, :])
        return out

class FTA_XLSTM_Model(nn.Module):
    def __init__(self, input_size, hidden_dim, num_layers, adj_matrix):
        super(FTA_XLSTM_Model, self).__init__()
        self.input_size = input_size
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers
        self.adj_matrix = adj_matrix
        
        # DCT layer
        self.dct_layer = DCTLayer()
        
        # Graph convolution layers
        self.graph_conv1 = GCNConv(input_size, hidden_dim)
        self.graph_conv2 = GCNConv(hidden_dim, hidden_dim)
        
        # LSTM layers
        self.lstm = nn.LSTM(input_size, hidden_dim, num_layers, batch_first=True)
        
        # Output layer
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        # Apply DCT to transform to frequency domain
        x_dct = self.dct_layer(x)
        
        # Apply graph convolutions
        if self.adj_matrix is not None:
            edge_index = self.adj_matrix.nonzero().t().contiguous()
            x_gcn = self.graph_conv1(x_dct, edge_index)
            x_gcn = torch.relu(x_gcn)
            x_gcn = self.graph_conv2(x_gcn, edge_index)
            x_gcn = torch.relu(x_gcn)
        else:
            x_gcn = x_dct
            
        # Reshape for LSTM
        x_lstm = x_gcn.view(x_gcn.size(0), -1, self.input_size)
        
        # Apply LSTM
        h0 = torch.zeros(self.num_layers, x_lstm.size(0), self.hidden_dim).to(x_lstm.device)
        c0 = torch.zeros(self.num_layers, x_lstm.size(0), self.hidden_dim).to(x_lstm.device)
        
        out, _ = self.lstm(x_lstm, (h0, c0))
        out = self.fc(out[:, -1, :])
        return out

class DCTLayer(nn.Module):
    def __init__(self):
        super(DCTLayer, self).__init__()
        
    def forward(self, x):
        # Apply DCT along the sequence dimension
        # x shape: (batch_size, seq_length)
        batch_size, seq_length = x.shape
        x_dct = torch.zeros_like(x)
        
        for i in range(batch_size):
            x_dct[i] = torch.from_numpy(dct(x[i].numpy(), type=2, norm='ortho'))
            
        return x_dct


