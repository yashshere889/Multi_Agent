def evaluate(experiment_output):
    """Evaluate model performance using MAE and RMSE."""
    y_true = experiment_output['y_test_actual']
    lstm_pred = experiment_output['lstm_predictions']
    fta_xlstm_pred = experiment_output['fta_xlstm_predictions']
    
    # Calculate metrics
    def mae(y_true, y_pred):
        return np.mean(np.abs(y_true - y_pred))
    
    def rmse(y_true, y_pred):
        return np.sqrt(np.mean((y_true - y_pred) ** 2))
    
    lstm_mae = mae(y_true, lstm_pred)
    lstm_rmse = rmse(y_true, lstm_pred)
    
    fta_xlstm_mae = mae(y_true, fta_xlstm_pred)
    fta_xlstm_rmse = rmse(y_true, fta_xlstm_pred)
    
    # Determine if hypothesis is supported
    meets_success_criteria = False
    success_notes = ""
    
    if fta_xlstm_mae < lstm_mae and fta_xlstm_rmse < lstm_rmse:
        meets_success_criteria = True
        success_notes = "FTA-XLSTM achieved lower MAE and RMSE than LSTM, supporting the hypothesis."
    elif fta_xlstm_mae >= lstm_mae or fta_xlstm_rmse >= lstm_rmse:
        meets_success_criteria = False
        success_notes = "FTA-XLSTM did not achieve lower MAE and RMSE than LSTM, refuting the hypothesis."
    else:
        meets_success_criteria = "unknown"
        success_notes = "Could not determine success due to insufficient data or computation issues."
    
    return {
        "lstm_mae": float(lstm_mae),
        "lstm_rmse": float(lstm_rmse),
        "fta_xlstm_mae": float(fta_xlstm_mae),
        "fta_xlstm_rmse": float(fta_xlstm_rmse),
        "meets_success_criteria": meets_success_criteria,
        "success_notes": success_notes
    }


