def run_experiment(data, model):
    """Run the comparative benchmark experiment."""
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    logger.info(f"Using device: {device}")
    
    # Move models to device
    lstm_model = model['lstm'].to(device)
    fta_xlstm_model = model['fta_xlstm'].to(device)
    
    # Prepare data loaders
    train_dataset = TensorDataset(data['X_train'], data['y_train'])
    train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True)
    
    # Set up optimizers
    lstm_optimizer = torch.optim.Adam(lstm_model.parameters(), lr=LEARNING_RATE)
    fta_xlstm_optimizer = torch.optim.Adam(fta_xlstm_model.parameters(), lr=LEARNING_RATE)
    
    # Loss function
    criterion = nn.MSELoss()
    
    # Train LSTM model
    logger.info("Training LSTM model...")
    lstm_model.train()
    for epoch in range(EPOCHS):
        total_loss = 0
        for batch_x, batch_y in train_loader:
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)
            batch_x = batch_x.unsqueeze(-1)  # Add feature dimension
            
            lstm_optimizer.zero_grad()
            outputs = lstm_model(batch_x)
            loss = criterion(outputs.squeeze(), batch_y)
            loss.backward()
            lstm_optimizer.step()
            total_loss += loss.item()
        if (epoch + 1) % 10 == 0:
            logger.info(f"LSTM Epoch [{epoch+1}/{EPOCHS}], Loss: {total_loss/len(train_loader):.4f}")
    
    # Train FTA-XLSTM model
    logger.info("Training FTA-XLSTM model...")
    fta_xlstm_model.train()
    # Set adjacency matrix for FTA-XLSTM
    fta_xlstm_model.adj_matrix = data['adj_matrix']
    
    for epoch in range(EPOCHS):
        total_loss = 0
        for batch_x, batch_y in train_loader:
            batch_x, batch_y = batch_x.to(device), batch_y.to(device)
            
            fta_xlstm_optimizer.zero_grad()
            outputs = fta_xlstm_model(batch_x)
            loss = criterion(outputs.squeeze(), batch_y)
            loss.backward()
            fta_xlstm_optimizer.step()
            total_loss += loss.item()
        if (epoch + 1) % 10 == 0:
            logger.info(f"FTA-XLSTM Epoch [{epoch+1}/{EPOCHS}], Loss: {total_loss/len(train_loader):.4f}")
    
    # Evaluate models
    lstm_model.eval()
    fta_xlstm_model.eval()
    
    with torch.no_grad():
        # Get predictions for LSTM
        X_test = data['X_test'].unsqueeze(-1).to(device)
