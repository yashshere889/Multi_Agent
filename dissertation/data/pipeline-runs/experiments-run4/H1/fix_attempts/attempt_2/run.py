def create_sequences(data: torch.Tensor, seq_length: int, forecast_horizon: int) -> Tuple[torch.Tensor, torch.Tensor]:
    """Create sequences for training."""
    X, y = [], []
    for i in range(len(data) - seq_length - forecast_horizon + 1):
        X.append(data[i:(i + seq_length)])
        y.append(data[i + seq_length:i + seq_length + forecast_horizon, 0])  # Predict first feature
    return torch.stack(X), torch.stack(y).squeeze()

def run_experiment(data: Any, model: Any) -> dict[str, Any]:
    """Run the experiment with given data and model."""
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model.to(device)
    
    # Split data
    train_size = int(len(data) * TRAIN_SPLIT)
    val_size = int(len(data) * VALIDATION_SPLIT)
    
    train_data = data[:train_size]
    val_data = data[train_size:train_size + val_size]
    test_data = data[train_size + val_size:]
    
    # Create sequences
    X_train, y_train = create_sequences(train_data, SEQUENCE_LENGTH, FORECAST_HORIZON)
    X_val, y_val = create_sequences(val_data, SEQUENCE_LENGTH, FORECAST_HORIZON)
    X_test, y_test = create_sequences(test_data, SEQUENCE_LENGTH, FORECAST_HORIZON)
    
    # Create data loaders
    train_loader = DataLoader(TensorDataset(X_train, y_train), batch_size=BATCH_SIZE, shuffle=True)
    val_loader = DataLoader(TensorDataset(X_val, y_val), batch_size=BATCH_SIZE, shuffle=False)
    test_loader = DataLoader(TensorDataset(X_test, y_test), batch_size=BATCH_SIZE, shuffle=False)
    
    # Initialize optimizer
    optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)
    
    # Training loop
    model.train()
    for epoch in range(NUM_EPOCHS):
        total_loss = 0
        for batch_X, batch_y in train_loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            optimizer.zero_grad()
            outputs = model(batch_X)
            loss = nn.MSELoss()(outputs.squeeze(), batch_y)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
    
    # Evaluation
    model.eval()
    all_preds = []
    all_targets = []
    
    with torch.no_grad():
        for batch_X, batch_y in test_loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            outputs = model(batch_X)
            all_preds.extend(outputs.cpu().numpy())
            all_targets.extend(batch_y.cpu().numpy())
    
    return {
        "predictions": np.array(all_preds),
        "targets": np.array(all_targets),
        "model": model
    }


