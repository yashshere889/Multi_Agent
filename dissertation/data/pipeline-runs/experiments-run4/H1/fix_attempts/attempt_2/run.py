class LSTMModel(nn.Module):
    def __init__(self, input_size: int, hidden_dim: int, num_layers: int, dropout: float):
        super(LSTMModel, self).__init__()
        self.lstm = nn.LSTM(input_size, hidden_dim, num_layers, batch_first=True, dropout=dropout)
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        lstm_out, _ = self.lstm(x)
        output = self.fc(lstm_out[:, -1, :])
        return output

class FTA_XLSTM(nn.Module):
    def __init__(self, input_size: int, embedding_dim: int, hidden_dim: int, num_layers: int, dropout: float):
        super(FTA_XLSTM, self).__init__()
        self.embedding = nn.Linear(input_size, embedding_dim)
        self.lstm = nn.LSTM(embedding_dim, hidden_dim, num_layers, batch_first=True, dropout=dropout)
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        # Apply DCT transformation
        x_dct = torch.zeros_like(x)
        for i in range(x.size(0)):
            for j in range(x.size(2)):
                x_dct[i, :, j] = torch.tensor(dct(x[i, :, j].numpy(), type=2, norm='ortho'))
        
        # Embedding layer
        embedded = self.embedding(x_dct)
        
        # LSTM layer
        lstm_out, _ = self.lstm(embedded)
        
        # Final prediction
        output = self.fc(lstm_out[:, -1, :])
        return output

def build_model(model_type: str, input_size: int) -> Any:
    """Build either LSTM or FTA-XLSTM model based on model_type."""
    if model_type == "lstm":
        model = LSTMModel(
            input_size=input_size,
            hidden_dim=HIDDEN_DIM,
            num_layers=NUM_LAYERS,
            dropout=DROPOUT
        )
    elif model_type == "fta_xlstm":
        model = FTA_XLSTM(
            input_size=input_size,
            embedding_dim=EMBEDDING_DIM,
            hidden_dim=HIDDEN_DIM,
            num_layers=NUM_LAYERS,
            dropout=DROPOUT
        )
    else:
        raise ValueError("Invalid model type. Choose 'lstm' or 'fta_xlstm'")
    
    return model


