def synthesize_stock_data(n_samples: int = 1000, n_features: int = 10) -> pd.DataFrame:
    """
    Synthesize realistic stock price data for experimentation.
    
    This function generates synthetic stock price data that mimics real-world 
    financial time series characteristics such as trends, seasonality, and 
    autocorrelation. It is used as a surrogate for public datasets like Yahoo Finance.
    
    Parameters:
        n_samples (int): Number of time samples to generate.
        n_features (int): Number of simulated stocks/series.
        
    Returns:
        pd.DataFrame: DataFrame containing synthetic stock prices.
    """
    np.random.seed(42)
    dates = pd.date_range(start='2020-01-01', periods=n_samples, freq='D')
    
    # Generate base trend and noise
    trend = np.linspace(100, 200, n_samples)
    noise = np.random.normal(0, 5, (n_samples, n_features))
    
    # Create correlated features with some shared patterns
    base_series = trend[:, None] + noise
    
    # Add some cyclic behavior to simulate market cycles
    cycle = 10 * np.sin(np.linspace(0, 4*np.pi, n_samples))[:, None]
    base_series += cycle
    
    # Ensure positive values for stock prices
    base_series = np.abs(base_series) + 1
    
    df = pd.DataFrame(base_series, columns=[f'stock_{i}' for i in range(n_features)])
    df['date'] = dates
    df.set_index('date', inplace=True)
    
    return df

