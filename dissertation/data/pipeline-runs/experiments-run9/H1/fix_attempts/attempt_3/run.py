def build_model(model_type: str, input_dim: int, hidden_dim: int = HIDDEN_DIM, 
                num_layers: int = NUM_LAYERS, dropout: float = DROPOUT) -> Any:
    """
    Build a model based on the specified model type.
    
    Args:
        model_type: Type of model to build ('lstm', 'gru', 'dct_gnn')
        input_dim: Dimension of input features
        hidden_dim: Hidden dimension size
        num_layers: Number of layers
        dropout: Dropout rate
        
    Returns:
        Built model instance
    """
    if model_type == 'lstm':
        return LSTMModel(input_dim, hidden_dim, num_layers, dropout)
    elif model_type == 'gru':
        return GRUModel(input_dim, hidden_dim, num_layers, dropout)
    elif model_type == 'dct_gnn':
        return DCT_GNN_Model(input_dim, hidden_dim, dropout)
    else:
        raise ValueError(f"Unknown model type: {model_type}")

class LSTMModel(nn.Module):
    def __init__(self, input_dim: int, hidden_dim: int, num_layers: int, dropout: float):
        super(LSTMModel, self).__init__()
        self.lstm = nn.LSTM(input_dim, hidden_dim, num_layers, batch_first=True, dropout=dropout)
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        lstm_out, _ = self.lstm(x)
        output = self.fc(lstm_out[:, -1, :])
        return output

class GRUModel(nn.Module):
    def __init__(self, input_dim: int, hidden_dim: int, num_layers: int, dropout: float):
        super(GRUModel, self).__init__()
        self.gru = nn.GRU(input_dim, hidden_dim, num_layers, batch_first=True, dropout=dropout)
        self.fc = nn.Linear(hidden_dim, 1)
        
    def forward(self, x):
        gru_out, _ = self.gru(x)
        output = self.fc(gru_out[:, -1, :])
        return output

class DCT_GNN_Model(nn.Module):
    def __init__(self, input_dim: int, hidden_dim: int, dropout: float):
        super(DCT_GNN_Model, self).__init__()
        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        
        # DCT feature extractor
        self.dct_layer = nn.Linear(input_dim, hidden_dim)
        
        # GNN layer
        self.gnn_conv = GCNConv(hidden_dim, hidden_dim)
        self.dropout = nn.Dropout(dropout)
        
        # Output layer
        self.output_layer = nn.Linear(hidden_dim, 1)
        
    def forward(self, x, edge_index):
        # Apply DCT transformation
        x = self.dct_layer(x)
        
        # Apply GNN
        x = self.gnn_conv(x, edge_index)
        x = self.dropout(torch.relu(x))
        
        # Global pooling (mean)
        x = x.mean(dim=0, keepdim=True)
        
        # Output layer
        output = self.output_layer(x)
        return output


