def synthesize_stock_data(num_rows: int) -> pd.DataFrame:
    """
    Synthesize realistic stock price data for testing purposes.
    
    Args:
        num_rows: Number of rows to generate
        
    Returns:
        DataFrame with synthetic stock data
    """
    # Create synthetic timestamps
    start_date = datetime(2020, 1, 1)
    timestamps = pd.date_range(start=start_date, periods=num_rows, freq='1min')
    
    # Generate synthetic OHLCV data with realistic ranges and correlations
    np.random.seed(RANDOM_SEED)
    
    # Base prices with some trend and volatility
    base_prices = 100 + np.cumsum(np.random.randn(num_rows) * 0.5)
    
    # Generate correlated OHLC data
    opens = base_prices + np.random.randn(num_rows) * 2
    highs = np.maximum(opens, opens + np.abs(np.random.randn(num_rows) * 3))
    lows = np.minimum(opens, opens - np.abs(np.random.randn(num_rows) * 3))
    closes = opens + np.random.randn(num_rows) * 2
    
    # Generate realistic volumes
    volumes = np.random.lognormal(10, 1, num_rows) * 1000
    
    # Create DataFrame
    df = pd.DataFrame({
        'timestamp': timestamps,
        'open': opens,
        'high': highs,
        'low': lows,
        'close': closes,
        'volume': volumes.astype(int),
        'ticker': 'SYNTH'  # Synthetic ticker
    })
    
    return df


