class SCINet(nn.Module):
    """
    Sample Convolution Network (SCINet) for time series forecasting.
    Reused from literature: https://arxiv.org/abs/2007.02835
    """
    def __init__(self, input_size, hidden_size, num_layers, kernel_size, dropout=0.2):
        super(SCINet, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.kernel_size = kernel_size
        
        # Sample convolution layer
        self.conv1d = nn.Conv1d(input_size, hidden_size, kernel_size, padding=kernel_size//2)
        
        # LSTM layers
        self.lstm_layers = nn.ModuleList([
            nn.LSTM(hidden_size, hidden_size, batch_first=True) for _ in range(num_layers)
        ])
        
        # Dropout layer
        self.dropout = nn.Dropout(dropout)
        
        # Output layer
        self.fc = nn.Linear(hidden_size, 1)
        
    def forward(self, x):
        # x shape: (batch_size, seq_len, input_size)
        batch_size, seq_len, _ = x.size()
        
        # Apply sample convolution
        x = x.transpose(1, 2)  # (batch_size, input_size, seq_len)
        x = self.conv1d(x)
        x = x.transpose(1, 2)  # (batch_size, seq_len, hidden_size)
        
        # Apply LSTM layers
        for lstm in self.lstm_layers:
            x, _ = lstm(x)
            
        # Apply dropout
        x = self.dropout(x)
        
        # Output layer
        x = self.fc(x[:, -1, :])  # Take last time step
        return x

def build_model(model_type: str) -> Any:
    """Build model based on type."""
    if model_type == 'scinet':
        model = SCINet(
            input_size=SCINET_INPUT_SIZE,
            hidden_size=SCINET_HIDDEN_SIZE,
            num_layers=SCINET_NUM_LAYERS,
            kernel_size=SCINET_KERNEL_SIZE,
            dropout=SCINET_DROPOUT
        )
        return model
    elif model_type == 'lstm':
        model = nn.Sequential(
            nn.LSTM(input_size=1, hidden_size=LSTM_UNITS[0], num_layers=LSTM_LAYERS, batch_first=True),
            nn.Dropout(SCINET_DROPOUT),
            nn.LSTM(input_size=LSTM_UNITS[0], hidden_size=LSTM_UNITS[1], num_layers=1, batch_first=True),
            nn.Dropout(SCINET_DROPOUT),
            nn.Linear(LSTM_UNITS[1], 1)
        )
        return model
    elif model_type == 'arima':
        return None  # ARIMA is handled separately
    else:
        raise ValueError(f"Unknown model type: {model_type}")


