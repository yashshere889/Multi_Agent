def synthesize_stock_data(n_days: int = 1250) -> pd.DataFrame:
    """
    Synthesize realistic stock price data for experimentation.
    
    This function generates synthetic daily stock price data with realistic 
    characteristics including trends, seasonality, and volatility clustering.
    It is used as a surrogate for real financial data since no external 
    datasets are available in this environment.
    
    Parameters:
        n_days (int): Number of days of data to generate (default: 1250 ~ 5 years)
        
    Returns:
        pd.DataFrame: DataFrame with DatetimeIndex and 'close' column containing 
                     synthetic stock prices
    """
    np.random.seed(RANDOM_SEED)
    dates = pd.date_range(start=TRAIN_START_DATE, periods=n_days, freq='D')
    
    # Generate trend component
    trend = np.linspace(100, 150, n_days)
    
    # Generate seasonal component (weekly pattern)
    seasonal = 5 * np.sin(2 * np.pi * np.arange(n_days) / 7)
    
    # Generate noise with volatility clustering (GARCH-like effect)
    noise = np.zeros(n_days)
    vol = 0.5
    for i in range(1, n_days):
        # Volatility clustering effect
        vol = 0.9 * vol + 0.1 * np.random.normal(0, 0.1)
        noise[i] = np.random.normal(0, abs(vol))
    
    # Combine components
    prices = trend + seasonal + noise
    
    # Ensure positive prices
    prices = np.maximum(prices, 10)
    
    df = pd.DataFrame({'close': prices}, index=dates)
    return df

def load_data() -> Any:
    """Load and preprocess stock price data."""
    # Generate synthetic data
    df = synthesize_stock_data()
    
    # Apply log transformation to reduce skewness
    df['log_close'] = np.log(df['close'])
    
    # Normalize price data using Min-Max scaling
    scaler = MinMaxScaler(feature_range=(0, 1))
    df['scaled_log_close'] = scaler.fit_transform(df[['log_close']])
    
    # Create lagged features for temporal dependencies
    for i in range(1, 6):  # Create lags 1 through 5
        df[f'lag_{i}'] = df['scaled_log_close'].shift(i)
    
    # Drop rows with NaN values from lagging
