def prepare_sequences(data: pd.DataFrame, sequence_length: int = 10) -> Tuple[np.ndarray, np.ndarray]:
    """Prepare sequences for training/testing."""
    X, y = [], []
    for i in range(sequence_length, len(data)):
        X.append(data.iloc[i-sequence_length:i].values)
        y.append(data.iloc[i]['scaled_log_close'])
    return np.array(X), np.array(y)

def train_lstm(model, train_loader, epochs: int = 50):
    """Train LSTM model."""
    criterion = nn.MSELoss()
    optimizer = optim.Adam(model.parameters(), lr=0.001)
    
    model.train()
    for epoch in range(epochs):
        total_loss = 0
        for batch_x, batch_y in train_loader:
            optimizer.zero_grad()
            outputs = model(batch_x.float())
            loss = criterion(outputs.squeeze(), batch_y.float())
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
        if epoch % 10 == 0:
            print(f"LSTM Epoch [{epoch}/{epochs}], Loss: {total_loss/len(train_loader):.4f}")

