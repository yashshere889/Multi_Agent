    # Split data chronologically
    train_df = df[(df.index >= TRAIN_START_DATE) & (df.index <= TRAIN_END_DATE)]
    val_df = df[df.index >= VALIDATION_DATE]
    
    return {
        'full_data': df,
        'train_data': train_df,
        'val_data': val_df,
        'scaler': scaler
    }


