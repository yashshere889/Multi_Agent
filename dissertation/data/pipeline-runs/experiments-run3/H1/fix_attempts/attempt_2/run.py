def calculate_metrics(actual: np.ndarray, predicted: np.ndarray) -> dict[str, float]:
    """Calculate evaluation metrics."""
    mae = mean_absolute_error(actual, predicted)
    rmse = np.sqrt(mean_squared_error(actual, predicted))
    
    # Directional accuracy
    actual_diff = np.diff(actual)
    pred_diff = np.diff(predicted)
    da = np.mean(np.sign(actual_diff) == np.sign(pred_diff))
    
    return {
        'mae': mae,
        'rmse': rmse,
        'da': da
    }

def evaluate(experiment_output: dict[str, Any]) -> dict[str, Any]:
    """Evaluate experiment results."""
    model_type = experiment_output['model_type']
    predictions = experiment_output['predictions']
    actual_values = experiment_output['actual_values']
    
    # Calculate metrics
    metrics = calculate_metrics(actual_values, predictions)
    
    return {
        'model_type': model_type,
        'metrics': metrics,
        'predictions': predictions,
        'actual_values': actual_values
    }


