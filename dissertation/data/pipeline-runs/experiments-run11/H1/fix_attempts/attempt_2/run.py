def synthesize_stock_data(n_rows):
    """
    Synthesize realistic stock price data for testing purposes.
    
    This function generates synthetic stock data that mimics real financial time series
    with realistic price movements, volatility patterns, and correlations between features.
    
    Args:
        n_rows: Number of rows to generate
        
    Returns:
        DataFrame with synthetic stock data
    """
    np.random.seed(RANDOM_SEED)
    
    # Generate timestamps
    start_date = datetime(2020, 1, 1)
    timestamps = [start_date + timedelta(minutes=i*5) for i in range(n_rows)]
    
    # Generate correlated features
    # Base price with trend and noise
    base_trend = np.linspace(100, 120, n_rows)
    noise = np.random.normal(0, 0.5, n_rows)
    close_prices = base_trend + noise
    
    # Generate other features with realistic correlations
    open_prices = close_prices * (1 + np.random.normal(0, 0.005, n_rows))
    high_prices = np.maximum(open_prices, close_prices) * (1 + np.abs(np.random.normal(0, 0.01, n_rows)))
    low_prices = np.minimum(open_prices, close_prices) * (1 - np.abs(np.random.normal(0, 0.01, n_rows)))
    
    # Volume follows price movement patterns
    volume = np.abs(close_prices - np.roll(close_prices, 1)) * 1000 + np.random.exponential(500, n_rows)
    volume = np.maximum(volume, 100)  # Ensure positive volume
    
    # Create DataFrame
    df = pd.DataFrame({
        'timestamp': timestamps,
        'open': open_prices,
        'high': high_prices,
        'low': low_prices,
        'close': close_prices,
        'volume': volume.astype(int),
        'trade_count': np.random.poisson(50, n_rows).astype(int),
        'vol_weighted_avg_price': (open_prices + high_prices + low_prices + close_prices) / 4,
        'ticker': ['AAPL'] * n_rows,
        'name': ['Apple Inc.'] * n_rows
    })
    
    return df


