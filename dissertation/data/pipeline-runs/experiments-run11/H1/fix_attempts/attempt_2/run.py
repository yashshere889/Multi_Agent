    arima_forecast = arima_forecast[:min_length]
    actual_values = actual_values[:min_length]
    
    # Calculate MAE
    lstm_mae = np.mean(np.abs(lstm_preds - actual_values))
    arima_mae = np.mean(np.abs(arima_forecast - actual_values))
    
    # Calculate RMSE
    lstm_rmse = np.sqrt(np.mean((lstm_preds - actual_values)**2))
    arima_rmse = np.sqrt(np.mean((arima_forecast - actual_values)**2))
    
    # Calculate Directional Accuracy
    def directional_accuracy(preds, actual):
        pred_direction = np.diff(preds) > 0
        actual_direction = np.diff(actual) > 0
        return np.mean(pred_direction == actual_direction)
    
    lstm_da = directional_accuracy(lstm_preds, actual_values)
    arima_da = directional_accuracy(arima_forecast, actual_values)
    
    # Determine if success criteria are met
    meets_success_criteria = False
    success_notes = ""
    
    if lstm_mae < arima_mae and lstm_rmse < arima_rmse:
        meets_success_criteria = True
        success_notes = "LSTM model with adaptive fusion achieved better forecasting accuracy (lower MAE and RMSE) than ARIMA baseline."
