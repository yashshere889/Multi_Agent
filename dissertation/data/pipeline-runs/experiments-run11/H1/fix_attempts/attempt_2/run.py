    arima_forecast = np.array(experiment_output['arima_forecast'])
    actual_values = np.array(experiment_output['actual_values'])
    
    # Ensure all arrays have the same length for comparison
    min_length = min(len(lstm_preds), len(arima_forecast), len(actual_values))
