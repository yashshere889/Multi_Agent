def evaluate(experiment_output):
    """
    Evaluate the experiment results against the baseline and success criteria.
    
    Args:
        experiment_output: Dictionary containing model predictions and actual values
        
    Returns:
        Dictionary with evaluation metrics and success criteria status
    """
    # Extract predictions and actual values
