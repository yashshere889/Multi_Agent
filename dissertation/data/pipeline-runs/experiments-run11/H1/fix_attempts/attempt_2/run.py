def run_experiment(data, model):
    """
    Run the experiment comparing ARIMA and LSTM models.
    
    Args:
        data: DataFrame with stock price data
        model: Keras LSTM model
    
    Returns:
        Dictionary containing experiment results
    """
    # Preprocess data
    scaler = MinMaxScaler(feature_range=(0, 1))
    
    # Use closing prices for modeling
    close_prices = data['close'].values.reshape(-1, 1)
    scaled_prices = scaler.fit_transform(close_prices)
    
    # Prepare features using rolling windows
    X, y = [], []
    for i in range(LOOKBACK_WINDOW, len(scaled_prices) - FORECAST_HORIZON + 1):
        X.append(scaled_prices[i-LOOKBACK_WINDOW:i])
        y.append(scaled_prices[i:i+FORECAST_HORIZON])
    
    X, y = np.array(X), np.array(y)
    X = np.reshape(X, (X.shape[0], X.shape[1], 1))
    
    # Split data into train/validation/test sets
    train_size = int(len(X) * 0.7)
    val_size = int(len(X) * 0.15)
    
    X_train, X_val, X_test = X[:train_size], X[train_size:train_size+val_size], X[train_size+val_size:]
    y_train, y_val, y_test = y[:train_size], y[train_size:train_size+val_size], y[train_size+val_size:]
    
    # Train LSTM model
    lstm_history = model.fit(
        X_train, y_train,
        batch_size=BATCH_SIZE,
        epochs=EPOCHS,
        validation_data=(X_val, y_val),
        verbose=0
    )
    
    # Make predictions
    lstm_predictions = model.predict(X_test)
    
    # Invert scaling for predictions
    # Create dummy array for inverse transform
    dummy_array = np.zeros((len(lstm_predictions), 1))
    dummy_array[:, 0] = lstm_predictions.flatten()
    lstm_predictions = scaler.inverse_transform(dummy_array)[:, 0]
    
    # Prepare ARIMA data
    arima_data = data['close'].values
    
    # Fit ARIMA model
    arima_model = ARIMA(arima_data[:train_size], order=(1,1,1))
    arima_fitted = arima_model.fit()
    
    # Forecast using ARIMA
    arima_forecast = arima_fitted.forecast(steps=len(y_test))
    
    # Calculate metrics
    results = {
        'lstm_predictions': lstm_predictions.tolist(),
        'arima_forecast': arima_forecast.tolist(),
        'actual_values': data['close'].iloc[train_size+val_size:].values.tolist(),
        'y_test': y_test.tolist()
    }
    
    return results


